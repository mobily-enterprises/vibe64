# Connected development for Bundler.
#
#   ruby tooling/connected.rb prepare <sourcesFile>
#   ruby tooling/connected.rb verify  <sourcesFile>
#
# prepare: writes an untracked derived Gemfile (Gemfile.connected) that
# evaluates the tracked Gemfile with `eval_gemfile`, replacing the source of
# each connected gem by `path: <sourceRoot>`. Bundler names the lock after the
# Gemfile (Gemfile.connected.lock); it starts as a copy of the tracked
# Gemfile.lock so every other gem keeps its locked version. The derived
# Gemfile is selected through the untracked local Bundler setting `gemfile` in
# .bundle/config, which every `bundle` command (including `bundle exec`)
# honours. A launch that does not go through `bundle` (plain
# `ruby -rbundler/setup`) must export BUNDLE_GEMFILE=Gemfile.connected itself.
# The tracked Gemfile and Gemfile.lock are never written.
#
# verify: proves, in a fresh `bundle exec` process with no BUNDLE_GEMFILE in
# the environment, that each connected gem is loaded from its sourceRoot.

require "json"
require "open3"

CONTRACT = "vibe64.connected-sources.v1"
TYPES = %w[bundler gem ruby].freeze
GEMFILE = "Gemfile"
DERIVED = "Gemfile.connected"
DERIVED_LOCK = "#{DERIVED}.lock"

def fail!(message)
  warn "connected: #{message}"
  exit 1
end

def connected_gems(sources_file)
  sources = JSON.parse(File.read(sources_file))
  fail! "#{sources_file} is not a #{CONTRACT} sources map" unless sources["contract"] == CONTRACT
  gems = sources.fetch("projects", []).filter_map do |project|
    next unless TYPES.include?(project.fetch("type", "bundler"))
    root = File.realpath(project.fetch("sourceRoot", ""))
    gemspecs = Dir[File.join(root, "*.gemspec")]
    fail! "connected source must have exactly one gemspec: #{root}" unless gemspecs.size == 1
    spec = Dir.chdir(root) { Gem::Specification.load(gemspecs.first) }
    fail! "cannot load #{gemspecs.first}" unless spec
    { "name" => spec.name, "root" => root }
  end
  fail! "#{sources_file} lists no Bundler gems" if gems.empty?
  gems
rescue Errno::ENOENT, JSON::ParserError => error
  fail! error.message
end

def derived_gemfile(gems)
  paths = gems.to_h { |gem| [gem["name"], gem["root"]] }
  <<~RUBY
    # Generated by tooling/connected.rb for connected development. Untracked.
    # Evaluates the tracked Gemfile, replacing each connected gem's source by
    # its local checkout.
    connected = #{paths.inspect}.freeze
    declared = []
    define_singleton_method(:gem) do |name, *args|
      path = connected[name]
      return super(name, *args) unless path
      declared << name
      options = args.last.is_a?(Hash) ? args.pop.dup : {}
      %i[git github gitlab bitbucket branch ref tag submodules glob source].each { |key| options.delete(key) }
      super(name, *args, options.merge(path: path))
    end
    eval_gemfile File.expand_path(#{GEMFILE.inspect}, __dir__)
    # A connected gem the app does not declare directly (a transitive
    # dependency) is still taken from its checkout.
    (connected.keys - declared).each { |name| gem name, path: connected[name] }
  RUBY
end

def run(env, *command)
  warn "+ #{(env.map { |key, value| "#{key}=#{value}" } + command).join(' ')}"
  system(env, *command) || fail!("#{command.join(' ')} failed")
end

def prepare(sources_file)
  gems = connected_gems(sources_file)
  content = derived_gemfile(gems)
  File.write(DERIVED, content) unless File.exist?(DERIVED) && File.read(DERIVED) == content
  # Start from the tracked lock so only the connected gems are re-resolved.
  File.write(DERIVED_LOCK, File.read("Gemfile.lock")) if File.exist?("Gemfile.lock")
  env = { "BUNDLE_GEMFILE" => File.expand_path(DERIVED) }
  run({}, "bundle", "config", "set", "--local", "gemfile", DERIVED)
  run(env, "bundle", "install", "--quiet")
end

PROBE = <<~'RUBY'
  name, root = ARGV
  require "bundler/setup"
  gemfile = File.basename(Bundler.default_gemfile.to_s)
  abort "the app's Bundler setup uses #{gemfile}, not Gemfile.connected" unless gemfile == "Gemfile.connected"
  spec = Gem.loaded_specs[name] or abort "#{name} is not in the bundle"
  abort "#{name} is not a path gem" unless spec.source.is_a?(Bundler::Source::Path)
  abort "#{name} loads from #{spec.full_gem_path}, not #{root}" unless File.realpath(spec.full_gem_path) == root
  before = $LOADED_FEATURES.dup
  require name
  loaded = ($LOADED_FEATURES - before).select { |file| File.realpath(file).start_with?(root + "/") }
  abort "requiring #{name} loaded nothing from #{root}" if loaded.empty?
  puts "verified #{name} #{spec.version} path -> #{root} (#{loaded.size} file(s) loaded)"
RUBY

def verify(sources_file)
  gems = connected_gems(sources_file)
  fail! "not prepared: run prepare first" unless File.exist?(DERIVED_LOCK)
  lock = File.read(DERIVED_LOCK)
  # Use the app's normal `bundle exec` launch: no BUNDLE_GEMFILE override.
  env = { "BUNDLE_GEMFILE" => nil, "RUBYOPT" => nil }
  gems.each do |gem|
    unless lock.include?("PATH\n  remote: #{gem['root']}\n")
      fail! "#{DERIVED_LOCK} does not lock #{gem['name']} to #{gem['root']}"
    end
    warn "+ bundle exec ruby -e <bundler probe> #{gem['name']} #{gem['root']}"
    system(env, "bundle", "exec", RbConfig.ruby, "-e", PROBE, gem["name"], gem["root"]) || fail!("#{gem['name']} is not connected")
  end
  status, = Open3.capture2("git", "status", "--porcelain", "--", GEMFILE, "Gemfile.lock")
  fail! "tracked Bundler files changed:\n#{status}" unless status.strip.empty?
end

command, sources_file = ARGV
fail! "usage: ruby #{$PROGRAM_NAME} prepare|verify <sourcesFile>" unless %w[prepare verify].include?(command) && sources_file
command == "prepare" ? prepare(sources_file) : verify(sources_file)
