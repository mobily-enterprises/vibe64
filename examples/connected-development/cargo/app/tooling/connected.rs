//! Wires connected Vibe64 repositories into this Cargo package with Cargo's
//! native mechanisms: `[patch]` in an untracked `.cargo/config.toml`, plus
//! `resolver.lockfile-path` (Cargo 1.97+) so the patched resolution is written
//! to an untracked lockfile instead of the tracked `Cargo.lock`.
//!
//!   sh tooling/connected.sh prepare <sourcesFile>
//!   sh tooling/connected.sh verify  <sourcesFile>
//!
//! Run from the package root. Never edits Cargo.toml or Cargo.lock.

use std::collections::hash_map::DefaultHasher;
use std::fs;
use std::hash::{Hash, Hasher};
use std::path::{Path, PathBuf};
use std::process::{exit, Command, Stdio};

const CONTRACT: &str = "vibe64.connected-sources.v1";
const PACK_TYPE: &str = "cargo";
const MARKER: &str = "# Generated by tooling/connected.sh prepare. Untracked; do not commit.";
const DERIVED_LOCK: &str = ".development/cargo/Cargo.lock";

struct Project {
    name: String,
    relationship: String,
    source_root: PathBuf,
    crate_name: String,
    crate_version: String,
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    if args.len() != 3 || (args[1] != "prepare" && args[1] != "verify") {
        eprintln!("usage: sh tooling/connected.sh prepare|verify <sourcesFile>");
        exit(2);
    }
    let result = if args[1] == "prepare" { prepare(&args[2]) } else { verify(&args[2]) };
    if let Err(e) = result {
        eprintln!("connected {}: {}", args[1], e);
        exit(1);
    }
}

type Res<T> = Result<T, String>;

fn app_root() -> Res<PathBuf> {
    let root = std::env::current_dir().map_err(|e| e.to_string())?;
    if !root.join("Cargo.toml").is_file() {
        return Err("run from the package root (no Cargo.toml here)".into());
    }
    Ok(root)
}

fn load(file: &str) -> Res<(String, String, Vec<Project>)> {
    let text = fs::read_to_string(file).map_err(|e| format!("{}: {}", file, e))?;
    let doc = Json::parse(&text).map_err(|e| format!("{}: {}", file, e))?;
    if doc.get("contract").and_then(Json::as_str) != Some(CONTRACT) {
        return Err(format!("{}: contract must be {}", file, CONTRACT));
    }
    let session = doc.get("sessionId").and_then(Json::as_str).unwrap_or("").to_string();
    let mut out: Vec<Project> = Vec::new();
    for (i, p) in doc.get("projects").and_then(Json::as_arr).ok_or("projects must be an array")?.iter().enumerate() {
        let field = |k: &str| p.get(k).and_then(Json::as_str).unwrap_or("").to_string();
        let name = field("name");
        let label = format!("projects[{}] {:?}", i, name);
        let kind = match field("type").as_str() { "" => PACK_TYPE.to_string(), t => t.to_string() };
        if kind != PACK_TYPE {
            eprintln!("connected: skipping {} of type {:?} (this script wires {:?} only)", label, kind, PACK_TYPE);
            continue;
        }
        let relationship = field("relationship");
        if relationship != "dependency" && relationship != "composition" {
            return Err(format!("{}: relationship {:?} must be dependency or composition", label, relationship));
        }
        let raw = PathBuf::from(field("sourceRoot"));
        if !raw.is_absolute() {
            return Err(format!("{}: sourceRoot {:?} must be absolute", label, raw));
        }
        let source_root = raw.canonicalize().map_err(|e| format!("{}: {}: {}", label, raw.display(), e))?;
        let (crate_name, crate_version) = read_package(&source_root.join("Cargo.toml"))
            .map_err(|e| format!("{}: {}", label, e))?;
        if out.iter().any(|o| o.crate_name == crate_name) {
            return Err(format!("{}: crate {} is connected twice", label, crate_name));
        }
        out.push(Project { name, relationship, source_root, crate_name, crate_version });
    }
    Ok((session, file.to_string(), out))
}

fn prepare(file: &str) -> Res<()> {
    let root = app_root()?;
    let (session, file, projects) = load(file)?;
    let config = root.join(".cargo/config.toml");
    check_owned(&config)?;
    let derived = root.join(DERIVED_LOCK);
    if projects.is_empty() {
        let _ = fs::remove_file(&config);
        let _ = fs::remove_file(&derived);
        println!("connected prepare: no cargo repositories connected; .cargo/config.toml removed");
        return Ok(());
    }
    // Which source each connected crate is declared from decides the [patch] table.
    let meta = cargo_json(&root, &["metadata", "--format-version", "1", "--no-deps"])?;
    let manifest = canon(&root.join("Cargo.toml"));
    let pkg = meta.get("packages").and_then(Json::as_arr).unwrap_or(&[]).iter()
        .find(|p| p.get("manifest_path").and_then(Json::as_str).map(|m| canon(Path::new(m))) == Some(manifest.clone()))
        .ok_or("cargo metadata did not report this package")?;
    let mut tables: Vec<(String, Vec<&Project>)> = Vec::new();
    for p in &projects {
        let dep = pkg.get("dependencies").and_then(Json::as_arr).unwrap_or(&[]).iter()
            .find(|d| d.get("name").and_then(Json::as_str) == Some(p.crate_name.as_str()))
            .ok_or_else(|| format!("{} ({}) is not a dependency in Cargo.toml", p.crate_name, p.name))?;
        let key = patch_key(dep.get("source").and_then(Json::as_str))
            .map_err(|e| format!("{}: {}", p.crate_name, e))?;
        match tables.iter_mut().find(|(k, _)| *k == key) {
            Some((_, list)) => list.push(p),
            None => tables.push((key, vec![p])),
        }
    }
    let mut text = format!("{}\n# Sources: {} (session {})\n\n[resolver]\nlockfile-path = {}\n",
        MARKER, file, session, toml_str(&derived.to_string_lossy()));
    for (key, list) in &tables {
        let header = if key == "crates-io" { key.clone() } else { toml_str(key) };
        text.push_str(&format!("\n[patch.{}]\n", header));
        for p in list {
            text.push_str(&format!("{} = {{ path = {} }} # {} {} ({})\n",
                toml_str(&p.crate_name), toml_str(&p.source_root.to_string_lossy()),
                p.crate_name, p.crate_version, p.relationship));
        }
    }
    fs::create_dir_all(root.join(".cargo")).map_err(|e| e.to_string())?;
    write_atomic(&config, &text)?;
    // Start every prepare from the tracked lock so the derived lock differs
    // only by the patched entries, then let Cargo apply the patch to it.
    fs::create_dir_all(derived.parent().unwrap()).map_err(|e| e.to_string())?;
    let tracked = root.join("Cargo.lock");
    if tracked.is_file() {
        fs::copy(&tracked, &derived).map_err(|e| e.to_string())?;
    } else {
        let _ = fs::remove_file(&derived);
    }
    cargo_json(&root, &["metadata", "--format-version", "1"])?;
    for p in &projects {
        println!("connected prepare: {} {} -> {} ({})", p.crate_name, p.crate_version, p.source_root.display(), p.relationship);
    }
    Ok(())
}

fn verify(file: &str) -> Res<()> {
    let root = app_root()?;
    let (_, _, projects) = load(file)?;
    if projects.is_empty() {
        println!("connected verify: no cargo repositories connected; nothing to prove");
        return Ok(());
    }
    let config = root.join(".cargo/config.toml");
    if !config.is_file() {
        return Err(".cargo/config.toml is missing; run prepare".into());
    }
    check_owned(&config)?;
    let before = digest(&root);
    let meta = cargo_json(&root, &["metadata", "--format-version", "1", "--locked"])?;
    if !root.join(DERIVED_LOCK).is_file() {
        return Err(format!("{} is missing: resolver.lockfile-path is not in effect", DERIVED_LOCK));
    }
    let resolve = meta.get("resolve").ok_or("cargo metadata has no resolve graph")?;
    let root_id = resolve.get("root").and_then(Json::as_str).ok_or("no root package")?;
    let nodes = resolve.get("nodes").and_then(Json::as_arr).unwrap_or(&[]);
    let root_deps: Vec<&str> = nodes.iter()
        .find(|n| n.get("id").and_then(Json::as_str) == Some(root_id))
        .and_then(|n| n.get("deps")).and_then(Json::as_arr).unwrap_or(&[]).iter()
        .filter_map(|d| d.get("pkg").and_then(Json::as_str)).collect();
    let packages = meta.get("packages").and_then(Json::as_arr).unwrap_or(&[]);
    for p in &projects {
        let want = canon(&p.source_root.join("Cargo.toml"));
        let same_name: Vec<&Json> = packages.iter()
            .filter(|k| k.get("name").and_then(Json::as_str) == Some(p.crate_name.as_str())).collect();
        let connected = same_name.iter().find(|k| {
            k.get("source").map_or(false, |s| matches!(s, Json::Null))
                && k.get("manifest_path").and_then(Json::as_str).map(|m| canon(Path::new(m))) == Some(want.clone())
        });
        let connected = connected.ok_or_else(|| format!(
            "{} is not resolved from the connected checkout {} (the patch is unused or the version does not match the requirement)",
            p.crate_name, p.source_root.display()))?;
        if same_name.len() != 1 {
            return Err(format!("{} also resolves from another source; the build is not using only the connected checkout", p.crate_name));
        }
        let id = connected.get("id").and_then(Json::as_str).unwrap_or("");
        if !root_deps.contains(&id) {
            return Err(format!("{} is connected but this package does not depend on it", p.crate_name));
        }
        println!("connected verify: {} {} resolves from {}", p.crate_name, p.crate_version, p.source_root.display());
    }
    run(&root, &["build", "--locked"])?;
    if digest(&root) != before {
        return Err("Cargo.toml or Cargo.lock changed while verifying the connected build".into());
    }
    println!("connected verify: cargo build --locked succeeded against {}; Cargo.toml and Cargo.lock unchanged", DERIVED_LOCK);
    Ok(())
}

fn patch_key(source: Option<&str>) -> Res<String> {
    match source {
        None => Err("already a path dependency; nothing to connect".into()),
        Some(s) if s == "registry+https://github.com/rust-lang/crates.io-index" || s == "sparse+https://index.crates.io/" => Ok("crates-io".into()),
        Some(s) if s.starts_with("git+") => Ok(s[4..].split(|c| c == '?' || c == '#').next().unwrap().to_string()),
        Some(s) => Err(format!("dependencies from {} are not supported by this script", s)),
    }
}

fn check_owned(config: &Path) -> Res<()> {
    match fs::read_to_string(config) {
        Ok(t) if t.lines().next() == Some(MARKER) => Ok(()),
        Ok(_) => Err(format!("{} exists and was not generated by this script; refusing to replace it", config.display())),
        Err(_) => Ok(()),
    }
}

fn read_package(manifest: &Path) -> Res<(String, String)> {
    let text = fs::read_to_string(manifest).map_err(|e| format!("{}: {}", manifest.display(), e))?;
    let (mut in_pkg, mut name, mut version) = (false, None, None);
    for line in text.lines() {
        let line = line.split('#').next().unwrap().trim();
        if line.starts_with('[') {
            in_pkg = line == "[package]";
            continue;
        }
        if let (true, Some((k, v))) = (in_pkg, line.split_once('=')) {
            let v = v.trim().trim_matches('"').to_string();
            match k.trim() { "name" => name = Some(v), "version" => version = Some(v), _ => {} }
        }
    }
    match (name, version) {
        (Some(n), Some(v)) => Ok((n, v)),
        _ => Err(format!("{} has no [package] name and version (workspaces are not supported)", manifest.display())),
    }
}

fn cargo_json(dir: &Path, args: &[&str]) -> Res<Json> {
    let out = Command::new("cargo").args(args).current_dir(dir).stderr(Stdio::inherit()).output()
        .map_err(|e| format!("cargo: {}", e))?;
    if !out.status.success() {
        return Err(format!("cargo {} failed", args.join(" ")));
    }
    Json::parse(&String::from_utf8_lossy(&out.stdout)).map_err(|e| format!("cargo {}: {}", args.join(" "), e))
}

fn run(dir: &Path, args: &[&str]) -> Res<()> {
    let status = Command::new("cargo").args(args).current_dir(dir).status().map_err(|e| format!("cargo: {}", e))?;
    if status.success() { Ok(()) } else { Err(format!("cargo {} failed", args.join(" "))) }
}

fn digest(root: &Path) -> u64 {
    let mut h = DefaultHasher::new();
    for name in ["Cargo.toml", "Cargo.lock"] {
        fs::read(root.join(name)).ok().hash(&mut h);
    }
    h.finish()
}

fn write_atomic(path: &Path, text: &str) -> Res<()> {
    let tmp = path.with_extension("toml.tmp");
    fs::write(&tmp, text).map_err(|e| e.to_string())?;
    fs::rename(&tmp, path).map_err(|e| e.to_string())
}

fn canon(p: &Path) -> PathBuf {
    p.canonicalize().unwrap_or_else(|_| p.to_path_buf())
}

fn toml_str(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// Minimal JSON reader (std has none); enough for the sources map and cargo metadata.
enum Json {
    Null,
    Bool(#[allow(dead_code)] bool),
    Num(#[allow(dead_code)] String),
    Str(String),
    Arr(Vec<Json>),
    Obj(Vec<(String, Json)>),
}

impl Json {
    fn parse(text: &str) -> Res<Json> {
        let mut p = Parser { s: text.as_bytes(), i: 0 };
        let v = p.value()?;
        p.ws();
        if p.i != p.s.len() {
            return Err(format!("trailing data at byte {}", p.i));
        }
        Ok(v)
    }
    fn get(&self, k: &str) -> Option<&Json> {
        match self { Json::Obj(m) => m.iter().find(|(key, _)| key == k).map(|(_, v)| v), _ => None }
    }
    fn as_str(&self) -> Option<&str> {
        match self { Json::Str(s) => Some(s), _ => None }
    }
    fn as_arr(&self) -> Option<&[Json]> {
        match self { Json::Arr(a) => Some(a), _ => None }
    }
}

struct Parser<'a> {
    s: &'a [u8],
    i: usize,
}

impl<'a> Parser<'a> {
    fn ws(&mut self) {
        while self.i < self.s.len() && matches!(self.s[self.i], b' ' | b'\t' | b'\n' | b'\r') {
            self.i += 1;
        }
    }
    fn err<T>(&self, what: &str) -> Res<T> {
        Err(format!("invalid JSON: {} at byte {}", what, self.i))
    }
    fn eat(&mut self, lit: &str) -> bool {
        if self.s[self.i..].starts_with(lit.as_bytes()) { self.i += lit.len(); true } else { false }
    }
    fn value(&mut self) -> Res<Json> {
        self.ws();
        match self.s.get(self.i) {
            None => self.err("unexpected end"),
            Some(b'{') => {
                self.i += 1;
                let mut m = Vec::new();
                self.ws();
                if self.eat("}") { return Ok(Json::Obj(m)); }
                loop {
                    self.ws();
                    let k = self.string()?;
                    self.ws();
                    if !self.eat(":") { return self.err("expected ':'"); }
                    m.push((k, self.value()?));
                    self.ws();
                    if self.eat(",") { continue; }
                    if self.eat("}") { return Ok(Json::Obj(m)); }
                    return self.err("expected ',' or '}'");
                }
            }
            Some(b'[') => {
                self.i += 1;
                let mut a = Vec::new();
                self.ws();
                if self.eat("]") { return Ok(Json::Arr(a)); }
                loop {
                    a.push(self.value()?);
                    self.ws();
                    if self.eat(",") { continue; }
                    if self.eat("]") { return Ok(Json::Arr(a)); }
                    return self.err("expected ',' or ']'");
                }
            }
            Some(b'"') => Ok(Json::Str(self.string()?)),
            Some(_) if self.eat("null") => Ok(Json::Null),
            Some(_) if self.eat("true") => Ok(Json::Bool(true)),
            Some(_) if self.eat("false") => Ok(Json::Bool(false)),
            Some(_) => {
                let start = self.i;
                while self.i < self.s.len() && matches!(self.s[self.i], b'0'..=b'9' | b'-' | b'+' | b'.' | b'e' | b'E') {
                    self.i += 1;
                }
                if start == self.i { return self.err("unexpected character"); }
                Ok(Json::Num(String::from_utf8_lossy(&self.s[start..self.i]).into_owned()))
            }
        }
    }
    fn string(&mut self) -> Res<String> {
        if !self.eat("\"") { return self.err("expected string"); }
        let mut out: Vec<u8> = Vec::new();
        loop {
            let c = match self.s.get(self.i) { Some(c) => *c, None => return self.err("unterminated string") };
            self.i += 1;
            match c {
                b'"' => return String::from_utf8(out).map_err(|e| e.to_string()),
                b'\\' => {
                    let e = match self.s.get(self.i) { Some(e) => *e, None => return self.err("bad escape") };
                    self.i += 1;
                    match e {
                        b'"' => out.push(b'"'), b'\\' => out.push(b'\\'), b'/' => out.push(b'/'),
                        b'b' => out.push(8), b'f' => out.push(12), b'n' => out.push(b'\n'),
                        b'r' => out.push(b'\r'), b't' => out.push(b'\t'),
                        b'u' => {
                            let mut cp = self.hex4()?;
                            if (0xD800..0xDC00).contains(&cp) && self.eat("\\u") {
                                let lo = self.hex4()?;
                                cp = 0x10000 + ((cp - 0xD800) << 10) + (lo.wrapping_sub(0xDC00) & 0x3FF);
                            }
                            let ch = char::from_u32(cp).unwrap_or('\u{FFFD}');
                            out.extend_from_slice(ch.encode_utf8(&mut [0; 4]).as_bytes());
                        }
                        _ => return self.err("bad escape"),
                    }
                }
                c => out.push(c),
            }
        }
    }
    fn hex4(&mut self) -> Res<u32> {
        let h = self.s.get(self.i..self.i + 4).and_then(|b| std::str::from_utf8(b).ok())
            .and_then(|t| u32::from_str_radix(t, 16).ok());
        match h { Some(v) => { self.i += 4; Ok(v) } None => self.err("bad \\u escape") }
    }
}
