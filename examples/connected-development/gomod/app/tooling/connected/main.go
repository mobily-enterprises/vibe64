// Command connected wires connected Vibe64 repositories into this Go module
// with the Go toolchain's native workspace mechanism (an untracked go.work).
//
//	go run ./tooling/connected prepare <sourcesFile>
//	go run ./tooling/connected verify  <sourcesFile>
//
// Run it from the module root. It never edits go.mod or go.sum.
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
)

const (
	contract   = "vibe64.connected-sources.v1"
	packType   = "gomod"
	workMarker = "// Generated by tooling/connected prepare. Untracked; do not commit."
)

type project struct {
	Name           string `json:"name"`
	Repository     string `json:"repository"`
	Relationship   string `json:"relationship"`
	Type           string `json:"type"`
	SourceRoot     string `json:"sourceRoot"`
	ContributionID string `json:"contributionId"`

	modulePath string
	goVersion  string
}

type sources struct {
	Contract  string    `json:"contract"`
	SessionID string    `json:"sessionId"`
	Projects  []project `json:"projects"`
}

func main() {
	if len(os.Args) != 3 || (os.Args[1] != "prepare" && os.Args[1] != "verify") {
		fmt.Fprintln(os.Stderr, "usage: go run ./tooling/connected prepare|verify <sourcesFile>")
		os.Exit(2)
	}
	var err error
	if os.Args[1] == "prepare" {
		err = prepare(os.Args[2])
	} else {
		err = verify(os.Args[2])
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "connected "+os.Args[1]+": "+err.Error())
		os.Exit(1)
	}
}

func appRoot() (string, modInfo, error) {
	root, err := os.Getwd()
	if err != nil {
		return "", modInfo{}, err
	}
	info, err := readGoMod(filepath.Join(root, "go.mod"))
	if err != nil {
		return "", modInfo{}, fmt.Errorf("run from the module root: %w", err)
	}
	return root, info, nil
}

func load(file, appModule string) (sources, []project, error) {
	var s sources
	data, err := os.ReadFile(file)
	if err != nil {
		return s, nil, err
	}
	if err := json.Unmarshal(data, &s); err != nil {
		return s, nil, fmt.Errorf("%s: %w", file, err)
	}
	if s.Contract != contract {
		return s, nil, fmt.Errorf("%s: contract %q, want %q", file, s.Contract, contract)
	}
	var out []project
	seen := map[string]string{}
	for i, p := range s.Projects {
		label := fmt.Sprintf("projects[%d] %q", i, p.Name)
		if p.Type == "" {
			p.Type = packType
		}
		if p.Type != packType {
			fmt.Fprintf(os.Stderr, "connected: skipping %s of type %q (this script wires %q only)\n", label, p.Type, packType)
			continue
		}
		if p.Relationship != "dependency" && p.Relationship != "composition" {
			return s, nil, fmt.Errorf("%s: relationship %q must be dependency or composition", label, p.Relationship)
		}
		if !filepath.IsAbs(p.SourceRoot) {
			return s, nil, fmt.Errorf("%s: sourceRoot %q must be absolute", label, p.SourceRoot)
		}
		root, err := filepath.EvalSymlinks(p.SourceRoot)
		if err != nil {
			return s, nil, fmt.Errorf("%s: %w", label, err)
		}
		p.SourceRoot = root
		info, err := readGoMod(filepath.Join(root, "go.mod"))
		if err != nil {
			return s, nil, fmt.Errorf("%s: sourceRoot is not a Go module: %w", label, err)
		}
		if info.module == appModule {
			return s, nil, fmt.Errorf("%s: module %s is the consuming module itself", label, info.module)
		}
		if other, dup := seen[info.module]; dup {
			return s, nil, fmt.Errorf("%s: module %s is already connected from %s", label, info.module, other)
		}
		seen[info.module] = root
		p.modulePath, p.goVersion = info.module, info.goVersion
		out = append(out, p)
	}
	return s, out, nil
}

func prepare(file string) error {
	root, app, err := appRoot()
	if err != nil {
		return err
	}
	s, projects, err := load(file, app.module)
	if err != nil {
		return err
	}
	if err := checkGoworkEnv(root); err != nil {
		return err
	}
	workPath := filepath.Join(root, "go.work")
	if err := checkOwned(workPath); err != nil {
		return err
	}
	if len(projects) == 0 {
		if err := os.Remove(workPath); err != nil && !errors.Is(err, os.ErrNotExist) {
			return err
		}
		fmt.Println("connected prepare: no gomod repositories connected; go.work removed")
		return nil
	}
	goVersion := app.goVersion
	var b strings.Builder
	for _, p := range projects {
		if versionLess(goVersion, p.goVersion) {
			goVersion = p.goVersion
		}
	}
	fmt.Fprintf(&b, "%s\n// Sources: %s (session %s)\n\ngo %s\n\nuse (\n\t.\n", workMarker, file, s.SessionID, goVersion)
	for _, p := range projects {
		fmt.Fprintf(&b, "\t%s // %s (%s)\n", strconv.Quote(p.SourceRoot), p.modulePath, p.Relationship)
	}
	b.WriteString(")\n")
	tmp := workPath + ".tmp"
	if err := os.WriteFile(tmp, []byte(b.String()), 0o644); err != nil {
		return err
	}
	if err := os.Rename(tmp, workPath); err != nil {
		return err
	}
	for _, p := range projects {
		fmt.Printf("connected prepare: %s -> %s (%s)\n", p.modulePath, p.SourceRoot, p.Relationship)
	}
	return nil
}

func verify(file string) error {
	root, app, err := appRoot()
	if err != nil {
		return err
	}
	_, projects, err := load(file, app.module)
	if err != nil {
		return err
	}
	if len(projects) == 0 {
		fmt.Println("connected verify: no gomod repositories connected; nothing to prove")
		return nil
	}
	workPath := filepath.Join(root, "go.work")
	if _, err := os.Stat(workPath); err != nil {
		return fmt.Errorf("go.work is missing; run prepare: %w", err)
	}
	if err := checkOwned(workPath); err != nil {
		return err
	}
	active, err := goCmd(root, "env", "GOWORK")
	if err != nil {
		return err
	}
	if strings.TrimSpace(active) != workPath {
		return fmt.Errorf("go uses workspace %q, want %q", strings.TrimSpace(active), workPath)
	}
	before, err := manifestDigest(root)
	if err != nil {
		return err
	}
	// Every package the consumer's own packages build against, with the module
	// that supplied it and the directory its source was read from.
	deps, err := goCmd(root, "list", "-deps", "-f",
		"{{if .Module}}{{.Module.Path}}\t{{.Module.Dir}}\t{{.ImportPath}}\t{{.Dir}}{{end}}", "./...")
	if err != nil {
		return err
	}
	for _, p := range projects {
		used := 0
		for _, line := range strings.Split(deps, "\n") {
			f := strings.Split(line, "\t")
			if len(f) != 4 || f[0] != p.modulePath {
				continue
			}
			if !sameDir(f[1], p.SourceRoot) || !within(f[3], p.SourceRoot) {
				return fmt.Errorf("%s package %s is built from %s, not the connected checkout %s", p.modulePath, f[2], f[3], p.SourceRoot)
			}
			used++
		}
		if used == 0 {
			return fmt.Errorf("%s (%s) is connected but no package of it is in the build of ./...", p.modulePath, p.SourceRoot)
		}
		fmt.Printf("connected verify: %s: %d package(s) built from %s\n", p.modulePath, used, p.SourceRoot)
	}
	if _, err := goCmd(root, "build", "./..."); err != nil {
		return err
	}
	after, err := manifestDigest(root)
	if err != nil {
		return err
	}
	if before != after {
		return errors.New("go.mod or go.sum changed while verifying the connected build")
	}
	fmt.Println("connected verify: go build ./... succeeded in workspace mode; go.mod and go.sum unchanged")
	return nil
}

func checkGoworkEnv(root string) error {
	if v, ok := os.LookupEnv("GOWORK"); ok && v != "" && v != filepath.Join(root, "go.work") {
		return fmt.Errorf("GOWORK=%s overrides the generated go.work; unset it", v)
	}
	return nil
}

func checkOwned(workPath string) error {
	f, err := os.Open(workPath)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	defer f.Close()
	line, _ := bufio.NewReader(f).ReadString('\n')
	if strings.TrimSpace(line) != workMarker {
		return fmt.Errorf("%s exists and was not generated by this script; refusing to replace it", workPath)
	}
	return nil
}

func goCmd(dir string, args ...string) (string, error) {
	cmd := exec.Command("go", args...)
	cmd.Dir = dir
	var out bytes.Buffer
	cmd.Stdout = &out
	cmd.Stderr = os.Stderr
	if err := cmd.Run(); err != nil {
		return "", fmt.Errorf("go %s: %w", strings.Join(args, " "), err)
	}
	return out.String(), nil
}

func manifestDigest(root string) (string, error) {
	h := sha256.New()
	for _, name := range []string{"go.mod", "go.sum"} {
		data, err := os.ReadFile(filepath.Join(root, name))
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			return "", err
		}
		fmt.Fprintf(h, "%s %d\n", name, len(data))
		h.Write(data)
	}
	return fmt.Sprintf("%x", h.Sum(nil)), nil
}

type modInfo struct{ module, goVersion string }

func readGoMod(path string) (modInfo, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return modInfo{}, err
	}
	var info modInfo
	for _, line := range strings.Split(string(data), "\n") {
		if i := strings.Index(line, "//"); i >= 0 {
			line = line[:i]
		}
		f := strings.Fields(line)
		if len(f) == 2 && f[0] == "module" {
			info.module = strings.Trim(f[1], "\"`")
		}
		if len(f) == 2 && f[0] == "go" {
			info.goVersion = f[1]
		}
	}
	if info.module == "" {
		return info, fmt.Errorf("%s has no module directive", path)
	}
	return info, nil
}

func versionLess(a, b string) bool {
	pa, pb := strings.Split(a, "."), strings.Split(b, ".")
	for i := 0; i < len(pa) || i < len(pb); i++ {
		var x, y int
		if i < len(pa) {
			x, _ = strconv.Atoi(pa[i])
		}
		if i < len(pb) {
			y, _ = strconv.Atoi(pb[i])
		}
		if x != y {
			return x < y
		}
	}
	return false
}

func sameDir(a, b string) bool {
	ra, err1 := filepath.EvalSymlinks(a)
	rb, err2 := filepath.EvalSymlinks(b)
	return err1 == nil && err2 == nil && ra == rb
}

func within(dir, root string) bool {
	rd, err1 := filepath.EvalSymlinks(dir)
	rr, err2 := filepath.EvalSymlinks(root)
	if err1 != nil || err2 != nil {
		return false
	}
	rel, err := filepath.Rel(rr, rd)
	return err == nil && rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator))
}
