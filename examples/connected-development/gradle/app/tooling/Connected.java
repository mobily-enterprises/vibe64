// Connected development for a Gradle consumer (Vibe64 contract vibe64.connected-sources.v1).
//
// Run from the consumer checkout root with Java 11+ in single-file source mode:
//   java tooling/Connected.java prepare .development/connected.json
//   java tooling/Connected.java verify  .development/connected.json
//
// Mechanism (native Gradle composite builds):
//   * Prepare writes the git-ignored init script .development/connected.init.gradle.kts, which
//     calls Settings.includeBuild(<sourceRoot>) for every connected checkout. Gradle then
//     substitutes the external module (e.g. com.example:library) with the included build's
//     project and compiles it from source on every build. No tracked settings file changes.
//   * Ordinary commands pass the init script: gradle -I .development/connected.init.gradle.kts run
//     (equivalent to --include-build <sourceRoot> for each connected checkout).
//   * Verify runs Gradle with a second, throw-away init script that resolves every
//     runtimeClasspath and proves each connected project contributes an artifact that is a
//     project of an included build and lives inside the connected checkout.
//
// Environment:
//   CONNECTED_GRADLE_ARGS  extra whitespace-separated Gradle arguments for Verify (e.g. --offline)
//
// No tracked file is modified. Exit status is non-zero on any failure.

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

public class Connected {
    static final String CONTRACT = "vibe64.connected-sources.v1";
    static final String TYPE = "gradle";
    static final String INIT = ".development/connected.init.gradle.kts";
    static final String PROOF_INIT = ".development/connected-proof.init.gradle.kts";
    static final String MARKER = "// Generated by tooling/Connected.java for Vibe64 connected development. Do not commit.";

    static final class Project {
        String name, repository, relationship, type, contributionId;
        Path sourceRoot;
    }

    static final class Failure extends RuntimeException {
        Failure(String message) { super(message); }
    }

    public static void main(String[] args) {
        try {
            if (args.length != 2 || !(args[0].equals("prepare") || args[0].equals("verify"))) {
                throw new Failure("usage: java tooling/Connected.java prepare|verify <sources-file>");
            }
            Path app = Paths.get("").toAbsolutePath().normalize();
            if (!isGradleBuild(app)) throw new Failure("run from the consumer checkout root (no Gradle build in " + app + ")");
            List<Project> projects = load(app, app.resolve(args[1]));
            if (args[0].equals("prepare")) prepare(app, projects); else verify(app, projects);
        } catch (Failure f) {
            System.err.println("connected-gradle: FAIL: " + f.getMessage());
            System.exit(1);
        } catch (Exception e) {
            System.err.println("connected-gradle: FAIL: " + e);
            System.exit(1);
        }
    }

    // ---------------------------------------------------------------- prepare

    static void prepare(Path app, List<Project> projects) throws Exception {
        Path init = app.resolve(INIT);
        if (isTracked(app, INIT)) throw new Failure(INIT + " is tracked by Git; refusing to modify it");
        if (Files.exists(init) && !read(init).startsWith(MARKER)) {
            throw new Failure(INIT + " exists and was not written by this tool; refusing to overwrite it");
        }
        Files.createDirectories(init.getParent());
        Files.write(init, initScript(projects).getBytes(StandardCharsets.UTF_8));
        ensureIgnored(app, INIT);
        for (Project p : projects) {
            System.out.println("connected-gradle: including " + p.name + " (" + p.relationship + ") from " + p.sourceRoot);
        }
        System.out.println("connected-gradle: wrote " + INIT + "; run Gradle as: gradle -I " + INIT + " <tasks>");
    }

    static String initScript(List<Project> projects) {
        StringBuilder b = new StringBuilder(MARKER).append("\n// Use: gradle -I ").append(INIT).append(" <tasks>\n");
        b.append("settingsEvaluated {\n");
        for (Project p : projects) {
            b.append("    // ").append(p.name.replaceAll("[\\r\\n]", " ")).append(" (").append(p.relationship).append(")\n");
            b.append("    includeBuild(\"").append(kotlinString(p.sourceRoot.toString())).append("\")\n");
        }
        return b.append("}\n").toString();
    }

    static String kotlinString(String s) {
        return s.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$");
    }

    // ----------------------------------------------------------------- verify

    static final String PROOF_SCRIPT = String.join("\n",
            "// Throw-away proof script written by tooling/Connected.java verify.",
            "allprojects {",
            "    val projectPath = path",
            "    plugins.withId(\"java\") {",
            "        val runtime = configurations.getByName(\"runtimeClasspath\")",
            "        tasks.register(\"connectedProof\") {",
            "            dependsOn(runtime)",
            "            doLast {",
            "                runtime.incoming.artifacts.artifacts.forEach { a ->",
            "                    val id = a.id.componentIdentifier",
            "                    val build = (id as? org.gradle.api.artifacts.component.ProjectComponentIdentifier)?.build?.buildPath ?: \"-\"",
            "                    println(\"CONNECTED-ARTIFACT\\t\" + projectPath + \"\\t\" + build + \"\\t\" + id.displayName + \"\\t\" + a.file.absolutePath)",
            "                }",
            "            }",
            "        }",
            "    }",
            "}",
            "");

    static void verify(Path app, List<Project> projects) throws Exception {
        Path init = app.resolve(INIT);
        if (!Files.isRegularFile(init)) throw new Failure(INIT + " is missing; run prepare");
        if (!read(init).equals(initScript(projects))) throw new Failure(INIT + " does not match the sources map; run prepare");
        if (isTracked(app, INIT)) throw new Failure(INIT + " is tracked by Git");

        Path proof = app.resolve(PROOF_INIT);
        Files.write(proof, PROOF_SCRIPT.getBytes(StandardCharsets.UTF_8));
        ensureIgnored(app, PROOF_INIT);
        List<String> cmd = new ArrayList<>(gradle(app));
        String extra = System.getenv("CONNECTED_GRADLE_ARGS");
        if (extra != null && !extra.isBlank()) cmd.addAll(List.of(extra.trim().split("\\s+")));
        cmd.addAll(List.of("-q", "--console=plain", "--no-configuration-cache",
                "-I", init.toString(), "-I", proof.toString(), "connectedProof"));
        Result r;
        try {
            r = run(cmd, app, true);
        } finally {
            Files.deleteIfExists(proof);
        }
        if (r.code != 0) {
            System.err.print(r.output);
            throw new Failure("Gradle could not build the composite (exit " + r.code + ")");
        }
        List<String[]> artifacts = new ArrayList<>();
        for (String line : r.output.split("\\R")) {
            if (line.startsWith("CONNECTED-ARTIFACT\t")) artifacts.add(line.split("\t", 5));
        }
        if (artifacts.isEmpty()) throw new Failure("no runtimeClasspath was resolved (is this a Java/Kotlin JVM build?)");
        for (Project p : projects) {
            String[] hit = null;
            for (String[] a : artifacts) {
                if (a.length < 5 || a[2].equals("-") || a[2].equals(":")) continue; // not from an included build
                Path f = Paths.get(a[4]);
                if (Files.isRegularFile(f) && f.toRealPath().startsWith(p.sourceRoot)) { hit = a; break; }
            }
            if (hit == null) {
                throw new Failure(p.name + ": no runtimeClasspath artifact comes from the included build at " + p.sourceRoot
                        + " (does the checkout's group:name match the consumer's dependency?)");
            }
            System.out.println("connected-gradle: PROOF " + p.name + ": " + (hit[1].equals(":") ? "root project" : hit[1])
                    + " resolves " + hit[3] + " from included build " + hit[2] + " -> " + hit[4] + " (built from source now)");
        }
        System.out.println("connected-gradle: verified " + projects.size() + " connected project(s)");
    }

    // ------------------------------------------------------------- sources map

    static List<Project> load(Path app, Path file) throws IOException {
        if (!Files.isRegularFile(file)) throw new Failure("sources file not found: " + file);
        Object root = new Json(new String(Files.readAllBytes(file), StandardCharsets.UTF_8)).parseDocument();
        Map<String, Object> doc = object(root, "sources map");
        if (!CONTRACT.equals(doc.get("contract"))) throw new Failure("unsupported contract " + doc.get("contract"));
        if (!(doc.get("projects") instanceof List)) throw new Failure("projects must be an array");
        List<Project> result = new ArrayList<>();
        for (Object o : (List<?>) doc.get("projects")) {
            Map<String, Object> m = object(o, "project");
            Project p = new Project();
            p.name = string(m, "name", true);
            p.repository = string(m, "repository", false);
            p.relationship = string(m, "relationship", true);
            p.type = string(m, "type", false);
            p.contributionId = string(m, "contributionId", false);
            if (p.type == null) p.type = TYPE; // the stack's default package type
            if (!p.relationship.equals("dependency") && !p.relationship.equals("composition")) {
                throw new Failure(p.name + ": unknown relationship " + p.relationship);
            }
            if (!p.type.equals(TYPE)) {
                System.out.println("connected-gradle: skipping " + p.name + " (type " + p.type + " is not " + TYPE + ")");
                continue;
            }
            Path src = Paths.get(string(m, "sourceRoot", true));
            if (!src.isAbsolute()) throw new Failure(p.name + ": sourceRoot must be absolute");
            if (!Files.isDirectory(src)) throw new Failure(p.name + ": sourceRoot does not exist: " + src);
            p.sourceRoot = src.toRealPath();
            if (!isGradleBuild(p.sourceRoot)) throw new Failure(p.name + ": no settings.gradle(.kts) or build.gradle(.kts) in " + p.sourceRoot);
            if (p.sourceRoot.startsWith(app.toRealPath()) || app.toRealPath().startsWith(p.sourceRoot)) {
                throw new Failure(p.name + ": sourceRoot overlaps the consumer checkout");
            }
            result.add(p);
        }
        if (result.isEmpty()) throw new Failure("the sources map lists no " + TYPE + " project; nothing to prepare or prove");
        return result;
    }

    @SuppressWarnings("unchecked")
    static Map<String, Object> object(Object o, String what) {
        if (!(o instanceof Map)) throw new Failure(what + " must be a JSON object");
        return (Map<String, Object>) o;
    }

    static String string(Map<String, Object> m, String key, boolean required) {
        Object v = m.get(key);
        if (v == null && !required) return null;
        if (!(v instanceof String) || ((String) v).isEmpty()) throw new Failure("field " + key + " must be a non-empty string");
        return (String) v;
    }

    /** Small strict RFC 8259 parser: objects, arrays, strings (with escapes), numbers, literals. */
    static final class Json {
        final String s; int i;
        Json(String s) { this.s = s; }
        Object parseDocument() { ws(); Object v = value(); ws(); if (i != s.length()) err("trailing data"); return v; }
        Object value() {
            if (i >= s.length()) err("unexpected end");
            char c = s.charAt(i);
            if (c == '{') return obj();
            if (c == '[') return arr();
            if (c == '"') return str();
            if (s.startsWith("true", i)) { i += 4; return Boolean.TRUE; }
            if (s.startsWith("false", i)) { i += 5; return Boolean.FALSE; }
            if (s.startsWith("null", i)) { i += 4; return null; }
            return num();
        }
        Map<String, Object> obj() {
            Map<String, Object> m = new LinkedHashMap<>(); i++; ws();
            if (peek('}')) { i++; return m; }
            while (true) {
                ws(); if (!peek('"')) err("expected key"); String k = str(); ws(); expect(':'); ws();
                if (m.containsKey(k)) err("duplicate key " + k);
                m.put(k, value()); ws();
                if (peek(',')) { i++; continue; } expect('}'); return m;
            }
        }
        List<Object> arr() {
            List<Object> l = new ArrayList<>(); i++; ws();
            if (peek(']')) { i++; return l; }
            while (true) { ws(); l.add(value()); ws(); if (peek(',')) { i++; continue; } expect(']'); return l; }
        }
        String str() {
            expect('"'); StringBuilder b = new StringBuilder();
            while (true) {
                if (i >= s.length()) err("unterminated string");
                char c = s.charAt(i++);
                if (c == '"') return b.toString();
                if (c < 0x20) err("control character in string");
                if (c != '\\') { b.append(c); continue; }
                if (i >= s.length()) err("bad escape");
                char e = s.charAt(i++);
                switch (e) {
                    case '"': b.append('"'); break; case '\\': b.append('\\'); break; case '/': b.append('/'); break;
                    case 'b': b.append('\b'); break; case 'f': b.append('\f'); break; case 'n': b.append('\n'); break;
                    case 'r': b.append('\r'); break; case 't': b.append('\t'); break;
                    case 'u':
                        if (i + 4 > s.length()) err("bad unicode escape");
                        try { b.append((char) Integer.parseInt(s.substring(i, i + 4), 16)); } catch (NumberFormatException x) { err("bad unicode escape"); }
                        i += 4; break;
                    default: err("bad escape \\" + e);
                }
            }
        }
        Object num() {
            int start = i;
            while (i < s.length() && "+-0123456789.eE".indexOf(s.charAt(i)) >= 0) i++;
            if (start == i) err("unexpected character '" + s.charAt(i) + "'");
            try { return Double.valueOf(s.substring(start, i)); } catch (NumberFormatException x) { err("bad number"); return null; }
        }
        void ws() { while (i < s.length() && " \t\r\n".indexOf(s.charAt(i)) >= 0) i++; }
        boolean peek(char c) { return i < s.length() && s.charAt(i) == c; }
        void expect(char c) { if (!peek(c)) err("expected '" + c + "'"); i++; }
        void err(String m) { throw new Failure("invalid sources JSON at offset " + i + ": " + m); }
    }

    // ---------------------------------------------------------------- helpers

    static boolean isGradleBuild(Path dir) {
        for (String f : List.of("settings.gradle.kts", "settings.gradle", "build.gradle.kts", "build.gradle")) {
            if (Files.isRegularFile(dir.resolve(f))) return true;
        }
        return false;
    }

    static List<String> gradle(Path dir) {
        Path wrapper = dir.resolve("gradlew");
        return Files.isExecutable(wrapper) ? List.of(wrapper.toString()) : List.of("gradle");
    }

    static String read(Path p) throws IOException {
        return new String(Files.readAllBytes(p), StandardCharsets.UTF_8);
    }

    static boolean isTracked(Path app, String rel) {
        try {
            Result r = run(List.of("git", "ls-files", "--error-unmatch", "--", rel), app, true);
            return r.code == 0;
        } catch (Exception e) {
            return false; // not a Git checkout (or Git unavailable): nothing can be tracked
        }
    }

    /** Make sure a derived path is ignored; fall back to the repository-local .git/info/exclude. */
    static void ensureIgnored(Path app, String rel) throws Exception {
        Result inside;
        try { inside = run(List.of("git", "rev-parse", "--is-inside-work-tree"), app, true); } catch (IOException e) { return; }
        if (inside.code != 0) return;
        if (run(List.of("git", "check-ignore", "-q", "--", rel), app, true).code == 0) return;
        Result p = run(List.of("git", "rev-parse", "--git-path", "info/exclude"), app, true);
        Path exclude = app.resolve(p.output.trim());
        Files.createDirectories(exclude.getParent());
        Files.write(exclude, ("/" + rel + "\n").getBytes(StandardCharsets.UTF_8),
                java.nio.file.StandardOpenOption.CREATE, java.nio.file.StandardOpenOption.APPEND);
        System.out.println("connected-gradle: added /" + rel + " to " + exclude);
    }

    static final class Result { int code; String output = ""; }

    static Result run(List<String> cmd, Path dir, boolean capture) throws IOException, InterruptedException {
        ProcessBuilder pb = new ProcessBuilder(cmd).directory(dir.toFile()).redirectErrorStream(true);
        if (!capture) pb.redirectOutput(ProcessBuilder.Redirect.INHERIT);
        Process proc = pb.start();
        Result r = new Result();
        if (capture) {
            try (InputStream in = proc.getInputStream()) {
                ByteArrayOutputStream buf = new ByteArrayOutputStream();
                in.transferTo(buf);
                r.output = buf.toString(StandardCharsets.UTF_8);
            }
        }
        r.code = proc.waitFor();
        return r;
    }
}
