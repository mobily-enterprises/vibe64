// Connected development for a Maven consumer (Vibe64 contract vibe64.connected-sources.v1).
//
// Run from the consumer checkout root with Java 11+ in single-file source mode:
//   java tooling/Connected.java prepare .development/connected.json
//   java tooling/Connected.java verify  .development/connected.json
//
// Mechanism (native Maven 3.9+ features only):
//   * Prepare runs `mvn install` in every connected checkout with a project-local, git-ignored
//     HEAD local repository (-Dmaven.repo.local=.development/maven-connected-repository) chained
//     in front of the developer's normal local repository (-Dmaven.repo.local.tail=...). Maven
//     writes only to the head, so the developer's shared ~/.m2 is never touched.
//   * Prepare writes the git-ignored `.mvn/maven.config` with the same two arguments, so every
//     ordinary `mvn ...` command in this checkout resolves the connected build first.
//   * Verify asks Maven for the consumer's resolved classpath and proves that each connected
//     project contributes a jar from the head repository that is byte-identical to the jar just
//     built from the connected checkout, and that the checkout has not changed since Prepare.
//
// Environment:
//   CONNECTED_MAVEN_TAIL  local repository used as the read-only tail (default ~/.m2/repository)
//   MAVEN_ARGS            standard Maven 3.9 variable; e.g. "-B -o" to stay offline
//
// No tracked file is modified. Exit status is non-zero on any failure.

import java.io.ByteArrayOutputStream;
import java.io.File;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.nio.file.attribute.FileTime;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;
import java.util.stream.Stream;

public class Connected {
    static final String CONTRACT = "vibe64.connected-sources.v1";
    static final String TYPE = "maven";
    static final String HEAD_DIR = ".development/maven-connected-repository";
    static final String CONFIG = ".mvn/maven.config";
    static final String CONFIG_MARKER = "# Generated by tooling/Connected.java for Vibe64 connected development. Do not commit.";
    static final String DEPENDENCY_PLUGIN = "org.apache.maven.plugins:maven-dependency-plugin:3.11.0:build-classpath";

    static final class Project {
        String name, repository, relationship, type, contributionId;
        Path sourceRoot;
    }

    static final class Failure extends RuntimeException {
        Failure(String message) { super(message); }
    }

    public static void main(String[] args) {
        try {
            if (args.length != 2 || !(args[0].equals("prepare") || args[0].equals("verify"))) {
                throw new Failure("usage: java tooling/Connected.java prepare|verify <sources-file>");
            }
            Path app = Paths.get("").toAbsolutePath().normalize();
            if (!Files.isRegularFile(app.resolve("pom.xml"))) {
                throw new Failure("run from the consumer checkout root (no pom.xml in " + app + ")");
            }
            List<Project> projects = load(app, app.resolve(args[1]));
            if (args[0].equals("prepare")) prepare(app, projects); else verify(app, projects);
        } catch (Failure f) {
            System.err.println("connected-maven: FAIL: " + f.getMessage());
            System.exit(1);
        } catch (Exception e) {
            System.err.println("connected-maven: FAIL: " + e);
            System.exit(1);
        }
    }

    // ---------------------------------------------------------------- prepare

    static void prepare(Path app, List<Project> projects) throws Exception {
        requireMaven(app);
        Path head = app.resolve(HEAD_DIR);
        Path tail = tail();
        Path config = app.resolve(CONFIG);
        guardConfig(app, config);

        // Rebuild the head from scratch every time: no stale or disconnected artifact can survive.
        deleteTree(head);
        Files.createDirectories(head);
        for (Project p : projects) {
            System.out.println("connected-maven: installing " + p.name + " (" + p.relationship + ") from " + p.sourceRoot);
            List<String> cmd = new ArrayList<>(mvn(p.sourceRoot));
            cmd.addAll(List.of("-B", "-q", "-f", p.sourceRoot.resolve("pom.xml").toString(),
                    "-Dmaven.repo.local=" + head, "-Dmaven.repo.local.tail=" + tail,
                    "-DskipTests", "install"));
            Result r = run(cmd, p.sourceRoot, false);
            if (r.code != 0) throw new Failure("mvn install failed for " + p.name + " (exit " + r.code + ")");
        }
        String content = CONFIG_MARKER + "\n-Dmaven.repo.local=" + head + "\n-Dmaven.repo.local.tail=" + tail + "\n";
        Files.createDirectories(config.getParent());
        Files.write(config, content.getBytes(StandardCharsets.UTF_8));
        ensureIgnored(app, CONFIG);
        ensureIgnored(app, HEAD_DIR + "/");
        System.out.println("connected-maven: prepared " + projects.size() + " connected project(s); head " + head + ", tail " + tail);
    }

    // ----------------------------------------------------------------- verify

    static void verify(Path app, List<Project> projects) throws Exception {
        requireMaven(app);
        Path head = app.resolve(HEAD_DIR).toRealPath();
        Path config = app.resolve(CONFIG);
        if (!Files.isRegularFile(config)) throw new Failure(CONFIG + " is missing; run prepare");
        String text = new String(Files.readAllBytes(config), StandardCharsets.UTF_8);
        if (!text.startsWith(CONFIG_MARKER) || !text.contains("-Dmaven.repo.local=" + app.resolve(HEAD_DIR) + "\n")) {
            throw new Failure(CONFIG + " does not select the connected head repository; run prepare");
        }
        if (isTracked(app, CONFIG)) throw new Failure(CONFIG + " is tracked by Git");

        // Ask Maven itself, through the ordinary command path (.mvn/maven.config applies), which
        // files make up the consumer's classpath.
        Path out = app.resolve(".development/connected-classpath.txt");
        Files.deleteIfExists(out);
        List<String> cmd = new ArrayList<>(mvn(app));
        cmd.addAll(List.of("-B", "-q", DEPENDENCY_PLUGIN, "-Dmdep.outputFile=" + out, "-Dmdep.includeScope=runtime"));
        Result r = run(cmd, app, true);
        if (r.code != 0 || !Files.isRegularFile(out)) {
            System.err.print(r.output);
            throw new Failure("could not resolve the consumer classpath (exit " + r.code + ")");
        }
        String raw = new String(Files.readAllBytes(out), StandardCharsets.UTF_8).trim();
        List<Path> classpath = new ArrayList<>();
        for (String s : raw.split(File.pathSeparator)) if (!s.isEmpty()) classpath.add(Paths.get(s).toRealPath());

        for (Project p : projects) {
            Map<String, Path> built = builtJars(p.sourceRoot);
            if (built.isEmpty()) throw new Failure(p.name + ": no jar built under " + p.sourceRoot + "; run prepare");
            Path match = null, source = null;
            for (Path entry : classpath) {
                if (!entry.startsWith(head) || !Files.isRegularFile(entry)) continue;
                Path b = built.get(sha256(entry));
                if (b != null) { match = entry; source = b; break; }
            }
            if (match == null) {
                throw new Failure(p.name + ": the consumer classpath contains no artifact from the connected checkout "
                        + "(is the dependency version requested by pom.xml the version the checkout builds?) classpath=" + classpath);
            }
            Path changed = newerThan(p.sourceRoot, Files.getLastModifiedTime(source));
            if (changed != null) {
                throw new Failure(p.name + ": " + changed + " changed after Prepare built " + source + "; run prepare again");
            }
            System.out.println("connected-maven: PROOF " + p.name + ": consumer resolves " + app.relativize(match)
                    + " == " + source + " (sha256 " + sha256(match).substring(0, 16) + "...)");
        }
        System.out.println("connected-maven: verified " + projects.size() + " connected project(s)");
    }

    // ------------------------------------------------------------- sources map

    static List<Project> load(Path app, Path file) throws IOException {
        if (!Files.isRegularFile(file)) throw new Failure("sources file not found: " + file);
        Object root = new Json(new String(Files.readAllBytes(file), StandardCharsets.UTF_8)).parseDocument();
        Map<String, Object> doc = object(root, "sources map");
        if (!CONTRACT.equals(doc.get("contract"))) throw new Failure("unsupported contract " + doc.get("contract"));
        if (!(doc.get("projects") instanceof List)) throw new Failure("projects must be an array");
        List<Project> result = new ArrayList<>();
        for (Object o : (List<?>) doc.get("projects")) {
            Map<String, Object> m = object(o, "project");
            Project p = new Project();
            p.name = string(m, "name", true);
            p.repository = string(m, "repository", false);
            p.relationship = string(m, "relationship", true);
            p.type = string(m, "type", false);
            p.contributionId = string(m, "contributionId", false);
            if (p.type == null) p.type = TYPE; // the stack's default package type
            if (!p.relationship.equals("dependency") && !p.relationship.equals("composition")) {
                throw new Failure(p.name + ": unknown relationship " + p.relationship);
            }
            if (!p.type.equals(TYPE)) {
                System.out.println("connected-maven: skipping " + p.name + " (type " + p.type + " is not " + TYPE + ")");
                continue;
            }
            Path src = Paths.get(string(m, "sourceRoot", true));
            if (!src.isAbsolute()) throw new Failure(p.name + ": sourceRoot must be absolute");
            if (!Files.isDirectory(src)) throw new Failure(p.name + ": sourceRoot does not exist: " + src);
            p.sourceRoot = src.toRealPath();
            if (!Files.isRegularFile(p.sourceRoot.resolve("pom.xml"))) throw new Failure(p.name + ": no pom.xml in " + p.sourceRoot);
            if (p.sourceRoot.startsWith(app.toRealPath()) || app.toRealPath().startsWith(p.sourceRoot)) {
                throw new Failure(p.name + ": sourceRoot overlaps the consumer checkout");
            }
            result.add(p);
        }
        if (result.isEmpty()) throw new Failure("the sources map lists no " + TYPE + " project; nothing to prepare or prove");
        return result;
    }

    @SuppressWarnings("unchecked")
    static Map<String, Object> object(Object o, String what) {
        if (!(o instanceof Map)) throw new Failure(what + " must be a JSON object");
        return (Map<String, Object>) o;
    }

    static String string(Map<String, Object> m, String key, boolean required) {
        Object v = m.get(key);
        if (v == null && !required) return null;
        if (!(v instanceof String) || ((String) v).isEmpty()) throw new Failure("field " + key + " must be a non-empty string");
        return (String) v;
    }

    /** Small strict RFC 8259 parser: objects, arrays, strings (with escapes), numbers, literals. */
    static final class Json {
        final String s; int i;
        Json(String s) { this.s = s; }
        Object parseDocument() { ws(); Object v = value(); ws(); if (i != s.length()) err("trailing data"); return v; }
        Object value() {
            if (i >= s.length()) err("unexpected end");
            char c = s.charAt(i);
            if (c == '{') return obj();
            if (c == '[') return arr();
            if (c == '"') return str();
            if (s.startsWith("true", i)) { i += 4; return Boolean.TRUE; }
            if (s.startsWith("false", i)) { i += 5; return Boolean.FALSE; }
            if (s.startsWith("null", i)) { i += 4; return null; }
            return num();
        }
        Map<String, Object> obj() {
            Map<String, Object> m = new LinkedHashMap<>(); i++; ws();
            if (peek('}')) { i++; return m; }
            while (true) {
                ws(); if (!peek('"')) err("expected key"); String k = str(); ws(); expect(':'); ws();
                if (m.containsKey(k)) err("duplicate key " + k);
                m.put(k, value()); ws();
                if (peek(',')) { i++; continue; } expect('}'); return m;
            }
        }
        List<Object> arr() {
            List<Object> l = new ArrayList<>(); i++; ws();
            if (peek(']')) { i++; return l; }
            while (true) { ws(); l.add(value()); ws(); if (peek(',')) { i++; continue; } expect(']'); return l; }
        }
        String str() {
            expect('"'); StringBuilder b = new StringBuilder();
            while (true) {
                if (i >= s.length()) err("unterminated string");
                char c = s.charAt(i++);
                if (c == '"') return b.toString();
                if (c < 0x20) err("control character in string");
                if (c != '\\') { b.append(c); continue; }
                if (i >= s.length()) err("bad escape");
                char e = s.charAt(i++);
                switch (e) {
                    case '"': b.append('"'); break; case '\\': b.append('\\'); break; case '/': b.append('/'); break;
                    case 'b': b.append('\b'); break; case 'f': b.append('\f'); break; case 'n': b.append('\n'); break;
                    case 'r': b.append('\r'); break; case 't': b.append('\t'); break;
                    case 'u':
                        if (i + 4 > s.length()) err("bad unicode escape");
                        try { b.append((char) Integer.parseInt(s.substring(i, i + 4), 16)); } catch (NumberFormatException x) { err("bad unicode escape"); }
                        i += 4; break;
                    default: err("bad escape \\" + e);
                }
            }
        }
        Object num() {
            int start = i;
            while (i < s.length() && "+-0123456789.eE".indexOf(s.charAt(i)) >= 0) i++;
            if (start == i) err("unexpected character '" + s.charAt(i) + "'");
            try { return Double.valueOf(s.substring(start, i)); } catch (NumberFormatException x) { err("bad number"); return null; }
        }
        void ws() { while (i < s.length() && " \t\r\n".indexOf(s.charAt(i)) >= 0) i++; }
        boolean peek(char c) { return i < s.length() && s.charAt(i) == c; }
        void expect(char c) { if (!peek(c)) err("expected '" + c + "'"); i++; }
        void err(String m) { throw new Failure("invalid sources JSON at offset " + i + ": " + m); }
    }

    // ---------------------------------------------------------------- helpers

    static Path tail() throws IOException {
        String t = System.getenv("CONNECTED_MAVEN_TAIL");
        Path p = (t == null || t.isEmpty()) ? Paths.get(System.getProperty("user.home"), ".m2", "repository") : Paths.get(t);
        p = p.toAbsolutePath().normalize();
        Files.createDirectories(p);
        return p;
    }

    static List<String> mvn(Path dir) {
        Path wrapper = dir.resolve("mvnw");
        return Files.isExecutable(wrapper) ? List.of(wrapper.toString()) : List.of("mvn");
    }

    /** Chained local repositories (maven.repo.local.tail) and comments in maven.config need Maven 3.9.3+. */
    static void requireMaven(Path app) throws Exception {
        List<String> cmd = new ArrayList<>(mvn(app));
        cmd.add("--version");
        Result r = run(cmd, app, true);
        java.util.regex.Matcher m = java.util.regex.Pattern.compile("Apache Maven (\\d+)\\.(\\d+)\\.(\\d+)").matcher(r.output);
        if (r.code != 0 || !m.find()) throw new Failure("Maven is not available: " + r.output.trim());
        int[] v = {Integer.parseInt(m.group(1)), Integer.parseInt(m.group(2)), Integer.parseInt(m.group(3))};
        if (v[0] == 3 && (v[1] < 9 || (v[1] == 9 && v[2] < 3)) || v[0] < 3) {
            throw new Failure("Maven 3.9.3 or newer is required, found " + m.group());
        }
    }

    static void guardConfig(Path app, Path config) throws IOException {
        if (isTracked(app, CONFIG)) {
            throw new Failure(CONFIG + " is tracked by this project; refusing to modify it. "
                    + "Put -Dmaven.repo.local/-Dmaven.repo.local.tail in MAVEN_ARGS instead.");
        }
        if (Files.exists(config)) {
            String text = new String(Files.readAllBytes(config), StandardCharsets.UTF_8);
            if (!text.startsWith(CONFIG_MARKER)) throw new Failure(CONFIG + " exists and was not written by this tool; refusing to overwrite it");
        }
    }

    static boolean isTracked(Path app, String rel) {
        try {
            Result r = run(List.of("git", "ls-files", "--error-unmatch", "--", rel), app, true);
            return r.code == 0;
        } catch (Exception e) {
            return false; // not a Git checkout (or Git unavailable): nothing can be tracked
        }
    }

    /** Make sure a derived path is ignored; fall back to the repository-local .git/info/exclude. */
    static void ensureIgnored(Path app, String rel) throws Exception {
        Result inside;
        try { inside = run(List.of("git", "rev-parse", "--is-inside-work-tree"), app, true); } catch (IOException e) { return; }
        if (inside.code != 0) return;
        if (run(List.of("git", "check-ignore", "-q", "--", rel), app, true).code == 0) return;
        Result p = run(List.of("git", "rev-parse", "--git-path", "info/exclude"), app, true);
        Path exclude = app.resolve(p.output.trim());
        Files.createDirectories(exclude.getParent());
        Files.write(exclude, ("/" + rel + "\n").getBytes(StandardCharsets.UTF_8),
                java.nio.file.StandardOpenOption.CREATE, java.nio.file.StandardOpenOption.APPEND);
        System.out.println("connected-maven: added /" + rel + " to " + exclude);
    }

    /** Jars produced by the connected build (target/ directories, excluding sources/javadoc), keyed by SHA-256. */
    static Map<String, Path> builtJars(Path root) throws IOException {
        Map<String, Path> jars = new LinkedHashMap<>();
        try (Stream<Path> s = Files.walk(root, 6)) {
            List<Path> found = s.filter(f -> f.getFileName().toString().endsWith(".jar"))
                    .filter(f -> f.getParent() != null && f.getParent().getFileName().toString().equals("target"))
                    .filter(f -> !f.getFileName().toString().matches(".*-(sources|javadoc|tests)\\.jar"))
                    .collect(Collectors.toList());
            for (Path f : found) jars.put(sha256(f), f);
        }
        return jars;
    }

    /** First build input (pom.xml or a file under src/) modified after the given time, or null. */
    static Path newerThan(Path root, FileTime time) throws IOException {
        try (Stream<Path> s = Files.walk(root)) {
            return s.filter(Files::isRegularFile)
                    .filter(f -> { Path r = root.relativize(f); return !r.startsWith("target") && !r.toString().contains("/target/") && !r.startsWith(".git"); })
                    .filter(f -> f.getFileName().toString().equals("pom.xml") || root.relativize(f).toString().matches("(.*/)?src/.*"))
                    .filter(f -> { try { return Files.getLastModifiedTime(f).compareTo(time) > 0; } catch (IOException e) { return true; } })
                    .findFirst().orElse(null);
        }
    }

    static String sha256(Path f) throws IOException {
        try {
            MessageDigest d = MessageDigest.getInstance("SHA-256");
            byte[] h = d.digest(Files.readAllBytes(f));
            StringBuilder b = new StringBuilder();
            for (byte x : h) b.append(String.format("%02x", x));
            return b.toString();
        } catch (java.security.NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }

    static void deleteTree(Path p) throws IOException {
        if (!Files.exists(p)) return;
        try (Stream<Path> s = Files.walk(p)) {
            for (Path f : s.sorted(Comparator.reverseOrder()).collect(Collectors.toList())) Files.delete(f);
        }
    }

    static final class Result { int code; String output = ""; }

    static Result run(List<String> cmd, Path dir, boolean capture) throws IOException, InterruptedException {
        ProcessBuilder pb = new ProcessBuilder(cmd).directory(dir.toFile()).redirectErrorStream(true);
        if (!capture) pb.redirectOutput(ProcessBuilder.Redirect.INHERIT);
        Process proc = pb.start();
        Result r = new Result();
        if (capture) {
            try (InputStream in = proc.getInputStream()) {
                ByteArrayOutputStream buf = new ByteArrayOutputStream();
                in.transferTo(buf);
                r.output = buf.toString(StandardCharsets.UTF_8);
            }
        }
        r.code = proc.waitFor();
        return r;
    }
}
