// Vibe64 connected development for NuGet PackageReferences.
//
//   dotnet run --project tooling/Connected -- prepare|verify <sources file>
//
// prepare: for every consuming project that references a package produced by a
//   connected checkout, writes an untracked, Git-excluded Directory.Build.targets
//   beside that .csproj. MSBuild imports it automatically, including during
//   NuGet restore, and it chains to any Directory.Build.targets further up.
//   For that one project it replaces the PackageReference with a
//   ProjectReference to the connected .csproj and moves the NuGet lock file to
//   an untracked obj/ path. It is active only while the sources file exists.
//   Nothing tracked is edited and no package enters any NuGet cache.
//   (Project-extension files in obj/ are not used: MSBuild 17.10+ skips them
//   during restore.)
// verify: builds each affected project and proves that restore resolved the
//   package as the connected project, that the referenced assembly is the one
//   built from the connected checkout, and that no tracked file changed.
using System.Diagnostics;
using System.Security;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;

const string Contract = "vibe64.connected-sources.v1";
const string Generated = "Generated by tooling/Connected (Vibe64 connected development)";

if (args.Length != 2 || args[0] is not ("prepare" or "verify"))
    return Fail("usage: prepare|verify <sources file>");

var projectRoot = Path.GetFullPath(Directory.GetCurrentDirectory());
var sourcesFile = Path.GetFullPath(args[1], projectRoot);
if (!File.Exists(sourcesFile)) return Fail($"sources file not found: {sourcesFile}");

var map = JsonNode.Parse(File.ReadAllText(sourcesFile))?.AsObject();
if (map?["contract"]?.GetValue<string>() != Contract) return Fail($"sources file is not {Contract}");
var connected = (map["projects"]?.AsArray() ?? [])
    .Select(p => p!.AsObject())
    .Where(p => (p["type"]?.GetValue<string>() ?? "nuget") == "nuget")
    .Select(p => (Name: p["name"]!.GetValue<string>(), Root: Path.GetFullPath(p["sourceRoot"]!.GetValue<string>())))
    .ToList();

// Package id -> connected .csproj that produces it.
var packages = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
foreach (var (name, root) in connected)
{
    var found = false;
    foreach (var csproj in ProjectFiles(root))
    {
        var props = Evaluate(csproj, "-getProperty:PackageId", "-getProperty:IsPackable");
        if (props["Properties"]?["IsPackable"]?.GetValue<string>() == "false") continue;
        var id = props["Properties"]?["PackageId"]?.GetValue<string>();
        if (string.IsNullOrEmpty(id)) continue;
        if (packages.TryGetValue(id, out var other) && other != csproj)
            return Fail($"package {id} is produced by both {other} and {csproj}");
        packages[id] = csproj;
        found = true;
    }
    if (!found) return Fail($"connected project {name} at {root} produces no packable .csproj");
}

// Consuming projects: every .csproj in this checkout except tooling and connected roots.
var consumers = ProjectFiles(projectRoot)
    .Where(p => !IsUnder(p, Path.Combine(projectRoot, "tooling")) && !connected.Any(c => IsUnder(p, c.Root)))
    .ToList();

var used = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
var affected = new List<(string Project, string Targets, string ObjDir, string[] Ids)>();
foreach (var consumer in consumers)
{
    // Evaluate without our own extension so a second prepare sees the original references.
    var eval = Evaluate(consumer, "-getItem:PackageReference", "-getProperty:MSBuildProjectExtensionsPath", "-p:Vibe64ConnectedDisabled=true");
    var ids = (eval["Items"]?["PackageReference"]?.AsArray() ?? [])
        .Select(i => i!["Identity"]!.GetValue<string>())
        .Where(packages.ContainsKey).Distinct(StringComparer.OrdinalIgnoreCase).ToArray();
    var targets = Path.Combine(Path.GetDirectoryName(consumer)!, "Directory.Build.targets");
    var ours = File.Exists(targets) && File.ReadAllText(targets).Contains(Generated);
    if (ids.Length == 0)
    {
        if (args[0] == "prepare" && ours) File.Delete(targets);
        continue;
    }
    if (File.Exists(targets) && !ours)
        return Fail($"{Rel(targets)} already exists and is not generated; move it to a parent directory to use connected development");
    var extPath = Path.GetFullPath(eval["Properties"]!["MSBuildProjectExtensionsPath"]!.GetValue<string>(), Path.GetDirectoryName(consumer)!);
    used.UnionWith(ids);
    affected.Add((consumer, targets, extPath, ids));
}
foreach (var (name, root) in connected)
    if (!packages.Where(p => IsUnder(p.Value, root)).Any(p => used.Contains(p.Key)))
        return Fail($"no consuming project references a package from connected project {name}");

return args[0] == "prepare" ? Prepare() : Verify();

int Prepare()
{
    foreach (var (project, targets, objDir, ids) in affected)
    {
        var xml = new StringBuilder();
        xml.AppendLine("<Project>");
        xml.AppendLine($"  <!-- {Generated} from {X(sourcesFile)}. Untracked and Git-excluded; delete freely. -->");
        xml.AppendLine("  <PropertyGroup>");
        xml.AppendLine("    <Vibe64ParentBuildTargets>$([MSBuild]::GetPathOfFileAbove('Directory.Build.targets', '$(MSBuildThisFileDirectory)../'))</Vibe64ParentBuildTargets>");
        xml.AppendLine("  </PropertyGroup>");
        xml.AppendLine("  <Import Project=\"$(Vibe64ParentBuildTargets)\" Condition=\"'$(Vibe64ParentBuildTargets)' != ''\" />");
        xml.AppendLine($"  <PropertyGroup Condition=\"'$(MSBuildProjectFullPath)' == '{X(M(project))}' And '$(Vibe64ConnectedDisabled)' != 'true' And Exists('{X(M(sourcesFile))}')\">");
        xml.AppendLine("    <Vibe64ConnectedActive>true</Vibe64ConnectedActive>");
        xml.AppendLine("    <!-- The graph differs from the tracked lock file; keep connected locks out of source. -->");
        xml.AppendLine($"    <NuGetLockFilePath>{X(M(Path.Combine(objDir, "vibe64-connected.packages.lock.json")))}</NuGetLockFilePath>");
        xml.AppendLine("    <RestoreLockedMode>false</RestoreLockedMode>");
        xml.AppendLine("  </PropertyGroup>");
        xml.AppendLine("  <ItemGroup Condition=\"'$(Vibe64ConnectedActive)' == 'true'\">");
        foreach (var id in ids)
        {
            xml.AppendLine($"    <PackageReference Remove=\"{X(M(id))}\" />");
            xml.AppendLine($"    <ProjectReference Include=\"{X(M(packages[id]))}\" />");
        }
        xml.AppendLine("  </ItemGroup>");
        xml.AppendLine("</Project>");
        var text = xml.ToString();
        if (!File.Exists(targets) || File.ReadAllText(targets) != text) File.WriteAllText(targets, text);
        GitExclude(targets);
        Console.WriteLine($"connected: {Rel(project)} uses {string.Join(", ", ids.Select(i => $"{i} -> {packages[i]}"))}");
    }
    return 0;
}

int Verify()
{
    foreach (var (project, targets, objDir, ids) in affected)
    {
        if (!File.Exists(targets)) return Fail($"run prepare first: {Rel(targets)} is missing");
        Run("dotnet", "build", project, "-nologo", "-v:q");
        var outDir = Path.GetDirectoryName(Evaluate(project, "-getProperty:TargetPath")["Properties"]!["TargetPath"]!.GetValue<string>())!;
        var assetsPath = Path.Combine(objDir, "project.assets.json");
        var assets = JsonNode.Parse(File.ReadAllText(assetsPath))!;
        foreach (var id in ids)
        {
            // 1. Restore resolved the id as a project, at the connected .csproj.
            var lib = assets["libraries"]!.AsObject()
                .FirstOrDefault(kv => kv.Key.StartsWith(id + "/", StringComparison.OrdinalIgnoreCase));
            var type = lib.Value?["type"]?.GetValue<string>();
            var resolved = lib.Value?["path"]?.GetValue<string>();
            if (type != "project" || resolved is null ||
                Path.GetFullPath(resolved, Path.GetDirectoryName(project)!) != packages[id])
                return Fail($"{Rel(project)}: {id} resolved as {type ?? "missing"} {resolved}, not {packages[id]}");
            // 2. The assembly in the consumer's output is the one built from the connected checkout.
            var built = Evaluate(packages[id], "-getProperty:TargetPath")["Properties"]!["TargetPath"]!.GetValue<string>();
            var copied = Path.Combine(outDir, Path.GetFileName(built));
            if (!File.Exists(built) || !File.Exists(copied) || Hash(built) != Hash(copied))
                return Fail($"{Rel(project)}: {copied} is not the assembly built at {built}");
            Console.WriteLine($"connected: {Rel(project)} built {id} from {packages[id]}");
        }
    }
    // 3. Connected development edited nothing tracked.
    if (Directory.Exists(Path.Combine(projectRoot, ".git")) || File.Exists(Path.Combine(projectRoot, ".git")))
    {
        var status = Run("git", "-C", projectRoot, "status", "--porcelain", "--untracked-files=no").Trim();
        if (status.Length > 0) return Fail($"tracked files changed:\n{status}");
    }
    Console.WriteLine("connected: verified");
    return 0;
}

// Keep the generated file out of `git status` with Git's own untracked exclude list.
void GitExclude(string file)
{
    if (!Directory.Exists(Path.Combine(projectRoot, ".git")) && !File.Exists(Path.Combine(projectRoot, ".git"))) return;
    var exclude = Path.GetFullPath(Run("git", "-C", projectRoot, "rev-parse", "--git-path", "info/exclude").Trim(), projectRoot);
    var line = "/" + Rel(file).Replace(Path.DirectorySeparatorChar, '/');
    var lines = File.Exists(exclude) ? File.ReadAllLines(exclude) : [];
    if (lines.Contains(line)) return;
    Directory.CreateDirectory(Path.GetDirectoryName(exclude)!);
    File.AppendAllLines(exclude, ["# Vibe64 connected development (tooling/Connected)", line]);
}

static IEnumerable<string> ProjectFiles(string root) =>
    Directory.EnumerateFiles(root, "*.csproj", SearchOption.AllDirectories)
        .Select(Path.GetFullPath)
        .Where(p => !p.Split(Path.DirectorySeparatorChar).Any(s => s is "bin" or "obj" or ".git" or ".development"))
        .Order(StringComparer.Ordinal);

static bool IsUnder(string path, string root) =>
    path.StartsWith(Path.TrimEndingDirectorySeparator(root) + Path.DirectorySeparatorChar, StringComparison.Ordinal);

static JsonNode Evaluate(string project, params string[] query)
{
    var output = Run(["dotnet", "msbuild", project, "-nologo", .. query]);
    // A single -getProperty prints the raw value; normalize to the JSON shape.
    if (query.Count(q => q.StartsWith("-get")) == 1 && query[0].StartsWith("-getProperty:"))
        return new JsonObject { ["Properties"] = new JsonObject { [query[0]["-getProperty:".Length..]] = output.Trim() } };
    return JsonNode.Parse(output)!;
}

static string Run(params string[] argv)
{
    var psi = new ProcessStartInfo(argv[0]) { RedirectStandardOutput = true, RedirectStandardError = true };
    foreach (var a in argv[1..]) psi.ArgumentList.Add(a);
    using var p = Process.Start(psi)!;
    var stdout = p.StandardOutput.ReadToEndAsync();
    var stderr = p.StandardError.ReadToEnd();
    p.WaitForExit();
    if (p.ExitCode != 0) throw new Exception($"{string.Join(' ', argv)} failed ({p.ExitCode}):\n{stdout.Result}{stderr}");
    return stdout.Result;
}

static string Hash(string file) => Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(file)));
// MSBuild-escape then XML-escape a literal value.
static string M(string s) => s.Replace("%", "%25").Replace("$", "%24").Replace("@", "%40").Replace(";", "%3B").Replace("'", "%27");
static string X(string s) => SecurityElement.Escape(s);
string Rel(string p) => Path.GetRelativePath(projectRoot, p);

static int Fail(string message)
{
    Console.Error.WriteLine($"connected: {message}");
    return 1;
}
