#!/usr/bin/env node
// Patches the Android project `cap add android` generated in the throwaway
// shell: pinned SDK levels, the build number and version, the app's permissions,
// deep links, and a checksum-pinned Gradle distribution. Each patch insists its
// anchor is present, so a Capacitor template change fails loudly instead of
// building something unreviewed. Stage 1 runs this file as a build step:
//   node shellPatch.js apply <shellRoot>
//   node shellPatch.js collect <shellRoot>
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

import { CAPACITOR_SHELL_TEMPLATE } from "./shellTemplate/index.js";

const SPEC_FILE = "vibe64-shell.json";
const UNSIGNED_APK = "android/app/build/outputs/apk/release/app-release-unsigned.apk";

function templateChanged(file, anchor) {
  return new Error(`The Capacitor Android template changed: ${file} has no ${anchor}. Update the Vibe64 shell patch before building.`);
}

function replaceOnce(text, pattern, replacement, file, anchor) {
  let count = 0;
  const result = text.replace(pattern, (...match) => {
    count += 1;
    return typeof replacement === "function" ? replacement(...match) : replacement;
  });
  if (count !== 1) throw templateChanged(file, anchor);
  return result;
}

function xmlText(value) {
  return String(value).replace(/&/gu, "&amp;").replace(/</gu, "&lt;").replace(/>/gu, "&gt;").replace(/"/gu, "&quot;");
}

// Android string resources: XML-escaped, with aapt's own quote and backslash escapes.
function resourceText(value) {
  const escaped = String(value).replace(/\\/gu, "\\\\").replace(/'/gu, "\\'").replace(/"/gu, "\\\"")
    .replace(/&/gu, "&amp;").replace(/</gu, "&lt;").replace(/>/gu, "&gt;");
  return /^[@?]/u.test(escaped) ? `\\${escaped}` : escaped;
}

function variablesGradle() {
  const pins = {
    minSdkVersion: CAPACITOR_SHELL_TEMPLATE.minSdk,
    compileSdkVersion: CAPACITOR_SHELL_TEMPLATE.compileSdk,
    targetSdkVersion: CAPACITOR_SHELL_TEMPLATE.targetSdk,
    ...CAPACITOR_SHELL_TEMPLATE.androidx
  };
  const lines = Object.entries(pins).map(([name, value]) => `    ${name} = ${typeof value === "number" ? value : `'${value}'`}`);
  return `// Generated by Vibe64 (${CAPACITOR_SHELL_TEMPLATE.id}).\next {\n${lines.join("\n")}\n}\n`;
}

function patchAppBuildGradle(text, spec) {
  const file = "app/build.gradle";
  let result = replaceOnce(text, /versionCode \d+/u, `versionCode ${spec.versionCode}`, file, "versionCode");
  result = replaceOnce(result, /versionName "[^"\n]*"/u, `versionName "${spec.version}"`, file, "versionName");
  result = replaceOnce(result, /minifyEnabled false/u, "minifyEnabled false", file, "release minifyEnabled");
  return result;
}

function patchStrings(text, spec) {
  const file = "res/values/strings.xml";
  const scheme = spec.deepLinkScheme || spec.applicationId;
  let result = replaceOnce(text, /<string name="app_name">[^<]*<\/string>/u, `<string name="app_name">${resourceText(spec.name)}</string>`, file, "app_name");
  result = replaceOnce(result, /<string name="title_activity_main">[^<]*<\/string>/u, `<string name="title_activity_main">${resourceText(spec.name)}</string>`, file, "title_activity_main");
  return replaceOnce(result, /<string name="custom_url_scheme">[^<]*<\/string>/u, `<string name="custom_url_scheme">${resourceText(scheme)}</string>`, file, "custom_url_scheme");
}

function linkFilters(spec) {
  const filters = [];
  if (spec.deepLinkScheme) {
    filters.push([
      "            <intent-filter>",
      "                <action android:name=\"android.intent.action.VIEW\" />",
      "                <category android:name=\"android.intent.category.DEFAULT\" />",
      "                <category android:name=\"android.intent.category.BROWSABLE\" />",
      `                <data android:scheme="${xmlText(spec.deepLinkScheme)}" />`,
      "            </intent-filter>"
    ].join("\n"));
  }
  if (spec.appLinkDomains.length) {
    filters.push([
      "            <intent-filter android:autoVerify=\"true\">",
      "                <action android:name=\"android.intent.action.VIEW\" />",
      "                <category android:name=\"android.intent.category.DEFAULT\" />",
      "                <category android:name=\"android.intent.category.BROWSABLE\" />",
      "                <data android:scheme=\"https\" />",
      ...spec.appLinkDomains.map((domain) => `                <data android:host="${xmlText(domain)}" />`),
      "            </intent-filter>"
    ].join("\n"));
  }
  return filters;
}

function patchManifest(text, spec) {
  const file = "AndroidManifest.xml";
  const permissions = spec.permissions.map((name) => `    <uses-permission android:name="${xmlText(name)}" />`).join("\n");
  let result = replaceOnce(
    text,
    /<!-- Permissions -->\s*(?:<uses-permission [^>]*\/>\s*)+/u,
    `<!-- Permissions (Vibe64 Packaging) -->\n\n${permissions}\n`,
    file,
    "the Permissions block"
  );
  const filters = linkFilters(spec);
  if (filters.length) {
    result = replaceOnce(
      result,
      /(<category android:name="android\.intent\.category\.LAUNCHER" \/>\s*<\/intent-filter>)/u,
      (match) => `${match}\n\n${filters.join("\n\n")}`,
      file,
      "the launcher intent-filter"
    );
  }
  return result;
}

function patchWrapperProperties(text) {
  const file = "gradle/wrapper/gradle-wrapper.properties";
  const { distributionUrl, distributionSha256Sum } = CAPACITOR_SHELL_TEMPLATE.gradle;
  let result = replaceOnce(text, /^distributionUrl=.*$/mu, `distributionUrl=${distributionUrl}`, file, "distributionUrl");
  result = result.replace(/^distributionSha256Sum=.*\n?/mu, "");
  return `${result.trimEnd()}\ndistributionSha256Sum=${distributionSha256Sum}\n`;
}

function patchCapacitorBuildGradle(text) {
  const file = "app/capacitor.build.gradle";
  return replaceOnce(text, /JavaVersion\.VERSION_(\d+)\s+targetCompatibility JavaVersion\.VERSION_(\d+)/u, (match, source, target) => {
    if (Number(source) !== CAPACITOR_SHELL_TEMPLATE.java || Number(target) !== CAPACITOR_SHELL_TEMPLATE.java) {
      throw templateChanged(file, `Java ${CAPACITOR_SHELL_TEMPLATE.java}`);
    }
    return match;
  }, file, "Java compatibility");
}

async function readSpec(shellRoot) {
  return JSON.parse(await readFile(path.join(shellRoot, SPEC_FILE), "utf8"));
}

async function rewrite(file, transform) {
  await writeFile(file, transform(await readFile(file, "utf8")));
}

async function applyShellPatch(shellRoot) {
  const spec = await readSpec(shellRoot);
  if (spec.template !== CAPACITOR_SHELL_TEMPLATE.id) throw new Error(`Shell spec ${spec.template} does not match ${CAPACITOR_SHELL_TEMPLATE.id}.`);
  const android = path.join(shellRoot, "android");
  await writeFile(path.join(android, "variables.gradle"), variablesGradle());
  await rewrite(path.join(android, "app", "build.gradle"), (text) => patchAppBuildGradle(text, spec));
  await rewrite(path.join(android, "app", "capacitor.build.gradle"), patchCapacitorBuildGradle);
  await rewrite(path.join(android, "app", "src", "main", "res", "values", "strings.xml"), (text) => patchStrings(text, spec));
  await rewrite(path.join(android, "app", "src", "main", "AndroidManifest.xml"), (text) => patchManifest(text, spec));
  await rewrite(path.join(android, "gradle", "wrapper", "gradle-wrapper.properties"), patchWrapperProperties);
}

// Copies Gradle's unsigned APK to `out/<package>-<version>-unsigned.apk`.
async function collectApk(shellRoot) {
  const spec = await readSpec(shellRoot);
  await mkdir(path.join(shellRoot, "out"), { recursive: true });
  await copyFile(path.join(shellRoot, UNSIGNED_APK), path.join(shellRoot, "out", spec.output));
}

async function main([command, shellRoot]) {
  if (!shellRoot || !path.isAbsolute(shellRoot)) throw new Error("Usage: shellPatch.js apply|collect <absolute shell folder>");
  if (command === "apply") return applyShellPatch(shellRoot);
  if (command === "collect") return collectApk(shellRoot);
  throw new Error(`Unknown shell patch command ${command}.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).catch((error) => {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  });
}

export {
  applyShellPatch,
  collectApk,
  patchAppBuildGradle,
  patchCapacitorBuildGradle,
  patchManifest,
  patchStrings,
  patchWrapperProperties,
  variablesGradle
};
