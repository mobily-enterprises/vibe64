// The cargo adapter: an untracked `.cargo/config.toml` at the session source patches each connected
// crate to the session's copy ([patch.crates-io], or [patch."<git url>"] for a git dependency) and
// points resolver.lockfile-path at an untracked copy of Cargo.lock, so Cargo builds the checkout
// under the crate's ordinary name while the tracked Cargo.toml and Cargo.lock stay as they are
// (Cargo 1.97 or later; the treatment examples/connected-development/cargo proves). Ordinary cargo
// commands run in the session source then use the checkout, and rebuild when it changes; no watcher.
// On Save, `bump` moves the tracked Cargo.lock (and Cargo.toml's requirement, if it must) to the
// checkout's version once that version is published.
import { readFile, realpath, writeFile } from "node:fs/promises";
import path from "node:path";
import semver from "semver";
import { vibe64Error } from "@local/vibe64-core/server/core";
import { errorSummary, lastLine } from "./commandOutput.js";
import { readDerivedFile, refuseTracked, removeDerivedFiles, writeDerivedFiles } from "./derivedFiles.js";

const CONFIG = ".cargo/config.toml";
const LOCK = ".development/cargo/Cargo.lock";
const MARKER = "# Generated by Vibe64 for connected development. Untracked; do not commit.";
const MINIMUM = Object.freeze([1, 97]);
const CARGO_TIMEOUT_MS = 15 * 60_000;
const CRATES_IO = new Set(["registry+https://github.com/rust-lang/crates.io-index", "sparse+https://index.crates.io/"]);
const UNPUBLISHED = /failed to select a version for the requirement|no matching package named|did not match any packages/u;
const DEPENDENCY_TABLE = /^\[(?:workspace\.)?(?:target\..+\.)?(?:dev-|build-)?dependencies\]$/u;


/** A TOML basic string: JSON's escapes are all valid TOML ones. */
function tomlString(text) {
  return JSON.stringify(String(text));
}

/** The `[package]` name and version of a Cargo.toml, when it states both. */
function packageOf(text) {
  const found = packageFields(text);
  return found.name && found.version ? found : null;
}

/** The `[package]` name and version a Cargo.toml states; either may be missing. */
function packageFields(text) {
  const found = { name: "", version: null };
  let inPackage = false;
  for (const raw of String(text).split(/\r?\n/u)) {
    const line = raw.trim();
    if (line.startsWith("[")) {
      inPackage = line.replace(/\s*#.*$/u, "") === "[package]";
      continue;
    }
    const match = inPackage ? /^(name|version)\s*=\s*"([^"]+)"\s*(?:#.*)?$/u.exec(line) : null;
    if (match) found[match[1]] = match[2];
  }
  return found;
}

/** Each connection's crate: its name and version (from its Cargo.toml) and its checkout. */
async function connectedCrates(connections) {
  const crates = [];
  for (const connection of connections) {
    const root = await realpath(connection.sourceRoot).catch(() => "");
    const found = packageOf(root ? await readFile(path.join(root, "Cargo.toml"), "utf8").catch(() => "") : "");
    if (!found) {
      throw vibe64Error(
        `Connected ${connection.name}: ${connection.sourceRoot} has no Cargo.toml stating a [package] name and version, so Cargo cannot patch it ` +
        "(a workspace of several crates is not supported).",
        "vibe64_connected_cargo_crate_missing"
      );
    }
    const twin = crates.find(entry => entry.name === found.name);
    if (twin) {
      throw vibe64Error(
        `Connected ${connection.name} and ${twin.connection.name} both hold the crate ${found.name}; connect it once.`,
        "vibe64_connected_cargo_duplicate"
      );
    }
    crates.push({ connection, name: found.name, version: found.version, root });
  }
  return crates;
}

function patchLine(crate) {
  return `${tomlString(crate.name)} = { path = ${tomlString(crate.root)} }`;
}

function lockfileLine(sessionSourceRoot) {
  return `lockfile-path = ${tomlString(path.join(sessionSourceRoot, LOCK))}`;
}

/** Fails unless a `.cargo/config.toml` there is absent or Vibe64's own. */
function refuseForeignConfig(connection, sessionSourceRoot, text) {
  if (text !== null && text.split("\n")[0] !== MARKER) {
    throw vibe64Error(
      `Connected ${connection.name}: ${path.join(sessionSourceRoot, CONFIG)} was not written by Vibe64, so Vibe64 will not replace it. ` +
      "Move its settings to a .cargo/config.toml in a parent folder or in CARGO_HOME, then prepare the workspace again.",
      "vibe64_connected_cargo_config_foreign"
    );
  }
}

async function cargoJson({ connection, runCommand, args, cwd }) {
  const result = await runCommand({ command: "cargo", args, cwd, timeout: CARGO_TIMEOUT_MS });
  let parsed = null;
  try {
    parsed = JSON.parse(String(result?.stdout || ""));
  } catch {
    parsed = null;
  }
  if (result?.ok !== true || !parsed) {
    throw vibe64Error(
      `Connected ${connection.name}: cargo ${args.join(" ")} failed. ${errorSummary(result?.stderr || result?.error)}`.trim(),
      "vibe64_connected_cargo_metadata_failed"
    );
  }
  return parsed;
}

async function refuseOldCargo({ connection, runCommand, cwd }) {
  const result = await runCommand({ command: "cargo", args: ["--version"], cwd, timeout: 60_000 });
  const match = /^cargo (\d+)\.(\d+)\.(\d+)/u.exec(String(result?.stdout || "").trim());
  if (result?.ok !== true || !match) {
    throw vibe64Error(
      `Connected ${connection.name}: cargo --version failed. ${lastLine(result?.stderr || result?.error)}`.trim(),
      "vibe64_connected_cargo_unavailable"
    );
  }
  const [major, minor] = [Number(match[1]), Number(match[2])];
  if (major < MINIMUM[0] || (major === MINIMUM[0] && minor < MINIMUM[1])) {
    throw vibe64Error(
      `Connected ${connection.name} needs Cargo ${MINIMUM.join(".")} or later (resolver.lockfile-path keeps the tracked Cargo.lock as it is); ` +
      `this session has cargo ${match[1]}.${match[2]}.${match[3]}.`,
      "vibe64_connected_cargo_too_old"
    );
  }
}

/** The [patch] table for a dependency's source: crates.io, a git URL, or "" for none. */
function patchKey(source) {
  if (CRATES_IO.has(source)) return "crates-io";
  return source.startsWith("git+") ? tomlString(source.slice(4).split(/[?#]/u)[0]) : "";
}

/** The [patch] table each crate belongs in, from where the session's packages declare it. */
function patchTables(connection, crates, metadata) {
  const tables = new Map();
  for (const crate of crates) {
    const sources = new Set();
    for (const entry of metadata.packages || []) {
      for (const dependency of entry.dependencies || []) {
        if (dependency.name === crate.name) sources.add(dependency.source || "");
      }
    }
    if (!sources.size) {
      throw vibe64Error(
        `Connected ${crate.connection.name}: no package of this session depends on the crate ${crate.name}, so there is nothing to patch.`,
        "vibe64_connected_cargo_unused"
      );
    }
    if (sources.size > 1) {
      throw vibe64Error(
        `Connected ${crate.connection.name}: this session's packages take ${crate.name} from more than one source (${[...sources].join(", ")}).`,
        "vibe64_connected_cargo_sources"
      );
    }
    const [source] = sources;
    const key = patchKey(source);
    if (!key) {
      throw vibe64Error(
        `Connected ${connection.name}: ${crate.name} comes from ${source || "a path"}, which Vibe64 cannot patch to the connected checkout.`,
        "vibe64_connected_cargo_source_unsupported"
      );
    }
    tables.set(key, [...(tables.get(key) || []), crate]);
  }
  return tables;
}

function configText(sessionSourceRoot, tables) {
  const keys = [...tables.keys()].sort((a, b) => Number(b === "crates-io") - Number(a === "crates-io") || a.localeCompare(b));
  const lines = [MARKER, "", "[resolver]", lockfileLine(sessionSourceRoot)];
  for (const key of keys) {
    lines.push("", `[patch.${key}]`, ...tables.get(key).sort((a, b) => a.name.localeCompare(b.name)).map(patchLine));
  }
  return `${lines.join("\n")}\n`;
}

async function applyCargo({ connection, connections, sessionSourceRoot, runCommand, writeGitExcludes }) {
  const crates = await connectedCrates(connections);
  refuseForeignConfig(connection, sessionSourceRoot, await readDerivedFile(sessionSourceRoot, CONFIG));
  await refuseTracked({ connection, tree: sessionSourceRoot, paths: [CONFIG, LOCK], runCommand });
  await refuseOldCargo({ connection, runCommand, cwd: sessionSourceRoot });
  const declared = await cargoJson({
    connection,
    runCommand,
    args: ["metadata", "--format-version", "1", "--no-deps"],
    cwd: sessionSourceRoot
  });
  const trackedLock = await readDerivedFile(sessionSourceRoot, "Cargo.lock");
  // Every apply starts the derived lock from the tracked one, so the two differ only by the patched crates.
  await writeDerivedFiles({
    connection,
    tree: sessionSourceRoot,
    files: {
      [CONFIG]: configText(sessionSourceRoot, patchTables(connection, crates, declared)),
      ...(trackedLock === null ? {} : { [LOCK]: trackedLock })
    },
    runCommand,
    writeGitExcludes: (tree, paths) => writeGitExcludes(tree, [...new Set([...paths, LOCK])])
  });
  // A lock entry at another version holds Cargo to it and leaves the patch unused: move the derived
  // lock's entry to the checkout's version, which only the patch provides.
  for (const crate of crates) {
    const entries = trackedLock === null ? [] : lockEntries(trackedLock, crate.name);
    if (!entries.length || entries.some(entry => entry.version === crate.version)) continue;
    const moved = await runCommand({
      command: "cargo",
      args: ["update", "--package", `${crate.name}@${entries[0].version}`, "--precise", crate.version],
      cwd: sessionSourceRoot,
      timeout: CARGO_TIMEOUT_MS
    });
    if (moved?.ok !== true) {
      throw vibe64Error(
        `Connected ${crate.connection.name}: Cargo cannot build the checkout's ${crate.name} ${crate.version} in place of the locked ${entries[0].version}: ${errorSummary(moved?.stderr || moved?.error)}`,
        "vibe64_connected_cargo_patch_unusable"
      );
    }
  }
  // Cargo applies the patch to the derived lock.
  await cargoJson({ connection, runCommand, args: ["metadata", "--format-version", "1"], cwd: sessionSourceRoot });
  if (await readDerivedFile(sessionSourceRoot, "Cargo.lock") !== trackedLock) {
    if (trackedLock !== null) await writeFile(path.join(sessionSourceRoot, "Cargo.lock"), trackedLock);
    throw vibe64Error(
      `Connected ${connection.name}: Cargo wrote the tracked Cargo.lock instead of ${LOCK}, so resolver.lockfile-path is not in effect; ` +
      "Vibe64 put Cargo.lock back.",
      "vibe64_connected_cargo_lock_rewritten"
    );
  }
  const own = crates.find(entry => entry.connection.repository === connection.repository);
  return { lines: [`[Connected] ${connection.name}: crate ${own.name} ${own.version} patched to ${own.root} through ${CONFIG}.`] };
}

/** The derived lock's entries for a crate: { version, source } each. */
function lockEntries(text, name) {
  return String(text).split(/^\[\[package\]\]$/mu).slice(1).map(block => ({
    name: /^name = "([^"]+)"$/mu.exec(block),
    version: /^version = "([^"]+)"$/mu.exec(block),
    source: /^source = "([^"]+)"$/mu.exec(block)
  })).filter(entry => entry.name && entry.name[1] === name).map(entry => ({
    version: entry.version ? entry.version[1] : "",
    source: entry.source ? entry.source[1] : ""
  }));
}

/** Whether `cargo metadata --locked` resolves the crate from the checkout alone, for a session package. */
async function resolvedFromCheckout({ connection, crate, sessionSourceRoot, runCommand }) {
  let metadata;
  const trackedLock = await readDerivedFile(sessionSourceRoot, "Cargo.lock");
  try {
    metadata = await cargoJson({ connection, runCommand, args: ["metadata", "--format-version", "1", "--locked"], cwd: sessionSourceRoot });
  } catch (error) {
    return `cargo metadata --locked does not resolve with the derived lock (${error.message}); prepare the workspace again.`;
  }
  if (await readDerivedFile(sessionSourceRoot, "Cargo.lock") !== trackedLock) {
    return "cargo changed the tracked Cargo.lock, so resolver.lockfile-path is not in effect.";
  }
  const manifest = path.join(crate.root, "Cargo.toml");
  const sameName = [];
  for (const entry of metadata.packages || []) {
    if (entry.name !== crate.name) continue;
    sameName.push({ ...entry, manifest: await realpath(entry.manifest_path).catch(() => entry.manifest_path) });
  }
  const connected = sameName.find(entry => entry.source === null && entry.manifest === manifest);
  if (!connected) {
    const other = sameName[0];
    const requirement = (metadata.packages || []).flatMap(entry => entry.dependencies || []).find(entry => entry.name === crate.name);
    if (!other) return `${crate.name} is not in this session's crate graph.`;
    const why = other.version !== crate.version && requirement
      ? `the checkout's ${crate.version} must meet the requirement ${requirement.req}`
      : `Cargo did not apply the patch in ${CONFIG}`;
    return `${crate.name} resolves to ${other.version} from ${other.source || other.manifest}, not ${crate.root}: ${why}.`;
  }
  if (sameName.length > 1) return `${crate.name} also resolves from another source, so the build does not use only ${crate.root}.`;
  const members = new Set(metadata.workspace_members || []);
  const dependedOn = (metadata.resolve?.nodes || [])
    .filter(node => members.has(node.id))
    .some(node => (node.deps || []).some(dependency => dependency.pkg === connected.id));
  return dependedOn ? "" : `no package of this session depends on the connected ${crate.name}.`;
}

async function proveCargo({ connection, sessionSourceRoot, runCommand }) {
  let crate;
  try {
    [crate] = await connectedCrates([connection]);
  } catch (error) {
    return { inEffect: false, reason: String(error.message) };
  }
  const config = await readDerivedFile(sessionSourceRoot, CONFIG);
  if (config === null) return { inEffect: false, reason: `${CONFIG} is missing in the session source; prepare the workspace to write it.` };
  const lines = config.split("\n");
  if (lines[0] !== MARKER) return { inEffect: false, reason: `${CONFIG} in the session source was not written by Vibe64.` };
  if (!lines.includes(patchLine(crate)) || !lines.includes(lockfileLine(sessionSourceRoot))) {
    return { inEffect: false, reason: `${CONFIG} does not patch ${crate.name} to this session's copy ${crate.root}; prepare the workspace again.` };
  }
  const lock = await readDerivedFile(sessionSourceRoot, LOCK);
  if (lock === null) return { inEffect: false, reason: `the derived lock ${LOCK} is missing; prepare the workspace again.` };
  // In preparation Cargo itself answers, and says why.
  if (runCommand) {
    const reason = await resolvedFromCheckout({ connection, crate, sessionSourceRoot, runCommand });
    return { inEffect: !reason, reason };
  }
  const entries = lockEntries(lock, crate.name);
  if (entries.some(entry => entry.version === crate.version && !entry.source)) return { inEffect: true, reason: "" };
  const published = entries.find(entry => entry.source);
  return {
    inEffect: false,
    reason: published
      ? `${LOCK} takes ${crate.name} ${published.version} from ${published.source}, not the checkout's ${crate.version}: ` +
        "prepare the workspace again, or make the checkout's version meet the app's requirement."
      : `${LOCK} has no ${crate.name} ${crate.version} from the checkout; prepare the workspace again.`
  };
}

/** With no Cargo connection left, Vibe64's config and derived lock go, and Cargo builds the published crates. */
async function restoreCargo({ connections, sessionSourceRoot, writeGitExcludes }) {
  if (connections.length) return [];
  const config = await readDerivedFile(sessionSourceRoot, CONFIG);
  if (config === null || config.split("\n")[0] !== MARKER) return [];
  const removed = await removeDerivedFiles({ tree: sessionSourceRoot, paths: [CONFIG, LOCK], writeGitExcludes });
  return [`[Connected] No Cargo connection remains: removed ${removed.join(" and ")}, so Cargo builds the published crates again.`];
}

/** Where the root Cargo.toml requires the crate: each line's index and requirement (null when not a plain version). */
function requirementsOf(text, name) {
  const found = [];
  let inTable = false;
  for (const [index, raw] of String(text).split("\n").entries()) {
    const line = raw.trim();
    if (line.startsWith("[")) {
      inTable = DEPENDENCY_TABLE.test(line.replace(/\s*#.*$/u, ""));
      continue;
    }
    const value = inTable && (line.startsWith(`${name} `) || line.startsWith(`${name}=`) || line.startsWith(`"${name}"`))
      ? /^"?[^"=\s]+"?\s*=\s*(.*)$/u.exec(line)
      : null;
    if (!value) continue;
    const requirement = /^"([^"]+)"/u.exec(value[1]) || /\bversion\s*=\s*"([^"]+)"/u.exec(value[1]);
    found.push({ index, requirement: requirement ? requirement[1] : null });
  }
  return found;
}

/** Whether Cargo's requirement admits the version; null when Vibe64 cannot read the requirement. */
function admits(requirement, version) {
  const range = semver.validRange(requirement.split(",").map(part => part.trim()).map(part => (/^\d/u.test(part) ? `^${part}` : part)).join(" "));
  return range ? semver.satisfies(version, range) : null;
}

/** The root Cargo.toml with each requirement the version falls outside moved to it, keeping a `=` or `~`. */
function movedManifest(text, name, version) {
  const lines = String(text).split("\n");
  for (const { index, requirement } of requirementsOf(text, name)) {
    if (!requirement || admits(requirement, version) !== false) continue;
    const operator = /^([=~^]?)\s*\d[^,]*$/u.exec(requirement.trim());
    lines[index] = lines[index].replace(`"${requirement}"`, `"${operator ? operator[1] : ""}${version}"`);
  }
  return lines.join("\n");
}

/**
 * The crate's version in the connected copy beside the one Staging and Production build: the tracked
 * Cargo.lock's registry entry (null without one, or with several). Files only.
 */
async function lockedCargo({ connection, sessionSourceRoot }) {
  const root = await realpath(connection.sourceRoot).catch(() => "");
  const { name, version } = packageFields(root ? await readFile(path.join(root, "Cargo.toml"), "utf8").catch(() => "") : "");
  if (!name) return [];
  const lock = await readDerivedFile(sessionSourceRoot, "Cargo.lock");
  if (lock === null) {
    return requirementsOf(await readDerivedFile(sessionSourceRoot, "Cargo.toml") || "", name).length
      ? [{ package: name, connected: version, locked: null }]
      : [];
  }
  const entries = lockEntries(lock, name);
  if (!entries.length) return [];
  const versions = [...new Set(entries.filter(entry => entry.source).map(entry => entry.version))];
  return [{ package: name, connected: version, locked: versions.length === 1 ? versions[0] : null }];
}

/**
 * On Save: moves the tracked Cargo.lock to the checkout's version once Cargo finds it published
 * (and Cargo.toml's requirement when the version falls outside it), then puts the checkout in effect
 * again. An unpublished version, or a registry Cargo cannot reach, changes nothing.
 */
async function bumpCargo(context) {
  const { connection, sessionSourceRoot, runCommand } = context;
  const manifestPath = path.join(sessionSourceRoot, "Cargo.toml");
  const lockPath = path.join(sessionSourceRoot, "Cargo.lock");
  const bumped = [];
  const lines = [];
  for (const entry of await lockedCargo(context)) {
    if (!entry.connected || !entry.locked || entry.connected === entry.locked) continue;
    const manifest = await readFile(manifestPath, "utf8");
    const lock = await readFile(lockPath, "utf8");
    const moved = movedManifest(manifest, entry.package, entry.connected);
    if (moved !== manifest) await writeFile(manifestPath, moved);
    // Cargo reads configuration from its working directory: run from the connected copy, the
    // session's patch is not read, so the tracked Cargo.lock takes the published version.
    const result = await runCommand({
      command: "cargo",
      args: ["update", "--manifest-path", manifestPath, "--package", `${entry.package}@${entry.locked}`, "--precise", entry.connected],
      cwd: connection.sourceRoot,
      timeout: CARGO_TIMEOUT_MS
    });
    if (result?.ok !== true) {
      if (moved !== manifest) await writeFile(manifestPath, manifest);
      if (await readFile(lockPath, "utf8") !== lock) await writeFile(lockPath, lock);
      const output = `${result?.stderr || ""}\n${result?.stdout || ""}`;
      if (!UNPUBLISHED.test(output)) {
        lines.push(`[Connected] ${connection.name}: could not check whether ${entry.package} ${entry.connected} is published: ${lastLine(result?.stderr || result?.error) || "cargo update failed"}.`);
      }
      continue;
    }
    bumped.push({ package: entry.package, from: entry.locked, to: entry.connected });
    lines.push(`[Connected] ${connection.name}: Staging and Production now use the published ${entry.package} ${entry.connected}.`);
  }
  if (!bumped.length) return { bumped, lines };
  // The derived lock starts again from the moved tracked one.
  try {
    lines.push(...(await applyCargo(context)).lines);
  } catch (error) {
    lines.push(`[Connected] ${connection.name}: prepare the workspace again to put the checkout back in effect: ${error.message}`);
  }
  return { bumped, lines };
}

const cargoAdapter = Object.freeze({
  type: "cargo",
  runtimeRequirements: Object.freeze(["rust", "git"]),
  apply: applyCargo,
  proof: proveCargo,
  restore: restoreCargo,
  locked: lockedCargo,
  bump: bumpCargo
});

export { cargoAdapter };
