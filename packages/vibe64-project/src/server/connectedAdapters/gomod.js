// The gomod adapter: Go's own workspace mechanism. An untracked go.work at the session source's
// module root `use`s the module and every connected Go module checkout, so each connected module
// replaces its required version and go.mod and go.sum stay unchanged; Go keeps any other checksums
// the workspace needs in go.work.sum, which is kept out of Git as well. The proof asks Go which
// workspace it uses and where each connected module's packages are built from. No watcher is
// needed: Go reads a workspace module's source in place, so a save takes effect at the next build.
//
// Staging and Production build without the workspace, from the tracked go.mod and go.sum: `locked`
// reads the version they record, and on Save `bump` moves them to the connected copy's latest
// version tag once Go can fetch that version (it is published), never onto an untagged commit.
import { readFile, realpath, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import semver from "semver";
import { vibe64Error } from "@local/vibe64-core/server/core";
import { readDerivedFile, refuseTracked, removeDerivedFiles, writeDerivedFiles } from "./derivedFiles.js";

const WORK_FILE = "go.work";
const WORK_SUM_FILE = "go.work.sum";
const MARKER = "// Generated by Vibe64 for this session's connected Go modules. Untracked; do not commit.";
const GO_TIMEOUT_MS = 10 * 60_000;
const GIT_TIMEOUT_MS = 60_000;
// What Go says when a proxy or the repository answers that the version does not exist.
// (A file:// proxy without the version has no .info for it.)
const UNPUBLISHED = /unknown revision|invalid version|no matching versions|not found|410 Gone|\.info: no such file or directory/iu;
const LIST_FORMAT = "{{if .Module}}{{.Module.Path}}\t{{.Module.Dir}}\t{{.ImportPath}}\t{{.Dir}}{{end}}";

/** A go.mod's module path and go version, or null when the folder is not a Go module. */
async function readGoMod(dir) {
  const text = await readFile(path.join(dir, "go.mod"), "utf8").catch(error => {
    if (error?.code === "ENOENT") return null;
    throw error;
  });
  if (text === null) return null;
  let modulePath = "";
  let goVersion = "";
  for (const raw of text.split("\n")) {
    const fields = raw.replace(/\/\/.*$/u, "").trim().split(/\s+/u);
    if (fields.length !== 2) continue;
    if (fields[0] === "module") modulePath = fields[1].replace(/^["`]|["`]$/gu, "");
    if (fields[0] === "go") goVersion = fields[1];
  }
  return modulePath ? { modulePath, goVersion } : null;
}

function versionLess(a, b) {
  const left = String(a).split(".").map(part => Number.parseInt(part, 10) || 0);
  const right = String(b).split(".").map(part => Number.parseInt(part, 10) || 0);
  for (let index = 0; index < Math.max(left.length, right.length); index += 1) {
    if ((left[index] || 0) !== (right[index] || 0)) return (left[index] || 0) < (right[index] || 0);
  }
  return false;
}

function within(dir, root) {
  const relative = path.relative(root, dir);
  return relative === "" || (!relative.startsWith("..") && !path.isAbsolute(relative));
}

/**
 * The workspace the session source needs now: its module, every connected module and the go.work
 * text that uses them. Refuses a connection that is not one distinct Go module.
 */
async function goWorkspace({ connections, sessionSourceRoot }) {
  const root = await realpath(sessionSourceRoot);
  const app = await readGoMod(root);
  if (!app) {
    throw vibe64Error(
      `The session source ${root} has no go.mod at its root, so Vibe64 cannot connect Go modules to it.`,
      "vibe64_connected_gomod_no_module"
    );
  }
  const modules = [];
  for (const connection of connections) {
    const sourceRoot = await realpath(connection.sourceRoot);
    const info = await readGoMod(sourceRoot);
    if (!info) {
      throw vibe64Error(
        `Connected ${connection.name}: ${sourceRoot} has no go.mod with a module line, so it is not a Go module.`,
        "vibe64_connected_gomod_not_module"
      );
    }
    if (info.modulePath === app.modulePath) {
      throw vibe64Error(
        `Connected ${connection.name}: ${info.modulePath} is the session's own module.`,
        "vibe64_connected_gomod_same_module"
      );
    }
    const other = modules.find(entry => entry.modulePath === info.modulePath);
    if (other) {
      throw vibe64Error(
        `Connected ${connection.name}: ${info.modulePath} is already connected as ${other.name}.`,
        "vibe64_connected_gomod_duplicate"
      );
    }
    modules.push({ name: connection.name, repository: connection.repository, sourceRoot, ...info });
  }
  const goVersion = modules.reduce((highest, entry) => versionLess(highest, entry.goVersion) ? entry.goVersion : highest, app.goVersion);
  const text = [
    MARKER,
    "",
    ...(goVersion ? [`go ${goVersion}`, ""] : []),
    "use (",
    "\t.",
    ...modules.map(entry => `\t${JSON.stringify(entry.sourceRoot)} // ${entry.modulePath}`),
    ")",
    ""
  ].join("\n");
  return { root, modules, text };
}

/** A go.work Vibe64 did not write stays the person's own. */
function ours(text) {
  return text !== null && text.split("\n")[0] === MARKER;
}

/** A go command's output, or why it failed. */
async function go(runCommand, root, args) {
  const result = await runCommand({ command: "go", args, cwd: root, timeout: GO_TIMEOUT_MS });
  if (result?.ok === true) return { output: String(result.stdout || ""), failed: "" };
  const detail = String(result?.stderr || result?.error || "").trim().split("\n").slice(-3).join(" ");
  return { output: "", failed: `go ${args.join(" ")} failed${detail ? `: ${detail}` : ""}` };
}

async function applyGomod({ connection, connections, sessionSourceRoot, runCommand, writeGitExcludes }) {
  const { root, modules, text } = await goWorkspace({ connections, sessionSourceRoot });
  const existing = await readDerivedFile(root, WORK_FILE);
  if (existing !== null && !ours(existing)) {
    throw vibe64Error(
      `Connected ${connection.name}: ${path.join(root, WORK_FILE)} was not written by Vibe64, so it will not replace it. Move it away.`,
      "vibe64_connected_gomod_work_foreign"
    );
  }
  // Go writes go.work.sum beside the workspace; a tracked one would change with the session's work.
  await refuseTracked({ connection, tree: root, paths: [WORK_SUM_FILE], runCommand });
  await writeDerivedFiles({ connection, tree: root, files: { [WORK_FILE]: text }, runCommand, writeGitExcludes });
  await writeGitExcludes(root, [WORK_FILE, WORK_SUM_FILE]);
  const own = modules.find(entry => entry.repository === connection.repository);
  return { lines: [`[Connected] ${connection.name}: ${own.modulePath} in effect from ${own.sourceRoot} through ${WORK_FILE}.`] };
}

async function proveGomod({ connection, connections, sessionSourceRoot, runCommand }) {
  let workspace;
  try {
    workspace = await goWorkspace({ connections, sessionSourceRoot });
  } catch (error) {
    return { inEffect: false, reason: String(error?.message || error) };
  }
  const { root, modules, text } = workspace;
  const own = modules.find(entry => entry.repository === connection.repository);
  const workPath = path.join(root, WORK_FILE);
  const current = await readDerivedFile(root, WORK_FILE);
  if (current === null) return { inEffect: false, reason: `${workPath} is missing; prepare the workspace to write it.` };
  if (current !== text) {
    return { inEffect: false, reason: `${workPath} no longer uses this session's connected Go modules; prepare the workspace again.` };
  }
  if (!runCommand) return { inEffect: true, reason: "" };
  const env = await go(runCommand, root, ["env", "GOWORK"]);
  if (env.failed) return { inEffect: false, reason: env.failed };
  const active = env.output.trim();
  if (await realpath(active).catch(() => active) !== workPath) {
    return { inEffect: false, reason: `Go uses the workspace "${active}", not ${workPath}; unset GOWORK.` };
  }
  const listed = await go(runCommand, root, ["list", "-deps", "-f", LIST_FORMAT, "./..."]);
  if (listed.failed) return { inEffect: false, reason: listed.failed };
  let used = 0;
  for (const line of listed.output.split("\n")) {
    const [modulePath, moduleDir, importPath, dir] = line.split("\t");
    if (modulePath !== own.modulePath || dir === undefined) continue;
    const resolvedModule = await realpath(moduleDir).catch(() => moduleDir);
    const resolvedDir = await realpath(dir).catch(() => dir);
    if (resolvedModule !== own.sourceRoot || !within(resolvedDir, own.sourceRoot)) {
      return {
        inEffect: false,
        reason: `${own.modulePath} package ${importPath} is built from ${dir}, not the connected checkout ${own.sourceRoot}.`
      };
    }
    used += 1;
  }
  if (!used) {
    return { inEffect: false, reason: `No package of ${own.modulePath} is in the build of ./..., so the session does not use it.` };
  }
  return { inEffect: true, reason: "" };
}

/** The versions a go.mod requires, by module path (single and block require lines). */
function requiredVersions(text) {
  const versions = new Map();
  let block = false;
  for (const raw of text.split("\n")) {
    const line = raw.replace(/\/\/.*$/u, "").trim();
    // A pattern, not the literal: the package-boundary check reads `require (` + a quote as an import.
    if (/^require\s*\($/u.test(line)) {
      block = true;
      continue;
    }
    if (block && line === ")") {
      block = false;
      continue;
    }
    const single = /^require\s+(\S+)\s+(\S+)$/u.exec(line);
    const fields = block ? line.split(/\s+/u) : [];
    if (single) versions.set(single[1].replace(/^"|"$/gu, ""), single[2]);
    else if (fields.length === 2) versions.set(fields[0].replace(/^"|"$/gu, ""), fields[1]);
  }
  return versions;
}

/**
 * What Staging and Production install for this connection: the version the tracked go.mod requires.
 * Go versions are tags, so the connected copy's files name none. Reads files only.
 */
async function lockedGomod({ connection, sessionSourceRoot }) {
  const info = await readGoMod(await realpath(connection.sourceRoot));
  const goMod = await readFile(path.join(await realpath(sessionSourceRoot), "go.mod"), "utf8").catch(() => null);
  if (!info || goMod === null) return [];
  const locked = requiredVersions(goMod).get(info.modulePath);
  return locked === undefined ? [] : [{ package: info.modulePath, connected: null, locked }];
}

async function snapshot(files) {
  return Promise.all(files.map(async file => [file, await readFile(file, "utf8").catch(() => null)]));
}

async function putBack(saved) {
  for (const [file, text] of saved) {
    if (text === null) await rm(file, { force: true });
    else if (await readFile(file, "utf8").catch(() => null) !== text) await writeFile(file, text);
  }
}

/**
 * On Save: moves the tracked go.mod and go.sum to the connected copy's latest version tag when it is
 * newer than what they require and Go can fetch it (`GOWORK=off go get`, which fails for a version
 * the proxy or repository lacks). Anything else changes nothing and says why.
 */
async function bumpGomod(context) {
  const { connection, sessionSourceRoot, runCommand } = context;
  const [entry] = await lockedGomod(context);
  if (!entry) return { bumped: [], lines: [] };
  const say = text => ({ bumped: [], lines: [`[Connected] ${connection.name}: ${text}`] });
  const tagged = await runCommand({
    command: "git",
    args: ["describe", "--tags", "--abbrev=0", "--match", "v*"],
    cwd: await realpath(connection.sourceRoot),
    timeout: GIT_TIMEOUT_MS
  });
  const version = tagged?.ok === true ? String(tagged.stdout || "").trim() : "";
  if (!semver.valid(version)) {
    return say(`the connected copy has no version tag of ${entry.package}, so Staging and Production keep ${entry.locked}.`);
  }
  if (version === entry.locked) return { bumped: [], lines: [] };
  if (semver.valid(entry.locked) && !semver.gt(version, entry.locked)) {
    return say(`the connected copy's ${entry.package} ${version} is older than the ${entry.locked} Staging and Production use; `
      + "nothing changed.");
  }
  const root = await realpath(sessionSourceRoot);
  const saved = await snapshot([path.join(root, "go.mod"), path.join(root, "go.sum")]);
  const got = await runCommand({
    command: "go",
    args: ["get", `${entry.package}@${version}`],
    cwd: root,
    timeout: GO_TIMEOUT_MS,
    env: { GOWORK: "off" }
  });
  if (got?.ok !== true) {
    await putBack(saved);
    const detail = (String(got?.stderr || got?.error || "").trim().split("\n").at(-1) || "go get failed").replace(/\.$/u, "");
    return UNPUBLISHED.test(detail)
      ? say(`${entry.package} ${version} is not published, so Staging and Production keep ${entry.locked}.`)
      : say(`could not check whether ${entry.package} ${version} is published: ${detail}.`);
  }
  const lines = [`[Connected] ${connection.name}: Staging and Production now use the published ${entry.package} ${version}.`];
  // go get may raise go.mod's go line, which go.work follows.
  await applyGomod(context).catch(error => lines.push(
    `[Connected] ${connection.name}: could not put the connection back in effect: ${String(error?.message || error)}`
  ));
  return { bumped: [{ package: entry.package, from: entry.locked, to: version }], lines };
}

/** With no Go module connected any more, Vibe64's go.work (and Go's go.work.sum) go. */
async function restoreGomod({ connections, sessionSourceRoot, writeGitExcludes }) {
  if (connections.length) return [];
  if (!ours(await readDerivedFile(sessionSourceRoot, WORK_FILE))) return [];
  await removeDerivedFiles({ tree: sessionSourceRoot, paths: [WORK_FILE, WORK_SUM_FILE], writeGitExcludes });
  return [`[Connected] No Go module is connected any more: removed ${WORK_FILE}.`];
}

const gomodAdapter = Object.freeze({
  type: "gomod",
  runtimeRequirements: Object.freeze(["go", "git"]),
  apply: applyGomod,
  proof: proveGomod,
  restore: restoreGomod,
  locked: lockedGomod,
  bump: bumpGomod
});

export { gomodAdapter };
