// The gradle adapter. An init script makes the session's Gradle build a composite that includes
// each connected checkout (Settings.includeBuild from settingsEvaluated), so Gradle substitutes the
// dependency with the included project of the same group:name and builds it from source on every
// run: a saved change needs no new preparation. The script sits in the init.d of the session's own
// Gradle user home (.development/gradle-home, untracked and kept out of Git), which Vibe64 gives
// every command of the session as GRADLE_USER_HOME (vibe64-execution's connectedGradleEnv), so the
// session's ordinary Gradle commands use it with no flag and nothing tracked changes. That home
// links the default home's gradle.properties and init scripts, so the person's own settings still
// apply, and reads dependencies first from the shared read-only cache, a copy of the default
// home's that apply refreshes at most once a day. Since the build reads the source in place, the
// adapter has no watch. On Save, a version the checkout declares that the project's repositories
// publish moves into the tracked build scripts (and gradle.lockfile), so Staging and Production use it.
import { cp, lstat, mkdir, readdir, readFile, readlink, realpath, rename, rm, stat, symlink, writeFile } from "node:fs/promises";
import path from "node:path";
import { vibe64Error } from "@local/vibe64-core/server/core";
import {
  CONNECTED_GRADLE_HOME,
  CONNECTED_GRADLE_INIT,
  CONNECTED_GRADLE_RO_CURRENT,
  connectedGradleEnv,
  connectedGradleReadOnlyCacheRoot
} from "@local/vibe64-execution/server/connectedGradleEnv";
import { notInEffect } from "./adapterResults.js";
import { readDerivedFile, refuseTracked, removeDerivedFiles, writeDerivedFiles } from "./derivedFiles.js";

const INIT = path.posix.join(CONNECTED_GRADLE_HOME, CONNECTED_GRADLE_INIT);
// Where an earlier Vibe64 wrote the script, for commands that passed it with -I.
const EARLIER_INIT = ".development/connected.init.gradle.kts";
const PROOF_INIT = ".development/connected-proof.init.gradle.kts";
const PUBLISHED_INIT = ".development/connected-published.init.gradle.kts";
const GENERATED = Object.freeze([CONNECTED_GRADLE_HOME, PROOF_INIT, PUBLISHED_INIT]);
const DAY_MS = 24 * 60 * 60_000;
// A published generation of the read-only cache outlives every build that can still be reading it.
const GENERATION_KEPT_MS = 7 * DAY_MS;
const GENERATION = /^generation-(\d+)$/u;
const MARKER = "// Generated by Vibe64 for connected development. Do not commit.";
const BUILD_FILES = Object.freeze(["settings.gradle.kts", "settings.gradle", "build.gradle.kts", "build.gradle"]);
const GRADLE_TIMEOUT_MS = 20 * 60_000;
const ARTIFACT_LINE = "CONNECTED-ARTIFACT\t";
const SCRIPT_DEPTH = 3;
const SKIPPED_DIRS = new Set([".git", ".gradle", ".kotlin", ".development", "build", "node_modules"]);
const BUILD_FILE_NAMES = new Set(["build.gradle.kts", "build.gradle", "gradle.lockfile", "libs.versions.toml"]);

// The proof's task: every runtime artifact of each JVM project, with the build it comes from.
const PROOF_SCRIPT = [
  "// Generated by Vibe64: lists where each runtime artifact comes from, for the connected proof. Do not commit.",
  "allprojects {",
  "  val projectPath = path",
  "  plugins.withId(\"java\") {",
  "    val runtime = configurations.getByName(\"runtimeClasspath\")",
  "    tasks.register(\"connectedProof\") {",
  "      dependsOn(runtime)",
  "      doLast {",
  "        runtime.incoming.artifacts.artifacts.forEach { a ->",
  "          val id = a.id.componentIdentifier",
  "          val build = (id as? org.gradle.api.artifacts.component.ProjectComponentIdentifier)?.build?.buildPath ?: \"-\"",
  "          println(\"CONNECTED-ARTIFACT\\t\" + projectPath + \"\\t\" + build + \"\\t\" + id.displayName + \"\\t\" + a.file.absolutePath)",
  "        }",
  "      }",
  "    }",
  "  }",
  "}",
  ""
].join("\n");

// The published check's task: one module from the build's own repositories, with no composite.
const PUBLISHED_SCRIPT = [
  "// Generated by Vibe64: resolves one module from the build's own repositories, for the published check. Do not commit.",
  "rootProject {",
  "  tasks.register(\"connectedPublished\") {",
  "    val notation = providers.gradleProperty(\"vibe64ConnectedModule\").get()",
  "    val module = configurations.detachedConfiguration(dependencies.create(notation))",
  "    module.isTransitive = false",
  "    doLast {",
  "      module.resolve()",
  "      println(\"CONNECTED-PUBLISHED\\t\" + notation)",
  "    }",
  "  }",
  "}",
  ""
].join("\n");

function kotlinString(text) {
  return text.replaceAll("\\", "\\\\").replaceAll("\"", "\\\"").replaceAll("$", "\\$");
}

/** The init script for every connected checkout of the type, in the Sources file's order. */
function initScript(connections) {
  return [
    MARKER,
    "// Gradle reads it from the session's own Gradle user home, which Vibe64 gives every command of the session.",
    "settingsEvaluated {",
    ...connections.flatMap(entry => [
      `    // ${entry.name.replace(/[\r\n]+/gu, " ")}`,
      `    includeBuild("${kotlinString(entry.sourceRoot)}")`
    ]),
    "}",
    ""
  ].join("\n");
}

async function isGradleBuild(dir) {
  for (const file of BUILD_FILES) {
    if ((await stat(path.join(dir, file)).catch(() => null))?.isFile()) return true;
  }
  return false;
}

async function requireBuilds({ connection, connections, sessionSourceRoot }) {
  if (!(await isGradleBuild(sessionSourceRoot))) {
    throw vibe64Error(
      `Connected ${connection.name}: the session source is not a Gradle build, so Gradle cannot include a connected checkout.`,
      "vibe64_connected_gradle_consumer"
    );
  }
  const consumer = await realpath(sessionSourceRoot);
  for (const entry of connections) {
    if (!(await isGradleBuild(entry.sourceRoot))) {
      throw vibe64Error(
        `Connected ${entry.name}: ${entry.sourceRoot} is not a Gradle build, so Gradle cannot include it.`,
        "vibe64_connected_gradle_not_gradle"
      );
    }
    const source = await realpath(entry.sourceRoot);
    if (source === consumer || source.startsWith(`${consumer}${path.sep}`) || consumer.startsWith(`${source}${path.sep}`)) {
      throw vibe64Error(
        `Connected ${entry.name}: ${entry.sourceRoot} overlaps the session source, so Gradle cannot include it as a separate build.`,
        "vibe64_connected_gradle_overlap"
      );
    }
  }
}

function ours(text) {
  return text !== null && text.startsWith(MARKER);
}

/** The Gradle user home the session's commands would have without a connection: the login's, as a command sees it. */
async function defaultGradleHome({ sessionSourceRoot, runCommand }) {
  // Run beside the session source, outside its tree, so the session's own home is not what answers.
  const probe = await runCommand({
    command: "sh",
    args: ["-c", "printf '%s' \"${GRADLE_USER_HOME:-$HOME/.gradle}\""],
    cwd: path.dirname(sessionSourceRoot),
    timeout: 60_000
  });
  const home = probe?.ok === true ? String(probe.stdout || "").trim() : "";
  return path.isAbsolute(home) && !home.startsWith(`${path.resolve(sessionSourceRoot)}${path.sep}`) ? home : "";
}

/** The session home links the default home's gradle.properties and init scripts, so the person's own settings still apply. */
async function linkDefaultHome({ sessionSourceRoot, defaultHome }) {
  const home = path.join(sessionSourceRoot, CONNECTED_GRADLE_HOME);
  const linked = [];
  const links = [["gradle.properties", path.join(defaultHome, "gradle.properties")]];
  for (const entry of await readdir(path.join(defaultHome, "init.d"), { withFileTypes: true }).catch(() => [])) {
    if (entry.isFile() && entry.name !== path.basename(CONNECTED_GRADLE_INIT)) {
      links.push([path.posix.join("init.d", entry.name), path.join(defaultHome, "init.d", entry.name)]);
    }
  }
  // Links of an earlier apply go first: one the default home no longer has must not stay.
  for (const name of ["gradle.properties", ...(await readdir(path.join(home, "init.d")).catch(() => [])).map(file => path.posix.join("init.d", file))]) {
    if ((await lstat(path.join(home, name)).catch(() => null))?.isSymbolicLink()) await rm(path.join(home, name));
  }
  for (const [name, target] of links) {
    // A file the session home has of its own stays, in place of the default home's.
    if (!(await stat(target).catch(() => null))?.isFile() || await lstat(path.join(home, name)).catch(() => null)) continue;
    await symlink(target, path.join(home, name));
    linked.push(name);
  }
  return linked;
}

/**
 * Publishes a new generation of the shared read-only cache from the default home's dependency cache
 * when none is published or the published one is a day old. As Gradle requires, a generation is a
 * copy without the cache's locks and cleanup state, complete before `current` names it, and never
 * written again; old ones go after GENERATION_KEPT_MS.
 */
async function refreshReadOnlyCache(defaultHome) {
  const source = path.join(defaultHome, "caches", "modules-2");
  if (!(await stat(source).catch(() => null))?.isDirectory()) return [];
  const root = connectedGradleReadOnlyCacheRoot();
  const current = path.join(root, CONNECTED_GRADLE_RO_CURRENT);
  const published = Number(GENERATION.exec(path.basename(await readlink(current).catch(() => "")))?.[1] || 0);
  const now = Date.now();
  if (now - published < DAY_MS) return [];
  const generation = path.join(root, `generation-${now}`);
  const partial = `${generation}.partial`;
  try {
    await mkdir(partial, { recursive: true });
    await cp(source, path.join(partial, "modules-2"), {
      recursive: true,
      filter: file => !file.endsWith(".lock") && path.basename(file) !== "gc.properties"
    });
    await rename(partial, generation);
    const link = `${current}.${process.pid}.${now}`;
    await symlink(path.basename(generation), link);
    await rename(link, current);
  } catch (error) {
    await rm(partial, { recursive: true, force: true });
    return [`[Connected] Gradle: could not refresh the shared read-only dependency cache (${error.message}); the session downloads what it lacks.`];
  }
  for (const entry of await readdir(root)) {
    const made = Number(GENERATION.exec(entry.replace(/\.partial$/u, ""))?.[1] || 0);
    if (made && entry !== path.basename(generation) && now - made > GENERATION_KEPT_MS) {
      await rm(path.join(root, entry), { recursive: true, force: true });
    }
  }
  return [`[Connected] Gradle: the shared read-only dependency cache now holds what ${defaultHome} had.`];
}

/**
 * Writes the init script that includes every connected checkout into the session's Gradle user
 * home, links the default home's settings there, and the proof's scripts beside it. No Gradle runs.
 */
async function applyGradle({ connection, connections, sessionSourceRoot, runCommand, writeGitExcludes }) {
  await requireBuilds({ connection, connections, sessionSourceRoot });
  const existing = await readDerivedFile(sessionSourceRoot, INIT);
  if (existing !== null && !ours(existing)) {
    throw vibe64Error(
      `Connected ${connection.name}: the session source has its own ${INIT}, so Vibe64 will not replace it.`,
      "vibe64_connected_gradle_init_foreign"
    );
  }
  // Nothing in the session's Gradle home, which its Gradle writes too, may be tracked.
  await refuseTracked({ connection, tree: sessionSourceRoot, paths: [CONNECTED_GRADLE_HOME], runCommand });
  await writeDerivedFiles({
    connection,
    tree: sessionSourceRoot,
    files: {
      [INIT]: initScript(connections),
      [PROOF_INIT]: PROOF_SCRIPT,
      [PUBLISHED_INIT]: PUBLISHED_SCRIPT
    },
    runCommand,
    writeGitExcludes,
    excludes: [CONNECTED_GRADLE_HOME]
  });
  if (ours(await readDerivedFile(sessionSourceRoot, EARLIER_INIT))) await rm(path.join(sessionSourceRoot, EARLIER_INIT));
  const lines = [
    `[Connected] ${connection.name}: Gradle builds it from ${connection.sourceRoot} in place of the published module ` +
      `with its group:name, in every Gradle command of the session (its Gradle user home is ${CONNECTED_GRADLE_HOME}).`
  ];
  const defaultHome = await defaultGradleHome({ sessionSourceRoot, runCommand });
  if (!defaultHome) {
    lines.push("[Connected] Gradle: Vibe64 could not find the default Gradle user home, so the session's has none of its settings.");
    return { lines };
  }
  await linkDefaultHome({ sessionSourceRoot, defaultHome });
  lines.push(...await refreshReadOnlyCache(defaultHome));
  return { lines };
}

async function proveGradle({ connection, connections, sessionSourceRoot, runCommand }) {
  const script = await readDerivedFile(sessionSourceRoot, INIT);
  if (script === null) return notInEffect(`${INIT} is missing; prepare the workspace to include the connected checkout.`);
  if (script !== initScript(connections)) {
    return notInEffect(`${INIT} does not include the session's connected checkouts; prepare the workspace again.`);
  }
  if (!runCommand) {
    return {
      inEffect: true,
      reason: ""
    };
  }
  if (await readDerivedFile(sessionSourceRoot, PROOF_INIT) !== PROOF_SCRIPT) {
    return notInEffect(`${PROOF_INIT} is missing; prepare the workspace again.`);
  }
  const tracked = await runCommand({
    command: "git",
    args: ["ls-files", "-z", "--", ...GENERATED],
    cwd: sessionSourceRoot,
    timeout: 60_000
  });
  const trackedPath = String(tracked?.stdout || "").split("\0").find(Boolean);
  if (tracked?.ok !== true || trackedPath) {
    return notInEffect(trackedPath
      ? `${trackedPath} is tracked in Git, so a Save would commit the connection.`
      : "Git could not say what the session source tracks.");
  }
  // Gradle builds the included checkout, as every command of the session runs it (no flag), and
  // names the build each runtime artifact comes from.
  const result = await runCommand({
    command: "gradle",
    args: [
      "-q",
      "--console=plain",
      "--no-daemon",
      "--no-configuration-cache",
      "-I",
      path.join(sessionSourceRoot, PROOF_INIT),
      "connectedProof"
    ],
    cwd: sessionSourceRoot,
    env: connectedGradleEnv(sessionSourceRoot),
    timeout: GRADLE_TIMEOUT_MS
  });
  if (result?.ok !== true) return notInEffect(`Gradle could not build the composite: ${gradleFailure(result)}.`);
  const artifacts = String(result.stdout || "").split(/\r?\n/u)
    .filter(line => line.startsWith(ARTIFACT_LINE))
    .map(line => line.split("\t"));
  if (!artifacts.length) return notInEffect("Gradle resolved no runtime classpath in the session source; does it apply the java plugin?");
  const source = await realpath(connection.sourceRoot);
  for (const [, , build, , file] of artifacts) {
    // Only an included build (its path is neither ":" nor "-") supplies the connected checkout.
    if (!file || build === "-" || build === ":") continue;
    const real = await realpath(file).catch(() => "");
    if (real.startsWith(`${source}${path.sep}`)) {
      return {
        inEffect: true,
        reason: ""
      };
    }
  }
  return notInEffect(
    `no runtime artifact of the session source comes from the included build at ${connection.sourceRoot}; ` +
      "does the checkout's group:name match the dependency?"
  );
}

/**
 * Once no gradle connection remains, the session's Gradle home goes (and with its init script, the
 * GRADLE_USER_HOME its commands got), with the proof's scripts: Gradle resolves the published modules.
 */
async function restoreGradle({ connections, sessionSourceRoot, writeGitExcludes }) {
  if (connections.length) return [];
  const generated = [
    ...(ours(await readDerivedFile(sessionSourceRoot, INIT)) ? [CONNECTED_GRADLE_HOME] : []),
    ...(ours(await readDerivedFile(sessionSourceRoot, EARLIER_INIT)) ? [EARLIER_INIT] : []),
    ...(await readDerivedFile(sessionSourceRoot, PROOF_INIT) === PROOF_SCRIPT ? [PROOF_INIT] : []),
    ...(await readDerivedFile(sessionSourceRoot, PUBLISHED_INIT) === PUBLISHED_SCRIPT ? [PUBLISHED_INIT] : [])
  ];
  if (!generated.length) return [];
  const removed = await removeDerivedFiles({ tree: sessionSourceRoot, paths: generated, writeGitExcludes });
  return [`[Connected] Gradle: removed ${removed.join(", ")}; Gradle resolves the published modules again.`];
}

async function optionalText(file) {
  return readFile(file, "utf8").catch(() => null);
}

/** The first of these files that exists, as text. */
async function firstText(dir, names) {
  for (const name of names) {
    const text = await optionalText(path.join(dir, name));
    if (text !== null) return text;
  }
  return null;
}

/** `name = "value"` (Kotlin), `name = 'value'` or `name 'value'` (Groovy), then gradle.properties. */
async function buildValue(dir, script, name) {
  const pattern = new RegExp(`^\\s*${name}\\s*(?:=\\s*)?["']([^"'$]+)["']\\s*$`, "mu");
  const properties = await optionalText(path.join(dir, "gradle.properties")) || "";
  return pattern.exec(script)?.[1] || new RegExp(`^\\s*${name}\\s*=\\s*(\\S+)\\s*$`, "mu").exec(properties)?.[1] || null;
}

/** The module a connected checkout's root project publishes: group:name and version, as its build declares them. */
async function connectedModule(root) {
  const settings = await firstText(root, ["settings.gradle.kts", "settings.gradle"]) || "";
  const script = await firstText(root, ["build.gradle.kts", "build.gradle"]) || "";
  const group = await buildValue(root, script, "group");
  if (!group) return null;
  const name = /rootProject\.name\s*=\s*["']([^"']+)["']/u.exec(settings)?.[1] || path.basename(root);
  return {
    package: `${group}:${name}`,
    version: await buildValue(root, script, "version")
  };
}

/** The session build's tracked build scripts and lockfiles, down to a few project levels. */
async function buildFiles(root, relative = "", depth = 0) {
  const files = [];
  for (const entry of await readdir(path.join(root, relative), { withFileTypes: true }).catch(() => [])) {
    const child = path.join(relative, entry.name);
    if (entry.isDirectory() && depth < SCRIPT_DEPTH && !SKIPPED_DIRS.has(entry.name)) {
      files.push(...await buildFiles(root, child, depth + 1));
    } else if (entry.isFile() && BUILD_FILE_NAMES.has(entry.name)) {
      files.push(child);
    }
  }
  return files.sort();
}

/** What Gradle says went wrong, in one line: the deepest cause under "* What went wrong:", else its first `> ` line or last line. */
function gradleFailure(result) {
  const lines = `${result?.stderr || ""}\n${result?.stdout || ""}\n${result?.error || ""}`.split("\n")
    .map(line => line.trim())
    .filter(Boolean);
  const start = lines.indexOf("* What went wrong:");
  const section = [];
  for (const line of start >= 0 ? lines.slice(start + 1) : []) {
    if (line.startsWith("* ")) break;
    section.push(line);
  }
  const cause = section.findLast(line => line.startsWith("> ")) || section[0] || lines.find(line => line.startsWith("> ")) || lines.at(-1);
  return String(cause || "no output").replace(/^> /u, "").replace(/[.\s]+$/u, "");
}

/** Where the session build names a module: its string notations' versions, its lockfiles', and whether a catalog names it. */
async function namedVersions(sessionSourceRoot, packageName) {
  const prefix = `${packageName}:`;
  const named = {
    scripts: {},
    lockfiles: {},
    catalogued: false
  };
  for (const file of await buildFiles(sessionSourceRoot)) {
    const text = await readFile(path.join(sessionSourceRoot, file), "utf8");
    if (file.endsWith("gradle.lockfile")) {
      const versions = text.split(/\r?\n/u)
        .filter(line => line.startsWith(prefix))
        .map(line => /^([^=\s]+)=/u.exec(line.slice(prefix.length))?.[1])
        .filter(Boolean);
      if (versions.length) named.lockfiles[file] = versions;
    } else if (file.endsWith("libs.versions.toml")) {
      named.catalogued ||= text.includes(packageName);
    } else {
      const versions = [...text.matchAll(/(["'])([^"'\n]*)\1/gu)]
        .map(match => match[2])
        .filter(value => value.startsWith(prefix) && /^[^$:]+$/u.test(value.slice(prefix.length)))
        .map(value => value.slice(prefix.length));
      if (versions.length) named.scripts[file] = versions;
    }
  }
  return named;
}

/**
 * The connected module the session build depends on: the version the checkout's build declares,
 * and the one the tracked build scripts (or gradle.lockfile, which wins) name, which Staging and
 * Production resolve. A version catalog or several versions read as null. Reads files.
 */
async function lockedGradle({ connection, sessionSourceRoot }) {
  const module = await connectedModule(connection.sourceRoot);
  if (!module) return [];
  const named = await namedVersions(sessionSourceRoot, module.package);
  const fromLock = [...new Set(Object.values(named.lockfiles).flat())];
  const fromScripts = [...new Set(Object.values(named.scripts).flat())];
  if (!fromLock.length && !fromScripts.length && !named.catalogued) return [];
  const versions = fromLock.length ? fromLock : fromScripts;
  return [{
    package: module.package,
    connected: module.version,
    locked: versions.length === 1 && !(named.catalogued && !fromLock.length) ? versions[0] : null
  }];
}

/**
 * Whether the build's own repositories publish this version: Gradle resolves it with no composite,
 * in the default Gradle user home (whose init.d has no connection). Null when it cannot tell.
 */
async function publishedGradle({ sessionSourceRoot, runCommand, module, defaultHome }) {
  const result = await runCommand({
    command: "gradle",
    args: [
      "-q",
      "--console=plain",
      "--no-daemon",
      "--no-configuration-cache",
      "-I",
      path.join(sessionSourceRoot, PUBLISHED_INIT),
      `-Pvibe64ConnectedModule=${module}`,
      "connectedPublished"
    ],
    cwd: sessionSourceRoot,
    env: { GRADLE_USER_HOME: defaultHome },
    timeout: GRADLE_TIMEOUT_MS
  });
  if (result?.ok === true && String(result.stdout || "").includes(`CONNECTED-PUBLISHED\t${module}`)) return { published: true };
  const output = `${result?.stdout || ""}\n${result?.stderr || ""}`;
  const unreachable = /Could not (?:GET|HEAD)|offline mode|No cached version|Connection refused|Unknown host|timed out/iu.test(output);
  if (!unreachable && /Could not find /u.test(output)) return { published: false };
  return {
    published: null,
    reason: gradleFailure(result)
  };
}

/** Moves every string notation of the module in the tracked build scripts, then rewrites gradle.lockfile without the composite. */
async function moveVersion({ sessionSourceRoot, runCommand, named, entry, defaultHome }) {
  const before = {};
  const from = `${entry.package}:${entry.locked}`;
  const to = `${entry.package}:${entry.connected}`;
  for (const file of Object.keys(named.scripts)) {
    const target = path.join(sessionSourceRoot, file);
    before[target] = await readFile(target, "utf8");
    let moved = before[target];
    for (const quote of ['"', "'"]) moved = moved.replaceAll(`${quote}${from}${quote}`, () => `${quote}${to}${quote}`);
    await writeFile(target, moved);
  }
  if (!Object.keys(named.lockfiles).length) return "";
  const result = await runCommand({
    command: "gradle",
    args: ["-q", "--console=plain", "--no-daemon", "--no-configuration-cache", "dependencies", "--write-locks"],
    cwd: sessionSourceRoot,
    env: { GRADLE_USER_HOME: defaultHome },
    timeout: GRADLE_TIMEOUT_MS
  });
  if (result?.ok === true) return "";
  for (const [target, text] of Object.entries(before)) await writeFile(target, text);
  return gradleFailure(result);
}

/** On Save: moves the tracked build scripts to the version the checkout declares once it is published. */
async function bumpGradle({ connection, connections, sessionSourceRoot, runCommand, writeGitExcludes }) {
  const bumped = [];
  const lines = [];
  const say = text => lines.push(`[Connected] ${connection.name}: ${text}`);
  for (const entry of await lockedGradle({ connection, sessionSourceRoot })) {
    const wanted = `${entry.package} ${entry.connected}`;
    if (!entry.connected || entry.connected === entry.locked) continue;
    if (entry.locked === null) {
      say(`Vibe64 cannot tell which ${entry.package} version the build gives Staging and Production, so it leaves the build as it is.`);
      continue;
    }
    if (entry.connected.endsWith("-SNAPSHOT")) {
      say(`${wanted} is a snapshot, which is never published; Staging and Production keep ${entry.locked}.`);
      continue;
    }
    const named = await namedVersions(sessionSourceRoot, entry.package);
    if (!Object.values(named.scripts).flat().includes(entry.locked)) {
      say(`no build script names ${entry.package}:${entry.locked}, so Vibe64 cannot move it to ${entry.connected}; move it by hand.`);
      continue;
    }
    // The published check's script is the adapter's own; an older preparation may not have written it.
    await applyGradle({ connection, connections, sessionSourceRoot, runCommand, writeGitExcludes });
    const defaultHome = await defaultGradleHome({ sessionSourceRoot, runCommand });
    if (!defaultHome) {
      say(`could not check whether ${wanted} is published: Vibe64 could not find the default Gradle user home.`);
      continue;
    }
    const check = await publishedGradle({ sessionSourceRoot, runCommand, module: `${entry.package}:${entry.connected}`, defaultHome });
    if (check.published === null) {
      say(`could not check whether ${wanted} is published: ${check.reason}.`);
    } else if (!check.published) {
      say(`${wanted} is not published; Staging and Production keep ${entry.locked}.`);
    } else {
      const failed = await moveVersion({ sessionSourceRoot, runCommand, named, entry, defaultHome });
      if (failed) {
        say(`${wanted} is published, but Gradle could not rewrite gradle.lockfile, so the build keeps ${entry.locked}: ${failed}.`);
        continue;
      }
      bumped.push({
        package: entry.package,
        from: entry.locked,
        to: entry.connected
      });
      say(`Staging and Production now use the published ${wanted}.`);
    }
  }
  return {
    bumped,
    lines
  };
}

const gradleAdapter = Object.freeze({
  type: "gradle",
  runtimeRequirements: Object.freeze(["java", "git"]),
  apply: applyGradle,
  proof: proveGradle,
  restore: restoreGradle,
  locked: lockedGradle,
  bump: bumpGradle
  // No watch: an included build is compiled from the checkout itself at each Gradle run.
});

export { gradleAdapter };
