// The maven adapter. Maven installs each connected checkout into a repository inside the session
// source, chained in front of the developer's own (Maven 3.9.3+: maven.repo.local with
// maven.repo.local.tail), and the session's untracked .mvn/maven.config selects that pair, so every
// ordinary `mvn` there resolves the connected build under its unchanged coordinates; pom.xml stays
// as it is and the developer's repository is only read. An install is a snapshot of the checkout:
// once its pom.xml or src/ files change, the proof says the connection is no longer in effect and
// the next preparation installs it again, and while the session runs the shared watcher does that
// after each save. On Save, a version the checkout declares that its remote repositories publish
// moves into the tracked pom.xml, so Staging and Production use it.
import { createHash } from "node:crypto";
import { readdir, readFile, realpath, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { vibe64Error } from "@local/vibe64-core/server/core";
import { notInEffect, notUsed } from "./adapterResults.js";
import { readDerivedFile, refuseTracked, removeDerivedFiles, writeDerivedFiles } from "./derivedFiles.js";
import { connectedArtifacts, dependencyVersion } from "./mavenPom.js";

const CONFIG = ".mvn/maven.config";
const RECORD = ".development/maven-connected.json";
const REPOSITORY = ".development/maven-connected-repository";
const CLASSPATH = ".development/maven-connected-classpath.txt";
// Only ever filled from remote repositories: what the published check finds there is published.
const PUBLISHED = ".development/maven-published-repository";
const GENERATED = Object.freeze([CONFIG, RECORD, REPOSITORY, CLASSPATH, PUBLISHED]);
const MARKER = "# Generated by Vibe64 for connected development. Do not commit.";
const RECORD_SCHEMA = "vibe64.connected-maven.v1";
const DEPENDENCY_PLUGIN = "org.apache.maven.plugins:maven-dependency-plugin:3.11.0:build-classpath";
const DEPENDENCY_GET = "org.apache.maven.plugins:maven-dependency-plugin:3.11.0:get";
const MAVEN_TIMEOUT_MS = 20 * 60_000;
const BUILT_JAR_DEPTH = 6;
const BUILT_JAR = /^(?!.*-(?:sources|javadoc|tests)\.jar$).+\.jar$/u;

/** The line of a failed command that says why, for a one-line message. */
function shortReason(result) {
  const lines = `${result?.stdout || ""}\n${result?.stderr || ""}\n${result?.error || ""}`.split("\n")
    .map(line => line.trim())
    .filter(Boolean);
  const error = lines.find(line => line.startsWith("[ERROR]"));
  return (error || lines.at(-1) || "no output").replace(/^\[ERROR\]\s*/u, "").replace(/[.\s]+$/u, "");
}

function configText(sessionSourceRoot, tail) {
  return `${MARKER}\n-Dmaven.repo.local=${path.join(sessionSourceRoot, REPOSITORY)}\n-Dmaven.repo.local.tail=${tail}\n`;
}

async function fileDigest(file) {
  return createHash("sha256").update(await readFile(file)).digest("hex");
}

async function fileRecord(file) {
  const entry = await stat(file);
  return {
    size: entry.size,
    mtimeMs: entry.mtimeMs,
    sha256: await fileDigest(file)
  };
}

/** Whether a file still holds what was recorded; it is hashed only when its time moved. */
async function unchanged(file, record) {
  const entry = await stat(file).catch(() => null);
  if (!entry?.isFile() || entry.size !== record.size) return false;
  return entry.mtimeMs === record.mtimeMs || await fileDigest(file) === record.sha256;
}

/** The checkout's build inputs, as Maven reads them: every pom.xml and every file under a src/ folder. */
async function buildInputs(root, relative = "", insideSource = false) {
  const files = [];
  for (const entry of await readdir(path.join(root, relative), { withFileTypes: true })) {
    const child = path.join(relative, entry.name);
    if (entry.isDirectory() && ![".git", "node_modules", "target"].includes(entry.name)) {
      files.push(...await buildInputs(root, child, insideSource || entry.name === "src"));
    } else if (entry.isFile() && (insideSource || entry.name === "pom.xml")) {
      files.push(child);
    }
  }
  return files;
}

async function sourceState(root) {
  const state = {};
  for (const file of (await buildInputs(root)).sort()) state[file] = await fileRecord(path.join(root, file));
  return state;
}

/** The first build input added, removed or changed since the install, or "". */
async function sourceChange(root, recorded) {
  const files = await buildInputs(root).catch(() => []);
  const present = new Set(files);
  const changed = files.find(file => !Object.hasOwn(recorded, file)) || Object.keys(recorded).find(file => !present.has(file));
  if (changed) return changed;
  for (const file of files.sort()) {
    if (!(await unchanged(path.join(root, file), recorded[file]))) return file;
  }
  return "";
}

/** The jars the checkout's build made: those in a target/ folder, without sources, javadoc or tests jars. */
async function builtJars(root, relative = "", depth = 0) {
  if (depth > BUILT_JAR_DEPTH) return [];
  const jars = [];
  for (const entry of await readdir(path.join(root, relative), { withFileTypes: true })) {
    const child = path.join(relative, entry.name);
    if (entry.isDirectory() && ![".git", "node_modules"].includes(entry.name)) {
      jars.push(...await builtJars(root, child, depth + 1));
    } else if (entry.isFile() && path.basename(relative) === "target" && BUILT_JAR.test(entry.name)) {
      jars.push(child);
    }
  }
  return jars;
}

async function repositoryJars(dir) {
  const jars = [];
  for (const entry of await readdir(dir, { withFileTypes: true }).catch(() => [])) {
    const child = path.join(dir, entry.name);
    if (entry.isDirectory()) jars.push(...await repositoryJars(child));
    else if (entry.isFile() && entry.name.endsWith(".jar")) jars.push(child);
  }
  return jars;
}

/** What the install put in the connected repository: the files holding a jar the checkout built. */
async function installedJars(connection, repository) {
  const built = new Map();
  for (const jar of await builtJars(connection.sourceRoot)) {
    const record = await fileRecord(path.join(connection.sourceRoot, jar));
    built.set(record.sha256, {
      built: jar,
      size: record.size
    });
  }
  const sizes = new Set([...built.values()].map(entry => entry.size));
  const installed = [];
  for (const file of await repositoryJars(repository)) {
    const entry = await stat(file);
    if (!sizes.has(entry.size)) continue;
    const record = await fileRecord(file);
    if (!built.has(record.sha256)) continue;
    installed.push({
      installed: path.relative(repository, file),
      built: built.get(record.sha256).built,
      ...record
    });
  }
  return installed.sort((a, b) => a.installed.localeCompare(b.installed));
}

async function readRecord(sessionSourceRoot) {
  const text = await readDerivedFile(sessionSourceRoot, RECORD);
  try {
    const record = text === null ? null : JSON.parse(text);
    return record?.schema === RECORD_SCHEMA && Array.isArray(record.connections) ? record : null;
  } catch {
    return null;
  }
}

async function isMavenProject(dir) {
  return (await stat(path.join(dir, "pom.xml")).catch(() => null))?.isFile() === true;
}

/** A session source that is no Maven project uses no connected checkout: the connection is unused. */
const NO_PROJECT = "The session source has no pom.xml, so no Maven build uses it.";

async function requireProjects({ connections, sessionSourceRoot }) {
  const consumer = await realpath(sessionSourceRoot);
  for (const entry of connections) {
    if (!(await isMavenProject(entry.sourceRoot))) {
      throw vibe64Error(
        `Connected ${entry.name}: ${entry.sourceRoot} has no pom.xml, so Maven cannot install it.`,
        "vibe64_connected_maven_not_maven"
      );
    }
    const source = await realpath(entry.sourceRoot);
    if (source === consumer || source.startsWith(`${consumer}${path.sep}`) || consumer.startsWith(`${source}${path.sep}`)) {
      throw vibe64Error(
        `Connected ${entry.name}: ${entry.sourceRoot} overlaps the session source, so Maven would read one project's .mvn for the other.`,
        "vibe64_connected_maven_overlap"
      );
    }
  }
}

/** A chained local repository needs Maven 3.9.0, and comments in maven.config 3.9.3. */
async function requireMaven({ connection, sessionSourceRoot, runCommand }) {
  const result = await runCommand({
    command: "mvn",
    args: ["--version"],
    cwd: sessionSourceRoot,
    timeout: 120_000
  });
  const version = /Apache Maven (\d+)\.(\d+)\.(\d+)/u.exec(`${result?.stdout || ""}\n${result?.stderr || ""}`);
  if (result?.ok !== true || !version) {
    throw vibe64Error(
      `Connected ${connection.name}: Maven is not available. ${shortReason(result)}.`,
      "vibe64_connected_maven_unavailable"
    );
  }
  const [major, minor, patch] = version.slice(1).map(Number);
  if (major < 3 || (major === 3 && (minor < 9 || (minor === 9 && patch < 3)))) {
    throw vibe64Error(
      `Connected ${connection.name}: Maven ${version.slice(1).join(".")} cannot chain a connected repository; it needs 3.9.3 or later.`,
      "vibe64_connected_maven_version"
    );
  }
}

/** The developer's own repository, read-only behind the connected one: Maven's default for their user.home. */
async function userRepository({ connection, sessionSourceRoot, runCommand }) {
  const result = await runCommand({
    command: "java",
    args: ["-XshowSettings:properties", "-version"],
    cwd: sessionSourceRoot,
    timeout: 120_000
  });
  const home = /^\s*user\.home = (.+)$/mu.exec(`${result?.stderr || ""}\n${result?.stdout || ""}`);
  if (result?.ok !== true || !home) {
    throw vibe64Error(
      `Connected ${connection.name}: Java could not say which home Maven uses. ${shortReason(result)}.`,
      "vibe64_connected_maven_home"
    );
  }
  return path.join(home[1].trim(), ".m2", "repository");
}

/** Why the recorded installs no longer match the session's connections and checkouts, or "". */
async function staleness({ record, connections, sessionSourceRoot, tail }) {
  const identity = entries => entries.map(entry => `${entry.repository}\n${entry.sourceRoot}`).join("\n\n");
  if (!record) return "nothing is installed yet";
  if (identity(record.connections) !== identity(connections)) return "the session's connected repositories changed";
  if (record.tail !== tail) return "the developer's repository moved";
  if (await readDerivedFile(sessionSourceRoot, CONFIG) !== configText(sessionSourceRoot, record.tail)) return `${CONFIG} changed`;
  for (const entry of record.connections) {
    const changed = await sourceChange(entry.sourceRoot, entry.sources);
    if (changed) return `${changed} changed in ${entry.name}`;
    for (const jar of entry.jars) {
      if (!(await unchanged(path.join(sessionSourceRoot, REPOSITORY, jar.installed), jar))) return `${jar.installed} changed`;
    }
  }
  return "";
}

/** Installs every connected checkout of the type, in the Sources file's order, then selects them. */
async function applyMaven({ connection, connections, sessionSourceRoot, runCommand, writeGitExcludes }) {
  if (!(await isMavenProject(sessionSourceRoot))) return { lines: [], unused: NO_PROJECT };
  await requireProjects({ connections, sessionSourceRoot });
  await requireMaven({ connection, sessionSourceRoot, runCommand });
  const tail = await userRepository({ connection, sessionSourceRoot, runCommand });
  await refuseTracked({ connection, tree: sessionSourceRoot, paths: [...GENERATED], runCommand });
  const config = await readDerivedFile(sessionSourceRoot, CONFIG);
  if (config !== null && !config.startsWith(MARKER)) {
    throw vibe64Error(
      `Connected ${connection.name}: the session source has its own ${CONFIG}, so Vibe64 will not replace it. Move it to MAVEN_ARGS.`,
      "vibe64_connected_maven_config_foreign"
    );
  }
  const record = await readRecord(sessionSourceRoot);
  if (!(await staleness({ record, connections, sessionSourceRoot, tail }))) {
    await writeGitExcludes(sessionSourceRoot, [...GENERATED]);
    return {
      lines: [`[Connected] ${connection.name}: Maven already resolves it from ${REPOSITORY}; the checkout is unchanged since its install.`]
    };
  }
  const repository = path.join(sessionSourceRoot, REPOSITORY);
  // Take back every earlier install (a version the checkout no longer builds, a connection that went)
  // and keep what Maven downloaded there.
  for (const entry of record?.connections || []) {
    for (const jar of entry.jars) await rm(path.dirname(path.join(repository, jar.installed)), { recursive: true, force: true });
  }
  const installed = [];
  for (const entry of connections) {
    // Read before the install, so an edit made while it runs shows as a change.
    const sources = await sourceState(entry.sourceRoot);
    const args = [
      "-B",
      "-q",
      "-f",
      path.join(entry.sourceRoot, "pom.xml"),
      `-Dmaven.repo.local=${repository}`,
      `-Dmaven.repo.local.tail=${tail}`,
      "-DskipTests",
      "install"
    ];
    const result = await runCommand({
      command: "mvn",
      args,
      cwd: entry.sourceRoot,
      timeout: MAVEN_TIMEOUT_MS
    });
    if (result?.ok !== true) {
      throw vibe64Error(
        `Connected ${entry.name}: mvn install failed in ${entry.sourceRoot}. ${shortReason(result)}.`,
        "vibe64_connected_maven_install_failed"
      );
    }
    const jars = await installedJars(entry, repository);
    if (!jars.length) {
      throw vibe64Error(
        `Connected ${entry.name}: mvn install put no jar built in ${entry.sourceRoot} into ${REPOSITORY}.`,
        "vibe64_connected_maven_nothing_installed"
      );
    }
    installed.push({
      name: entry.name,
      repository: entry.repository,
      sourceRoot: entry.sourceRoot,
      sources,
      jars
    });
  }
  await writeDerivedFiles({
    connection,
    tree: sessionSourceRoot,
    files: {
      [CONFIG]: configText(sessionSourceRoot, tail),
      [RECORD]: `${JSON.stringify({ schema: RECORD_SCHEMA, tail, connections: installed }, null, 2)}\n`
    },
    runCommand,
    writeGitExcludes
  });
  // The derived files, the repository Maven fills and the proof's classpath file.
  await writeGitExcludes(sessionSourceRoot, [...GENERATED]);
  return {
    lines: installed.map(entry => {
      const jars = entry.jars.map(jar => jar.installed).join(", ");
      return `[Connected] ${entry.name}: installed ${jars} from ${entry.sourceRoot}; every mvn in the session source resolves it from ` +
        `${REPOSITORY}. Prepare the workspace again after changing its source.`;
    })
  };
}

async function proveMaven({ connection, sessionSourceRoot, runCommand }) {
  if (!(await isMavenProject(sessionSourceRoot))) return notUsed(NO_PROJECT);
  const config = await readDerivedFile(sessionSourceRoot, CONFIG);
  if (config === null) return notInEffect(`${CONFIG} is missing; prepare the workspace to install the connected checkout.`);
  const record = await readRecord(sessionSourceRoot);
  if (!record) return notInEffect(`${RECORD} is missing; prepare the workspace to install the connected checkout.`);
  if (config !== configText(sessionSourceRoot, record.tail)) {
    return notInEffect(`${CONFIG} does not select the connected repository ${REPOSITORY}; prepare the workspace again.`);
  }
  const entry = record.connections.find(candidate => candidate.repository === connection.repository);
  if (!entry || entry.sourceRoot !== connection.sourceRoot) {
    return notInEffect(`Maven has not installed it from ${connection.sourceRoot}; prepare the workspace to install it.`);
  }
  const changed = await sourceChange(entry.sourceRoot, entry.sources);
  if (changed) {
    return notInEffect(`${changed} changed in the connected copy since Maven installed it; prepare the workspace again to install it.`);
  }
  for (const jar of entry.jars) {
    if (!(await unchanged(path.join(sessionSourceRoot, REPOSITORY, jar.installed), jar))) {
      return notInEffect(`${REPOSITORY}/${jar.installed} no longer holds the jar built from the connected copy; prepare again.`);
    }
  }
  if (!runCommand) {
    return {
      inEffect: true,
      reason: ""
    };
  }
  const tracked = await runCommand({
    command: "git",
    args: ["ls-files", "-z", "--", ...GENERATED],
    cwd: sessionSourceRoot,
    timeout: 60_000
  });
  const trackedPath = String(tracked?.stdout || "").split("\0").find(Boolean);
  if (tracked?.ok !== true || trackedPath) {
    return notInEffect(trackedPath
      ? `${trackedPath} is tracked in Git, so a Save would commit the connection.`
      : "Git could not say what the session source tracks.");
  }
  // Maven itself, through the ordinary command path (.mvn/maven.config applies), names the classpath.
  const output = path.join(sessionSourceRoot, CLASSPATH);
  await rm(output, { force: true });
  const result = await runCommand({
    command: "mvn",
    args: ["-B", "-q", DEPENDENCY_PLUGIN, `-Dmdep.outputFile=${output}`, "-Dmdep.includeScope=runtime"],
    cwd: sessionSourceRoot,
    timeout: MAVEN_TIMEOUT_MS
  });
  const classpath = await readFile(output, "utf8").catch(() => null);
  await rm(output, { force: true });
  if (result?.ok !== true || classpath === null) {
    return notInEffect(`Maven could not resolve the session source's runtime classpath. ${shortReason(result)}.`);
  }
  const repository = await realpath(path.join(sessionSourceRoot, REPOSITORY)).catch(() => "");
  const digests = new Set(entry.jars.map(jar => jar.sha256));
  for (const item of classpath.trim().split(path.delimiter).filter(Boolean)) {
    const file = await realpath(item).catch(() => "");
    if (repository && file.startsWith(`${repository}${path.sep}`) && digests.has(await fileDigest(file))) {
      return {
        inEffect: true,
        reason: ""
      };
    }
  }
  return notInEffect(
    `the session source's runtime classpath has no jar Maven installed from ${connection.sourceRoot}; ` +
      "does pom.xml ask for the version the checkout builds?"
  );
}

/** Once no maven connection remains, the derived files and the connected repository go: Maven resolves the published artifacts. */
async function restoreMaven({ connections, sessionSourceRoot, writeGitExcludes }) {
  if (connections.length) return [];
  const config = await readDerivedFile(sessionSourceRoot, CONFIG);
  const ours = [];
  for (const relative of GENERATED) {
    if (relative === CONFIG && (config === null || !config.startsWith(MARKER))) continue;
    if (await stat(path.join(sessionSourceRoot, relative)).catch(() => null)) ours.push(relative);
  }
  if (!ours.length) return [];
  const removed = await removeDerivedFiles({ tree: sessionSourceRoot, paths: ours, writeGitExcludes });
  return [`[Connected] Maven: removed ${removed.join(", ")}; Maven resolves the published artifacts again.`];
}

/**
 * Each artifact of the checkout the session's pom.xml depends on: the version the checkout's pom
 * declares, and the one the tracked pom.xml names, which Staging and Production resolve. Reads files.
 */
async function lockedMaven({ connection, sessionSourceRoot }) {
  const consumer = await readFile(path.join(sessionSourceRoot, "pom.xml"), "utf8").catch(() => null);
  if (consumer === null) return [];
  const entries = [];
  for (const artifact of await connectedArtifacts(connection.sourceRoot)) {
    const named = dependencyVersion(consumer, artifact.package);
    if (!named.found) continue;
    entries.push({
      package: artifact.package,
      connected: artifact.version,
      locked: named.version
    });
  }
  return entries;
}

/**
 * Whether the project's remote repositories publish this version: Maven resolves its pom into a
 * repository nothing installs into, with neither the connected repository nor the developer's in
 * reach (on the command line these win over .mvn/maven.config). Null when it cannot tell.
 */
async function publishedMaven({ sessionSourceRoot, runCommand, artifact }) {
  const published = path.join(sessionSourceRoot, PUBLISHED);
  const result = await runCommand({
    command: "mvn",
    args: [
      "-B",
      "-q",
      "-U",
      `-Dmaven.repo.local=${published}`,
      `-Dmaven.repo.local.tail=${published}`,
      DEPENDENCY_GET,
      `-Dartifact=${artifact}:pom`,
      "-Dtransitive=false"
    ],
    cwd: sessionSourceRoot,
    timeout: MAVEN_TIMEOUT_MS
  });
  if (result?.ok === true) return { published: true };
  const output = `${result?.stdout || ""}\n${result?.stderr || ""}`;
  const unreachable = /Could not transfer|offline mode|Unknown host|Connection refused|timed out/iu.test(output);
  if (!unreachable && /Could not find artifact|was not found in/u.test(output)) return { published: false };
  return {
    published: null,
    reason: shortReason(result)
  };
}

/** On Save: moves the tracked pom.xml to each version the checkout declares once it is published. */
async function bumpMaven({ connection, sessionSourceRoot, runCommand, writeGitExcludes }) {
  const bumped = [];
  const lines = [];
  const say = text => lines.push(`[Connected] ${connection.name}: ${text}`);
  await writeGitExcludes(sessionSourceRoot, [...GENERATED]);
  for (const entry of await lockedMaven({ connection, sessionSourceRoot })) {
    const wanted = `${entry.package} ${entry.connected}`;
    if (!entry.connected || entry.connected === entry.locked) continue;
    if (entry.locked === null) {
      say(`Vibe64 cannot tell which ${entry.package} version pom.xml gives Staging and Production, so it leaves pom.xml as it is.`);
      continue;
    }
    if (entry.connected.endsWith("-SNAPSHOT")) {
      say(`${wanted} is a snapshot, which is never published; Staging and Production keep ${entry.locked}.`);
      continue;
    }
    const check = await publishedMaven({ sessionSourceRoot, runCommand, artifact: `${entry.package}:${entry.connected}` });
    if (check.published === null) {
      say(`could not check whether ${wanted} is published: ${check.reason}.`);
    } else if (!check.published) {
      say(`${wanted} is not published; Staging and Production keep ${entry.locked}.`);
    } else {
      const pom = path.join(sessionSourceRoot, "pom.xml");
      const moved = dependencyVersion(await readFile(pom, "utf8"), entry.package).edit(entry.connected);
      if (moved === null) {
        say(`${wanted} is published, but pom.xml names ${entry.package} in more than one place; move it to ${entry.connected} by hand.`);
        continue;
      }
      await writeFile(pom, moved);
      bumped.push({
        package: entry.package,
        from: entry.locked,
        to: entry.connected
      });
      say(`Staging and Production now use the published ${wanted}.`);
    }
  }
  return {
    bumped,
    lines
  };
}

const mavenAdapter = Object.freeze({
  type: "maven",
  runtimeRequirements: Object.freeze(["java", "git"]),
  apply: applyMaven,
  proof: proveMaven,
  restore: restoreMaven,
  locked: lockedMaven,
  bump: bumpMaven,
  // An install is a copy: after a save, the shared watcher applies the connection again (a null sync).
  // The install's own target/ writes wake it once more; that apply finds the build inputs unchanged
  // and installs nothing.
  watch: Object.freeze({
    sources: async ({ connections }) => new Map(connections.map(entry => [entry.sourceRoot, entry.repository])),
    sync: async () => null
  })
});

export { mavenAdapter };
