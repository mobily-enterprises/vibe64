// The nuget adapter: MSBuild's own import. Beside each project of the session source that references
// a package a connected checkout builds, an untracked Directory.Build.targets (MSBuild imports it
// during restore as well as build, and it chains to any Directory.Build.targets further up) swaps
// that PackageReference for a ProjectReference to the connected .csproj and moves the restore lock
// under obj/. Project files, nuget.config and packages.lock.json stay unchanged, and no package
// enters a NuGet cache. The proof restores and reads obj/project.assets.json: each package must
// resolve as the connected project. No watcher is needed: a ProjectReference builds the connected
// source in place, so a save takes effect at the next build.
//
// Staging and Production restore from the tracked project files and lock files: `locked` reads the
// version they record, and on Save `bump` moves them to the connected project's declared version
// once the project's own feeds have that version (it is published), never onto unpublished source.
import { readdir, readFile, realpath, rename, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { vibe64Error } from "@local/vibe64-core/server/core";
import { excludedDerivedPatterns, readDerivedFile, removeDerivedFiles, writeDerivedFiles } from "./derivedFiles.js";

const TARGETS_FILE = "Directory.Build.targets";
const GENERATED = "Generated by Vibe64 for this session's connected NuGet packages.";
const LOCK_FILE = "vibe64-connected.packages.lock.json";
const DOTNET_TIMEOUT_MS = 15 * 60_000;
// No build server outlives the command that started it.
const DOTNET_ENV = Object.freeze({
  DOTNET_CLI_TELEMETRY_OPTOUT: "1",
  DOTNET_CLI_USE_MSBUILD_SERVER: "0",
  DOTNET_NOLOGO: "1",
  DOTNET_SKIP_FIRST_TIME_EXPERIENCE: "1",
  MSBUILDDISABLENODEREUSE: "1",
  UseSharedCompilation: "false"
});
const SKIPPED_FOLDERS = new Set(["bin", "obj", "node_modules"]);

/** Every .csproj below root, outside build output, dependencies and dot-folders. */
async function projectFiles(root) {
  const found = [];
  const walk = async (dir) => {
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      if (entry.isDirectory() && !entry.name.startsWith(".") && !SKIPPED_FOLDERS.has(entry.name)) await walk(path.join(dir, entry.name));
      else if (entry.isFile() && entry.name.endsWith(".csproj")) found.push(path.join(dir, entry.name));
    }
  };
  await walk(root);
  return found.sort();
}

function within(file, root) {
  const relative = path.relative(root, file);
  return relative !== "" && !relative.startsWith("..") && !path.isAbsolute(relative);
}

// MSBuild-escape, then XML-escape, a literal value; and back.
function literal(value) {
  return value.replaceAll("%", "%25").replaceAll("$", "%24").replaceAll("@", "%40").replaceAll(";", "%3B").replaceAll("'", "%27")
    .replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll("\"", "&quot;");
}

function unliteral(value) {
  return value.replaceAll("&quot;", "\"").replaceAll("&gt;", ">").replaceAll("&lt;", "<").replaceAll("&amp;", "&")
    .replace(/%(24|25|27|3B|40)/gu, (_match, code) => String.fromCharCode(Number.parseInt(code, 16)));
}

/** The generated import for one consuming project. */
function renderTargets({ project, objDir, references }) {
  return [
    "<Project>",
    `  <!-- ${GENERATED} Untracked and Git-excluded; Vibe64 removes it when the connection goes. -->`,
    "  <PropertyGroup>",
    "    <Vibe64ParentBuildTargets>$([MSBuild]::GetPathOfFileAbove('Directory.Build.targets', '$(MSBuildThisFileDirectory)../'))"
      + "</Vibe64ParentBuildTargets>",
    "  </PropertyGroup>",
    "  <Import Project=\"$(Vibe64ParentBuildTargets)\" Condition=\"'$(Vibe64ParentBuildTargets)' != ''\" />",
    `  <PropertyGroup Condition="'$(MSBuildProjectFullPath)' == '${literal(project)}' And '$(Vibe64ConnectedDisabled)' != 'true'">`,
    "    <Vibe64ConnectedActive>true</Vibe64ConnectedActive>",
    "    <!-- The graph differs from the tracked lock file; keep connected locks out of source. -->",
    `    <NuGetLockFilePath>${literal(path.join(objDir, LOCK_FILE))}</NuGetLockFilePath>`,
    "    <RestoreLockedMode>false</RestoreLockedMode>",
    "  </PropertyGroup>",
    "  <ItemGroup Condition=\"'$(Vibe64ConnectedActive)' == 'true'\">",
    ...references.flatMap(({ id, csproj }) => [
      `    <PackageReference Remove="${literal(id)}" />`,
      `    <ProjectReference Include="${literal(csproj)}" />`
    ]),
    "  </ItemGroup>",
    "</Project>",
    ""
  ].join("\n");
}

/** What a generated import says, or null when it is not one Vibe64 would write. */
function parseTargets(text) {
  const project = /'\$\(MSBuildProjectFullPath\)' == '([^']*)'/u.exec(text);
  const lock = /<NuGetLockFilePath>([^<]*)<\/NuGetLockFilePath>/u.exec(text);
  if (!project || !lock) return null;
  const references = [...text.matchAll(/<PackageReference Remove="([^"]*)" \/>\n {4}<ProjectReference Include="([^"]*)" \/>/gu)]
    .map(([, id, csproj]) => ({ id: unliteral(id), csproj: unliteral(csproj) }));
  const parsed = { project: unliteral(project[1]), objDir: path.dirname(unliteral(lock[1])), references };
  return renderTargets(parsed) === text ? parsed : null;
}

function ours(text) {
  return text !== null && text.includes(GENERATED);
}

async function dotnet(runCommand, cwd, args, failure) {
  const result = await runCommand({ command: "dotnet", args, cwd, timeout: DOTNET_TIMEOUT_MS, env: DOTNET_ENV });
  if (result?.ok === true) return String(result.stdout || "");
  const detail = String(result?.stderr || result?.stdout || result?.error || "").trim().split("\n").slice(-4).join(" ");
  throw vibe64Error(`${failure}${detail ? ` ${detail}` : ""}`, "vibe64_connected_nuget_dotnet_failed");
}

async function evaluate(runCommand, cwd, project, query) {
  const output = await dotnet(runCommand, cwd, ["msbuild", project, "-nologo", ...query], `MSBuild could not evaluate ${project}.`);
  try {
    return JSON.parse(output);
  } catch {
    throw vibe64Error(
      `MSBuild's evaluation of ${project} was not JSON: ${output.trim().slice(0, 300)}`,
      "vibe64_connected_nuget_dotnet_failed"
    );
  }
}

/**
 * Every consuming project's import, from MSBuild's evaluation of the connected checkouts (the
 * package ids they build) and of the session source's projects (the packages they reference,
 * evaluated without the import so a second apply sees the originals).
 */
async function nugetPlan({ connections, sessionSourceRoot, runCommand }) {
  const root = await realpath(sessionSourceRoot);
  const connected = [];
  for (const connection of connections) connected.push({ ...connection, sourceRoot: await realpath(connection.sourceRoot) });
  const packages = new Map();
  for (const connection of connected) {
    let builds = 0;
    for (const csproj of await projectFiles(connection.sourceRoot)) {
      const { Properties: properties = {} } = await evaluate(runCommand, connection.sourceRoot, csproj, [
        "-getProperty:PackageId",
        "-getProperty:IsPackable"
      ]);
      if (properties.IsPackable === "false" || !properties.PackageId) continue;
      const other = packages.get(properties.PackageId.toLowerCase());
      if (other) {
        throw vibe64Error(
          `Connected ${connection.name}: the package ${properties.PackageId} is built by both ${other.csproj} and ${csproj}.`,
          "vibe64_connected_nuget_duplicate"
        );
      }
      packages.set(properties.PackageId.toLowerCase(), { csproj, connection });
      builds += 1;
    }
    if (!builds) {
      throw vibe64Error(
        `Connected ${connection.name}: ${connection.sourceRoot} has no packable .csproj, so it builds no NuGet package.`,
        "vibe64_connected_nuget_no_package"
      );
    }
  }
  const affected = [];
  const stale = [];
  const consumers = (await projectFiles(root)).filter(csproj => !connected.some(connection => within(csproj, connection.sourceRoot)));
  for (const project of consumers) {
    const evaluation = await evaluate(runCommand, root, project, [
      "-getItem:PackageReference",
      "-getProperty:MSBuildProjectExtensionsPath",
      "-p:Vibe64ConnectedDisabled=true"
    ]);
    const ids = [...new Set((evaluation.Items?.PackageReference || []).map(item => item.Identity))]
      .filter(id => packages.has(String(id).toLowerCase()));
    const targets = path.relative(root, path.join(path.dirname(project), TARGETS_FILE));
    const existing = await readDerivedFile(root, targets);
    if (!ids.length) {
      if (ours(existing)) stale.push(targets);
      continue;
    }
    if (existing !== null && !ours(existing)) {
      throw vibe64Error(
        `${targets} in ${root} was not written by Vibe64, so it cannot swap ${ids.join(", ")}. `
          + "Move it to a parent folder: Vibe64's import chains to it.",
        "vibe64_connected_nuget_targets_foreign"
      );
    }
    if (affected.some(entry => entry.targets === targets)) {
      throw vibe64Error(
        `${path.dirname(targets)} in ${root} holds more than one project that uses a connected package; give each its own folder.`,
        "vibe64_connected_nuget_shared_folder"
      );
    }
    affected.push({
      project,
      targets,
      objDir: path.resolve(path.dirname(project), String(evaluation.Properties?.MSBuildProjectExtensionsPath || "obj/")),
      references: ids.map(id => ({ id, csproj: packages.get(id.toLowerCase()).csproj }))
    });
  }
  for (const connection of connected) {
    if (!affected.some(entry => entry.references.some(reference => within(reference.csproj, connection.sourceRoot)))) {
      throw vibe64Error(
        `Connected ${connection.name}: no project in ${root} references a package ${connection.sourceRoot} builds.`,
        "vibe64_connected_nuget_unused"
      );
    }
  }
  return { root, affected, stale };
}

async function restoreProject(runCommand, root, project) {
  await dotnet(runCommand, root, ["restore", project, "-nologo", "-v:q"], `dotnet restore ${path.relative(root, project)} failed.`);
}

/** A connected checkout that does not ignore its build output would commit what the session's restores build there. */
async function keepBuildOutputOutOfGit({ connection, affected, runCommand, writeGitExcludes }) {
  const sourceRoot = await realpath(connection.sourceRoot);
  const folders = [...new Set(affected.flatMap(entry => entry.references.map(reference => reference.csproj))
    .filter(csproj => within(csproj, sourceRoot))
    .flatMap(csproj => ["bin", "obj"].map(folder => path.relative(sourceRoot, path.join(path.dirname(csproj), folder)))))].sort();
  // A path inside the folder: Git matches a folder pattern (bin/) only against a folder.
  const probes = folders.map(folder => path.join(folder, "vibe64-build-output"));
  // (check-ignore takes -z only with --stdin.)
  const ignored = await runCommand({ command: "git", args: ["check-ignore", "--", ...probes], cwd: sourceRoot, timeout: 60_000 });
  if (ignored?.ok !== true && ignored?.exitCode !== 1) {
    // A checkout that is not a Git repository has nothing to commit the output into.
    if (/not a git repository/iu.test(String(ignored?.stderr || ""))) return;
    throw vibe64Error(
      `Connected ${connection.name}: Git could not say whether ${sourceRoot} ignores its build output. `
        + String(ignored?.stderr || "").trim(),
      "vibe64_connected_git_unavailable"
    );
  }
  const ignoredPaths = new Set(String(ignored.stdout || "").split("\n").filter(Boolean));
  if (probes.some(probe => !ignoredPaths.has(probe))) await writeGitExcludes(sourceRoot, folders);
}

async function applyNuget({ connection, connections, sessionSourceRoot, runCommand, writeGitExcludes }) {
  const { root, affected, stale } = await nugetPlan({ connections, sessionSourceRoot, runCommand });
  if (stale.length) await removeDerivedFiles({ tree: root, paths: stale, writeGitExcludes });
  const files = Object.fromEntries(affected.map(entry => [entry.targets, renderTargets(entry)]));
  await writeDerivedFiles({ connection, tree: root, files, runCommand, writeGitExcludes });
  await keepBuildOutputOutOfGit({ connection, affected, runCommand, writeGitExcludes });
  const lines = [];
  const sourceRoot = await realpath(connection.sourceRoot);
  for (const entry of affected) {
    await restoreProject(runCommand, root, entry.project);
    for (const reference of entry.references.filter(candidate => within(candidate.csproj, sourceRoot))) {
      lines.push(`[Connected] ${connection.name}: ${path.relative(root, entry.project)} uses ${reference.id} from ${reference.csproj}.`);
    }
  }
  return { lines };
}

/** Whether restore resolved each of the connection's packages as its connected project, from the files alone. */
async function proveFromFiles({ connection, root }) {
  const sourceRoot = await realpath(connection.sourceRoot).catch(() => connection.sourceRoot);
  const uses = [];
  for (const targets of [...new Set((await projectFiles(root)).map(project => path.join(path.dirname(project), TARGETS_FILE)))]) {
    const relative = path.relative(root, targets);
    const text = await readDerivedFile(root, relative);
    if (!ours(text)) continue;
    const parsed = parseTargets(text);
    if (!parsed) return { reason: `${relative} was changed since Vibe64 wrote it; prepare the workspace again.` };
    for (const reference of parsed.references) {
      if (within(reference.csproj, sourceRoot)) uses.push({ ...parsed, ...reference, relative });
    }
  }
  if (!uses.length) return { reason: `No project in ${root} uses a package built from ${sourceRoot}; prepare the workspace.` };
  for (const { project, objDir, id, csproj } of uses) {
    const name = path.relative(root, project);
    const assetsText = await readFile(path.join(objDir, "project.assets.json"), "utf8").catch(() => null);
    if (assetsText === null) return { reason: `${name} has not been restored since Vibe64 swapped ${id}; prepare the workspace again.` };
    let assets;
    try {
      assets = JSON.parse(assetsText);
    } catch {
      return { reason: `${path.join(objDir, "project.assets.json")} is not readable JSON; restore ${name} again.` };
    }
    const [key, library] = Object.entries(assets.libraries || {})
      .find(([candidate]) => candidate.toLowerCase().startsWith(`${id.toLowerCase()}/`)) || [];
    const resolved = library?.path ? path.resolve(path.dirname(project), library.path) : "";
    if (library?.type !== "project" || resolved !== csproj) {
      const as = library ? `the ${library.type} ${key}` : "nothing";
      return { reason: `${name} restores ${id} as ${as}, not the connected project ${csproj}.` };
    }
  }
  return { reason: "" };
}

async function proveNuget({ connection, connections, sessionSourceRoot, runCommand }) {
  try {
    const root = await realpath(sessionSourceRoot);
    if (runCommand) {
      const { affected } = await nugetPlan({ connections, sessionSourceRoot, runCommand });
      for (const entry of affected) {
        if (await readDerivedFile(root, entry.targets) !== renderTargets(entry)) {
          return {
            inEffect: false,
            reason: `${entry.targets} no longer swaps this session's connected packages; prepare the workspace again.`
          };
        }
      }
      // What a build resolves now, with the imports as they are.
      for (const entry of affected) await restoreProject(runCommand, root, entry.project);
    }
    const { reason } = await proveFromFiles({ connection, root });
    return { inEffect: !reason, reason };
  } catch (error) {
    return { inEffect: false, reason: String(error?.message || error) };
  }
}

function element(text, name) {
  return new RegExp(`<${name}>\\s*([^<]*?)\\s*</${name}>`, "iu").exec(text)?.[1] || "";
}

function attribute(text, name) {
  return new RegExp(`\\b${name}="([^"]*)"`, "iu").exec(text)?.[1] || "";
}

/** The packages a connected checkout builds and the version each declares, from its project files alone. */
async function declaredPackages(sourceRoot) {
  const declared = [];
  for (const csproj of await projectFiles(sourceRoot)) {
    // Properties only: a PackageReference may hold a <Version> of its own.
    const text = [...(await readFile(csproj, "utf8")).matchAll(/<PropertyGroup\b[^>]*>([\s\S]*?)<\/PropertyGroup>/gu)]
      .map(([, body]) => body).join("\n");
    if (element(text, "IsPackable").toLowerCase() === "false") continue;
    const id = element(text, "PackageId") || element(text, "AssemblyName") || path.basename(csproj, ".csproj");
    const prefix = element(text, "VersionPrefix");
    const version = element(text, "PackageVersion") || element(text, "Version")
      || (prefix && [prefix, element(text, "VersionSuffix")].filter(Boolean).join("-"));
    // A version MSBuild computes ($(...)) is not one the files can tell.
    declared.push({ id, csproj, version: version && !version.includes("$") ? version : null });
  }
  return declared;
}

/** A project's PackageReference to id: its version from the project, or from the nearest Directory.Packages.props. */
async function referenceOf(project, id, root) {
  const text = await readFile(project, "utf8");
  for (const [, attributes, body = ""] of text.matchAll(/<PackageReference\b([^>]*?)(?:\/>|>([\s\S]*?)<\/PackageReference>)/gu)) {
    if (attribute(attributes, "Include").toLowerCase() !== id.toLowerCase()) continue;
    const version = attribute(attributes, "Version") || element(body, "Version");
    if (version) return { version, versionFile: project };
    for (let dir = path.dirname(project); within(dir, root) || dir === root; dir = path.dirname(dir)) {
      const props = await readFile(path.join(dir, "Directory.Packages.props"), "utf8").catch(() => null);
      const entry = props && [...props.matchAll(/<PackageVersion\b([^>]*?)\/?>/gu)]
        .find(([, candidate]) => attribute(candidate, "Include").toLowerCase() === id.toLowerCase());
      if (entry) return { version: attribute(entry[1], "Version"), versionFile: path.join(dir, "Directory.Packages.props") };
      if (dir === root) break;
    }
    return { version: "", versionFile: "" };
  }
  return null;
}

/** What a restore of the tracked files installs: the lock file's resolved version, else the exact version referenced. */
async function lockedVersionOf(project, id, reference) {
  const lock = await readFile(path.join(path.dirname(project), "packages.lock.json"), "utf8").catch(() => null);
  if (lock !== null) {
    try {
      for (const dependencies of Object.values(JSON.parse(lock).dependencies || {})) {
        const [, entry] = Object.entries(dependencies).find(([name]) => name.toLowerCase() === id.toLowerCase()) || [];
        if (entry?.resolved) return entry.resolved;
      }
    } catch {
      return null;
    }
  }
  return /^\d+(?:\.\d+)*(?:-[0-9A-Za-z.-]+)?$/u.test(reference.version) ? reference.version : null;
}

/** Each package of the connection that a project of the session source references, with the version its tracked files install. */
async function nugetUses({ connection, sessionSourceRoot }) {
  const root = await realpath(sessionSourceRoot);
  const sourceRoot = await realpath(connection.sourceRoot);
  const consumers = (await projectFiles(root)).filter(project => !within(project, sourceRoot));
  const uses = [];
  for (const declared of await declaredPackages(sourceRoot)) {
    for (const project of consumers) {
      const reference = await referenceOf(project, declared.id, root);
      if (reference) uses.push({ ...declared, project, reference, locked: await lockedVersionOf(project, declared.id, reference) });
    }
  }
  return { root, uses };
}

/** What Staging and Production install for this connection's packages, beside the version the connected copy declares. Reads files only. */
async function lockedNuget(context) {
  const { uses } = await nugetUses(context);
  const entries = new Map();
  for (const use of uses) {
    const key = use.id.toLowerCase();
    const entry = entries.get(key) || { package: use.id, connected: use.version, locked: use.locked };
    // Projects that install different versions: no one version Staging and Production use.
    if (entry.locked !== use.locked) entry.locked = null;
    entries.set(key, entry);
  }
  return [...entries.values()];
}

/** Whether NuGet version a is newer than b (numeric parts, then a release above its prereleases). */
function newerVersion(a, b) {
  const [aNumbers, aPre = ""] = a.split(/-(.*)/su);
  const [bNumbers, bPre = ""] = b.split(/-(.*)/su);
  const left = aNumbers.split(".").map(Number);
  const right = bNumbers.split(".").map(Number);
  for (let index = 0; index < Math.max(left.length, right.length); index += 1) {
    if ((left[index] || 0) !== (right[index] || 0)) return (left[index] || 0) > (right[index] || 0);
  }
  if (aPre === bPre) return false;
  return !aPre || (Boolean(bPre) && aPre > bPre);
}

const UNPUBLISHED = /NU1102|NU1101|Unable to find package/iu;

/**
 * On Save: moves each project that installs an older version of the connection's package to the
 * version the connected copy declares, with `dotnet add package` (which restores from the project's
 * feeds and fails when they lack that version), while Vibe64's import is set aside so the restore
 * sees the published package. It updates the project file (or Directory.Packages.props) and the lock
 * file. Anything else changes nothing and says why; the import is back, in effect, afterwards.
 */
async function bumpNuget(context) {
  const { connection, runCommand } = context;
  const { root, uses } = await nugetUses(context);
  const bumped = [];
  const lines = [];
  let restored = false;
  const say = text => lines.push(`[Connected] ${connection.name}: ${text}`);
  for (const use of uses) {
    const name = path.relative(root, use.project);
    if (!use.version) {
      say(`${use.csproj} declares no version of ${use.id}, so ${name} keeps ${use.locked ?? "its version"}.`);
      continue;
    }
    if (use.locked && !newerVersion(use.version, use.locked)) {
      // The same version (1.1 is 1.1.0) needs nothing.
      if (newerVersion(use.locked, use.version)) {
        say(`the connected copy's ${use.id} ${use.version} is older than the ${use.locked} ${name} uses; nothing changed.`);
      }
      continue;
    }
    const tracked = [use.project, path.join(path.dirname(use.project), "packages.lock.json"), use.reference.versionFile]
      .filter(Boolean);
    const saved = await Promise.all([...new Set(tracked)].map(async file => [file, await readFile(file, "utf8").catch(() => null)]));
    const targets = path.join(path.dirname(use.project), TARGETS_FILE);
    // A name the type's exclude block already covers.
    const aside = `${targets}.vibe64-backup-bump`;
    const swapped = ours(await readFile(targets, "utf8").catch(() => null));
    if (swapped) await rename(targets, aside);
    let result;
    restored = true;
    const lockFile = path.join(path.dirname(use.project), "packages.lock.json");
    try {
      result = await runCommand({
        command: "dotnet",
        args: ["add", use.project, "package", use.id, "--version", use.version],
        cwd: root,
        timeout: DOTNET_TIMEOUT_MS,
        env: DOTNET_ENV
      });
      // The tracked lock file follows the new version.
      if (result?.ok === true && await readFile(lockFile, "utf8").then(() => true, () => false)) {
        result = await runCommand({
          command: "dotnet",
          args: ["restore", use.project, "-nologo", "-v:q"],
          cwd: root,
          timeout: DOTNET_TIMEOUT_MS,
          env: DOTNET_ENV
        });
      }
    } finally {
      if (swapped) await rename(aside, targets);
    }
    if (result?.ok !== true) {
      for (const [file, text] of saved) {
        if (text === null) await rm(file, { force: true });
        else if (await readFile(file, "utf8").catch(() => null) !== text) await writeFile(file, text);
      }
      const detail = String(result?.stdout || "").concat("\n", String(result?.stderr || result?.error || ""));
      const errorLine = detail.split("\n").map(line => line.trim()).filter(line => /error/iu.test(line)).at(-1);
      const reason = (errorLine || "dotnet add package failed").replace(/\.$/u, "");
      say(UNPUBLISHED.test(detail)
        ? `${use.id} ${use.version} is not published, so ${name} keeps ${use.locked ?? "its version"}.`
        : `could not check whether ${use.id} ${use.version} is published: ${reason}.`);
      continue;
    }
    bumped.push({ package: use.id, from: use.locked, to: use.version });
    say(`Staging and Production now use the published ${use.id} ${use.version}.`);
  }
  // The restore dotnet add ran (even a failed one) resolved the package itself: restore again with the swap.
  if (restored) {
    await applyNuget(context).catch(error => say(`could not put the connection back in effect: ${String(error?.message || error)}`));
  }
  return { bumped, lines };
}

/** With no NuGet package connected any more, Vibe64's imports go; the next restore uses the published packages. */
async function restoreNuget({ connections, sessionSourceRoot, writeGitExcludes }) {
  if (connections.length) return [];
  const root = await realpath(sessionSourceRoot).catch(() => "");
  // Nothing generated here before: no search of the project's files.
  if (!root || !(await excludedDerivedPatterns(root, "nuget")).length) return [];
  const generated = [];
  for (const project of await projectFiles(root)) {
    const targets = path.relative(root, path.join(path.dirname(project), TARGETS_FILE));
    if (!generated.includes(targets) && ours(await readDerivedFile(root, targets))) generated.push(targets);
  }
  if (!generated.length) return [];
  await removeDerivedFiles({ tree: root, paths: generated, writeGitExcludes });
  return [`[Connected] No NuGet package is connected any more: removed ${generated.join(", ")}.`];
}

const nugetAdapter = Object.freeze({
  type: "nuget",
  runtimeRequirements: Object.freeze(["csharp", "git"]),
  apply: applyNuget,
  proof: proveNuget,
  restore: restoreNuget,
  locked: lockedNuget,
  bump: bumpNuget
});

export { nugetAdapter };
