// Vibe64's Cargo treatment with a stand-in for cargo (real Git): what it writes, what it asks Cargo,
// and why its proof refuses. The real toolchain runs in examples/connected-development/cargo/prove.sh
// (vibe64ConnectedAdapterProofs).
const exec = promisify(execFile);
const repository = "https://github.com/example/library";
const CRATES_IO = "registry+https://github.com/rust-lang/crates.io-index";
const MARKER = "# Generated by Vibe64 for connected development. Untracked; do not commit.";
const TRACKED_LOCK = `# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "connected-app"
version = "0.1.0"
dependencies = [
 "connected-library",
]

[[package]]
name = "connected-library"
version = "1.0.0"
source = "${CRATES_IO}"
checksum = "84bc"
`;

async function git(cwd, ...args) {
  return exec("git", args, { cwd });
}

async function commitAll(cwd, message) {
  await git(cwd, "add", "--all");
  await git(cwd, "-c", "user.name=t", "-c", "user.email=t@e", "commit", "-qm", message);
}

/** A session whose source depends on connected-library 1.0.0 from crates.io, and its connected copy. */
async function fixture(t, { version = "1.0.0" } = {}) {
  const root = await mkdtemp(path.join(tmpdir(), "vibe64-connected-cargo-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const source = path.join(root, "session", "source");
  await mkdir(source, { recursive: true });
  await writeFile(path.join(source, "Cargo.toml"), [
    "[package]",
    "name = \"connected-app\"",
    "version = \"0.1.0\"",
    "",
    "[dependencies]",
    "connected-library = \"1.0.0\"",
    ""
  ].join("\n"));
  await writeFile(path.join(source, "Cargo.lock"), TRACKED_LOCK);
  await writeFile(path.join(source, ".gitignore"), "/target/\n");
  await git(source, "init", "-q", "--initial-branch=main");
  await commitAll(source, "app");
  const copy = path.join(root, "session", "connected", "library");
  await mkdir(copy, { recursive: true });
  await writeFile(path.join(copy, "Cargo.toml"), `[package]\nname = "connected-library" # the crate\nversion = "${version}"\nedition = "2021"\n`);
  return {
    source,
    copy: await realpath(copy),
    repositories: [{ name: "Library", repository, relationship: "dependency", type: "cargo", sourceRoot: copy }]
  };
}

/**
 * cargo as the adapter sees it. `metadata` without --no-deps resolves: it applies the config's
 * patch to the lock at resolver.lockfile-path (the tracked Cargo.lock when the config names none),
 * and with --locked reports where connected-library comes from (`from`: "checkout" or "registry").
 */
function toolchain({ calls = [], version = "1.99.0", from = "checkout", published = ["1.0.0"], reachable = true } = {}) {
  return async ({ command, args, cwd }) => {
    calls.push([command, ...args]);
    if (command === "cargo" && args[0] === "update") return update({ args, cwd, published, reachable });
    if (command === "git") {
      try {
        const { stdout, stderr } = await exec(command, args, { cwd });
        return { ok: true, stdout, stderr };
      } catch (error) {
        return { ok: false, stdout: String(error.stdout || ""), stderr: String(error.stderr || "") };
      }
    }
    if (command !== "cargo") return { ok: false, stdout: "", stderr: `unexpected ${command}` };
    if (args.join(" ") === "--version") return { ok: true, stdout: `cargo ${version} (1a2b3c4d5 2026-10-01)\n`, stderr: "" };
    const app = {
      name: "connected-app",
      version: "0.1.0",
      id: "path+file:///app#connected-app@0.1.0",
      source: null,
      manifest_path: path.join(cwd, "Cargo.toml"),
      dependencies: [{ name: "connected-library", source: CRATES_IO, req: "^1.0.0" }]
    };
    if (args.join(" ") === "metadata --format-version 1 --no-deps") {
      return { ok: true, stdout: JSON.stringify({ packages: [app], workspace_members: [app.id], resolve: null }), stderr: "" };
    }
    const config = await readFile(path.join(cwd, ".cargo", "config.toml"), "utf8").catch(() => "");
    const lockfile = /^lockfile-path = (".*")$/mu.exec(config);
    const lockPath = lockfile ? JSON.parse(lockfile[1]) : path.join(cwd, "Cargo.lock");
    if (args.join(" ") === "metadata --format-version 1") {
      const lock = await readFile(lockPath, "utf8").catch(() => TRACKED_LOCK);
      const patch = /= \{ path = (".*") \}$/mu.exec(config);
      const checkout = patch ? /^version = "([^"]+)"$/mu.exec(await readFile(path.join(JSON.parse(patch[1]), "Cargo.toml"), "utf8"))[1] : "";
      const patched = patch ? patchLock(lock, checkout) : lock;
      await mkdir(path.dirname(lockPath), { recursive: true });
      await writeFile(lockPath, patched);
      return { ok: true, stdout: "{\"packages\":[]}", stderr: "" };
    }
    if (args.join(" ") === "metadata --format-version 1 --locked") {
      const library = from === "checkout"
        ? {
          name: "connected-library",
          version: "1.0.0",
          id: "path+file:///library#connected-library@1.0.0",
          source: null,
          manifest_path: path.join(JSON.parse(/= \{ path = (".*") \}$/mu.exec(config)[1]), "Cargo.toml")
        }
        : {
          name: "connected-library",
          version: "1.0.0",
          id: `${CRATES_IO}#connected-library@1.0.0`,
          source: CRATES_IO,
          manifest_path: "/home/cargo/registry/src/connected-library-1.0.0/Cargo.toml"
        };
      return {
        ok: true,
        stdout: JSON.stringify({
          packages: [app, library],
          workspace_members: [app.id],
          resolve: { root: app.id, nodes: [{ id: app.id, deps: [{ pkg: library.id }] }, { id: library.id, deps: [] }] }
        }),
        stderr: ""
      };
    }
    return { ok: false, stdout: "", stderr: `unexpected cargo ${args.join(" ")}` };
  };
}

/** connected-library's lock entry as Cargo writes it for a path patch: the checkout's version, no source or checksum. */
function patchLock(lock, version) {
  return lock.replace(/(name = "connected-library"\n)version = "[^"]+"\n(?:source = "[^"]+"\n)?(?:checksum = "[^"]+"\n)?/u, `$1version = "${version}"\n`);
}

/**
 * `cargo update [--manifest-path <m>] --package connected-library@<old> --precise <new>`. From a folder
 * under the session source Cargo reads Vibe64's patch: the derived lock takes the checkout's version
 * from the patch. From elsewhere the tracked lock takes a `published` version from the registry.
 */
async function update({ args, cwd, published, reachable }) {
  const manifest = args.includes("--manifest-path") ? args[args.indexOf("--manifest-path") + 1] : path.join(cwd, "Cargo.toml");
  const wanted = args[args.indexOf("--precise") + 1];
  const readsPatch = cwd === path.dirname(manifest) || cwd.startsWith(`${path.dirname(manifest)}${path.sep}`);
  if (readsPatch) {
    const derived = path.join(path.dirname(manifest), ".development", "cargo", "Cargo.lock");
    await writeFile(derived, patchLock(await readFile(derived, "utf8"), wanted));
    return { ok: true, stdout: "", stderr: `    Updating connected-library v1.0.0 -> v${wanted} (patched)\n` };
  }
  if (!reachable) {
    return {
      ok: false,
      stdout: "",
      stderr: "error: failed to query replaced source registry `crates-io`\n\nCaused by:\n  download of config.json failed\n\nCaused by:\n" +
        "  [6] Could not resolve host: index.crates.io\n"
    };
  }
  if (!published.includes(wanted)) {
    return {
      ok: false,
      stdout: "",
      stderr: `error: failed to select a version for the requirement \`connected-library = "=${wanted}"\`\ncandidate versions found which didn't match: ${published.join(", ")}\n`
    };
  }
  const target = path.join(path.dirname(manifest), "Cargo.lock");
  const lock = await readFile(target, "utf8");
  await writeFile(target, lock.replace(
    /(name = "connected-library"\n)version = "[^"]+"\nsource = "([^"]+)"\nchecksum = "[^"]+"\n/u,
    `$1version = "${wanted}"\nsource = "$2"\nchecksum = "c-${wanted}"\n`
  ));
  return { ok: true, stdout: "", stderr: `    Updating connected-library v1.0.0 -> v${wanted}\n` };
}

function step(f, action, runCommand) {
  return runConnectedAdapterStep({ action, repository, repositories: f.repositories, sessionSourceRoot: f.source, runCommand });
}

async function status(f) {
  const [entry] = await inspectConnectedAdapters({ repositories: f.repositories, sessionSourceRoot: f.source });
  return entry;
}

function expectedConfig(f) {
  return [
    MARKER,
    "",
    "[resolver]",
    `lockfile-path = ${JSON.stringify(path.join(f.source, ".development", "cargo", "Cargo.lock"))}`,
    "",
    "[patch.crates-io]",
    `"connected-library" = { path = ${JSON.stringify(f.copy)} }`,
    ""
  ].join("\n");
}

async function tracked(f) {
  return [await readFile(path.join(f.source, "Cargo.toml"), "utf8"), await readFile(path.join(f.source, "Cargo.lock"), "utf8")];
}

test("cargo: apply patches the crate to the checkout through an untracked config and derived lock, leaving Cargo.toml and Cargo.lock", async t => {
  const f = await fixture(t);
  const before = await tracked(f);
  const calls = [];
  const runCommand = toolchain({ calls });
  const applied = await step(f, "apply", runCommand);
  assert.equal(applied.ok, true, applied.error);
  assert.equal(applied.output, `[Connected] Library: crate connected-library 1.0.0 patched to ${f.copy} through .cargo/config.toml.`);
  assert.equal(await readFile(path.join(f.source, ".cargo", "config.toml"), "utf8"), expectedConfig(f));
  assert.equal(
    await readFile(path.join(f.source, ".development", "cargo", "Cargo.lock"), "utf8"),
    TRACKED_LOCK.replace(`source = "${CRATES_IO}"\nchecksum = "84bc"\n`, "")
  );
  assert.deepEqual(await tracked(f), before);
  assert.match(await readFile(path.join(f.source, ".git", "info", "exclude"), "utf8"),
    /# BEGIN Vibe64 managed connected cargo packages files\n(?:.*\n)*\/\.cargo\/config\.toml\n(?:.*\n)*\/\.development\/cargo\/Cargo\.lock\n/u);
  assert.equal((await git(f.source, "status", "--porcelain", "--untracked-files=all")).stdout, "");
  assert.deepEqual(calls.filter(([command]) => command === "cargo"), [
    ["cargo", "--version"],
    ["cargo", "metadata", "--format-version", "1", "--no-deps"],
    ["cargo", "metadata", "--format-version", "1"]
  ]);

  // Idempotent: the same files again.
  assert.equal((await step(f, "apply", runCommand)).ok, true);
  assert.equal(await readFile(path.join(f.source, ".cargo", "config.toml"), "utf8"), expectedConfig(f));
  assert.deepEqual(await tracked(f), before);

  calls.length = 0;
  assert.deepEqual(await step(f, "proof", runCommand), { ok: true, output: "[Connected] Library is in effect." });
  assert.deepEqual(calls.filter(([command]) => command === "cargo"), [["cargo", "metadata", "--format-version", "1", "--locked"]]);
  assert.equal((await status(f)).inEffect, true);
});

test("cargo: a foreign or tracked .cargo/config.toml and a Cargo older than 1.97 are refused, changing nothing", async t => {
  const f = await fixture(t);
  const before = await tracked(f);
  const config = path.join(f.source, ".cargo", "config.toml");

  const old = await step(f, "apply", toolchain({ version: "1.96.2" }));
  assert.equal(old.ok, false);
  assert.equal(old.code, "vibe64_connected_cargo_too_old");
  assert.match(old.error, /needs Cargo 1\.97 or later .*this session has cargo 1\.96\.2\./u);
  assert.equal(await readFile(config, "utf8").catch(() => null), null);
  assert.deepEqual(await tracked(f), before);

  await mkdir(path.dirname(config), { recursive: true });
  await writeFile(config, "[build]\njobs = 2\n");
  const foreign = await step(f, "apply", toolchain());
  assert.equal(foreign.code, "vibe64_connected_cargo_config_foreign");
  assert.equal(await readFile(config, "utf8"), "[build]\njobs = 2\n");

  await writeFile(config, `${MARKER}\n`);
  await commitAll(f.source, "config");
  const trackedConfig = await step(f, "apply", toolchain());
  assert.equal(trackedConfig.code, "vibe64_connected_derived_tracked");
  assert.equal(await readFile(config, "utf8"), `${MARKER}\n`);
  assert.deepEqual(await tracked(f), before);
});

test("cargo: the proof says exactly why the checkout is not in effect", async t => {
  const f = await fixture(t);
  const config = path.join(f.source, ".cargo", "config.toml");
  const lock = path.join(f.source, ".development", "cargo", "Cargo.lock");
  const notInEffect = async (reason, runCommand = toolchain()) => {
    assert.deepEqual(await step(f, "proof", runCommand), { ok: false, error: `Connected Library is not in effect: ${reason}` });
  };
  await notInEffect(".cargo/config.toml is missing in the session source; prepare the workspace to write it.");
  assert.equal((await step(f, "apply", toolchain())).ok, true);

  await writeFile(config, expectedConfig(f).replace(JSON.stringify(f.copy), "\"/elsewhere/library\""));
  await notInEffect(`.cargo/config.toml does not patch connected-library to this session's copy ${f.copy}; prepare the workspace again.`);
  assert.equal((await status(f)).inEffect, false);
  await writeFile(config, expectedConfig(f));

  const derived = await readFile(lock, "utf8");
  await rm(lock);
  await notInEffect("the derived lock .development/cargo/Cargo.lock is missing; prepare the workspace again.");
  await writeFile(lock, TRACKED_LOCK);
  assert.deepEqual(await status(f), {
    name: "Library",
    repository,
    type: "cargo",
    sourceRoot: f.repositories[0].sourceRoot,
    inEffect: false,
    reason: `.development/cargo/Cargo.lock takes connected-library 1.0.0 from ${CRATES_IO}, not the checkout's 1.0.0: ` +
      "prepare the workspace again, or make the checkout's version meet the app's requirement."
  });
  await writeFile(lock, derived);

  // The files say so, but Cargo resolves the published crate.
  assert.equal((await status(f)).inEffect, true);
  await notInEffect(
    `connected-library resolves to 1.0.0 from ${CRATES_IO}, not ${f.copy}: Cargo did not apply the patch in .cargo/config.toml.`,
    toolchain({ from: "registry" })
  );
  // A checkout whose version the app's requirement excludes: Cargo ignores the patch.
  await writeFile(path.join(f.copy, "Cargo.toml"), "[package]\nname = \"connected-library\"\nversion = \"2.0.0\"\n");
  await notInEffect(
    `connected-library resolves to 1.0.0 from ${CRATES_IO}, not ${f.copy}: the checkout's 2.0.0 must meet the requirement ^1.0.0.`,
    toolchain({ from: "registry" })
  );
});

test("cargo: once no Cargo connection remains, preparation removes Vibe64's config and derived lock, and leaves a foreign config", async t => {
  const f = await fixture(t);
  const config = path.join(f.source, ".cargo", "config.toml");
  const lock = path.join(f.source, ".development", "cargo", "Cargo.lock");
  assert.equal((await step(f, "apply", toolchain())).ok, true);
  assert.deepEqual(await restoreDisconnected({ repositories: f.repositories, sessionSourceRoot: f.source }), []);
  assert.equal(await readFile(config, "utf8"), expectedConfig(f));

  assert.deepEqual(await restoreDisconnected({ repositories: [], sessionSourceRoot: f.source }), [
    "[Connected] No Cargo connection remains: removed .cargo/config.toml and .development/cargo/Cargo.lock, so Cargo builds the published crates again."
  ]);
  assert.equal(await readFile(config, "utf8").catch(() => null), null);
  assert.equal(await readFile(lock, "utf8").catch(() => null), null);
  assert.doesNotMatch(await readFile(path.join(f.source, ".git", "info", "exclude"), "utf8"), /config\.toml|Cargo\.lock/u);

  await mkdir(path.dirname(config), { recursive: true });
  await writeFile(config, "[build]\njobs = 2\n");
  assert.deepEqual(await restoreDisconnected({ repositories: [], sessionSourceRoot: f.source }), []);
  assert.equal(await readFile(config, "utf8"), "[build]\njobs = 2\n");
});

/** The adapter's context for Save, as the index gives it. */
function saveContext(f, runCommand) {
  return {
    connection: f.repositories[0],
    connections: f.repositories,
    repositories: f.repositories,
    sessionSourceRoot: f.source,
    trees: sessionTrees(f.source, f.repositories),
    runCommand,
    writeGitExcludes: (tree, paths) => writeManagedGitExcludes(tree, paths, { section: "connected cargo packages" })
  };
}

test("cargo: locked reads the checkout's version beside the tracked Cargo.lock's, which Staging and Production build", async t => {
  const f = await fixture(t, { version: "1.1.0" });
  assert.deepEqual(await cargoAdapter.locked(saveContext(f, null)), [{ package: "connected-library", connected: "1.1.0", locked: "1.0.0" }]);
  await rm(path.join(f.source, "Cargo.lock"));
  assert.deepEqual(await cargoAdapter.locked(saveContext(f, null)), [{ package: "connected-library", connected: "1.1.0", locked: null }]);
  await writeFile(path.join(f.source, "Cargo.toml"), "[package]\nname = \"connected-app\"\nversion = \"0.1.0\"\n");
  assert.deepEqual(await cargoAdapter.locked(saveContext(f, null)), []);
});

test("cargo: Save moves the tracked Cargo.lock to the checkout's version only once Cargo finds it published", async t => {
  const f = await fixture(t, { version: "1.1.0" });
  assert.equal((await step(f, "apply", toolchain())).ok, true);
  const before = await tracked(f);

  assert.deepEqual(await cargoAdapter.bump(saveContext(f, toolchain())), { bumped: [], lines: [] });
  assert.deepEqual(await tracked(f), before);

  const unreachable = await cargoAdapter.bump(saveContext(f, toolchain({ published: ["1.0.0", "1.1.0"], reachable: false })));
  assert.deepEqual(unreachable, {
    bumped: [],
    lines: ["[Connected] Library: could not check whether connected-library 1.1.0 is published: [6] Could not resolve host: index.crates.io."]
  });
  assert.deepEqual(await tracked(f), before);

  const calls = [];
  const runCommand = toolchain({ calls, published: ["1.0.0", "1.1.0"] });
  const moved = await cargoAdapter.bump(saveContext(f, runCommand));
  assert.deepEqual(moved.bumped, [{ package: "connected-library", from: "1.0.0", to: "1.1.0" }]);
  assert.deepEqual(moved.lines, [
    "[Connected] Library: Staging and Production now use the published connected-library 1.1.0.",
    `[Connected] Library: crate connected-library 1.1.0 patched to ${f.copy} through .cargo/config.toml.`
  ]);
  assert.deepEqual(calls.find(([, verb]) => verb === "update"), [
    "cargo", "update", "--manifest-path", path.join(f.source, "Cargo.toml"), "--package", "connected-library@1.0.0", "--precise", "1.1.0"
  ]);
  // The requirement already admits 1.1.0: only the lock entry moves, to the published crate.
  assert.deepEqual(await tracked(f), [
    before[0],
    before[1].replace(`version = "1.0.0"\nsource = "${CRATES_IO}"\nchecksum = "84bc"`, `version = "1.1.0"\nsource = "${CRATES_IO}"\nchecksum = "c-1.1.0"`)
  ]);
  assert.deepEqual(await step(f, "proof", runCommand), { ok: true, output: "[Connected] Library is in effect." });
  assert.equal((await status(f)).inEffect, true);

  calls.length = 0;
  assert.deepEqual(await cargoAdapter.bump(saveContext(f, runCommand)), { bumped: [], lines: [] });
  assert.deepEqual(calls, []);
});

test("cargo: a published version outside Cargo.toml's requirement moves the requirement with the lock", async t => {
  const f = await fixture(t, { version: "2.0.0" });
  const moved = await cargoAdapter.bump(saveContext(f, toolchain({ published: ["1.0.0", "2.0.0"] })));
  assert.deepEqual(moved.bumped, [{ package: "connected-library", from: "1.0.0", to: "2.0.0" }]);
  const [manifest, lock] = await tracked(f);
  assert.equal(manifest, "[package]\nname = \"connected-app\"\nversion = \"0.1.0\"\n\n[dependencies]\nconnected-library = \"2.0.0\"\n");
  assert.match(lock, /name = "connected-library"\nversion = "2\.0\.0"\nsource = "registry\+/u);

  // Unpublished: the requirement goes back as it was.
  const g = await fixture(t, { version: "3.0.0" });
  const before = await tracked(g);
  assert.deepEqual(await cargoAdapter.bump(saveContext(g, toolchain({ published: ["1.0.0"] }))), { bumped: [], lines: [] });
  assert.deepEqual(await tracked(g), before);
});
