const exec = promisify(execFile);
const MARKER = "// Generated by Vibe64 for this session's connected Go modules. Untracked; do not commit.";

async function git(cwd, ...args) {
  return (await exec("git", ["-c", "user.name=t", "-c", "user.email=t@e", ...args], { cwd })).stdout;
}

/**
 * Answers like Git (really) and like Go: `go env GOWORK` names the go.work in the folder (or the
 * test's override), and `go list -deps` reports each module of the build from the folder go.work
 * uses, or from the module cache when go.work does not use it.
 */
function toolchain(state) {
  return async ({ command, args, cwd, env }) => {
    state.calls.push({ command, args, cwd, env });
    if (command === "git") {
      try {
        const { stdout, stderr } = await exec("git", args, { cwd });
        return { ok: true, stdout, stderr, exitCode: 0 };
      } catch (error) {
        return { ok: false, stdout: String(error.stdout || ""), stderr: String(error.stderr || ""), exitCode: error.code };
      }
    }
    assert.equal(command, "go");
    if (args[0] === "get") {
      // Staging's view: never through the workspace.
      assert.equal(env.GOWORK, "off");
      const goMod = path.join(cwd, "go.mod");
      const text = await readFile(goMod, "utf8");
      if (state.goGet !== "published") await writeFile(goMod, "half-written\n");
      if (state.goGet === "unreachable") {
        return {
          ok: false,
          stderr: `go: ${args[1]}: Get "https://proxy.golang.org/example.com/library/@v/v1.1.0.info": dial tcp: lookup proxy.golang.org: no such host\n`,
          exitCode: 1
        };
      }
      if (state.goGet !== "published") return { ok: false, stderr: `go: ${args[1]}: invalid version: unknown revision v1.1.0\n`, exitCode: 1 };
      const [modulePath, version] = args[1].split("@");
      await writeFile(goMod, text.replace(`${modulePath} v1.0.0`, `${modulePath} ${version}`).replace("go 1.22", "go 1.24"));
      const goSum = path.join(cwd, "go.sum");
      await writeFile(goSum, `${await readFile(goSum, "utf8")}${modulePath} ${version} h1:published=\n`);
      return { ok: true, stdout: "", stderr: `go: upgraded ${modulePath} v1.0.0 => ${version}\n`, exitCode: 0 };
    }
    const work = await readFile(path.join(cwd, "go.work"), "utf8").catch(() => "");
    if (args[0] === "env") return { ok: true, stdout: `${state.gowork ?? (work ? path.join(cwd, "go.work") : "")}\n`, exitCode: 0 };
    assert.deepEqual(args.slice(0, 3), ["list", "-deps", "-f"]);
    if (state.list) return { ok: true, stdout: state.list, exitCode: 0 };
    const used = new Map();
    for (const [, dir] of work.matchAll(/^\t"(.*)" \/\/ /gmu)) {
      used.set(/^module (\S+)/u.exec(await readFile(path.join(dir, "go.mod"), "utf8"))[1], dir);
    }
    const lines = [`example.com/app\t${cwd}\texample.com/app\t${cwd}`];
    for (const modulePath of ["example.com/library", "example.com/other"]) {
      const dir = used.get(modulePath) || path.join(state.modcache, `${modulePath}@v1.0.0`);
      lines.push(`${modulePath}\t${dir}\t${modulePath}\t${dir}`);
    }
    return { ok: true, stdout: `${lines.join("\n")}\n`, exitCode: 0 };
  };
}

/** A committed Go app requiring two published modules, and session copies of both repositories. */
async function fixture(t) {
  const root = await realpath(await mkdtemp(path.join(tmpdir(), "vibe64-connected-gomod-")));
  t.after(() => rm(root, { recursive: true, force: true }));
  const app = path.join(root, "session", "source");
  await mkdir(app, { recursive: true });
  await writeFile(path.join(app, "go.mod"), "module example.com/app\n\ngo 1.22\n\nrequire (\n\texample.com/library v1.0.0\n\texample.com/other v1.0.0\n)\n");
  await writeFile(path.join(app, "go.sum"), "example.com/library v1.0.0 h1:published=\nexample.com/other v1.0.0 h1:published=\n");
  await writeFile(path.join(app, "main.go"), "package main\n\nfunc main() {}\n");
  await git(app, "init", "-q", "--initial-branch=main");
  await git(app, "add", "--all");
  await git(app, "commit", "-qm", "app");
  const library = path.join(root, "session", "connected", "library");
  const other = path.join(root, "session", "connected", "other");
  await mkdir(library, { recursive: true });
  await mkdir(other, { recursive: true });
  await writeFile(path.join(library, "go.mod"), "module example.com/library\n\ngo 1.23\n");
  await writeFile(path.join(other, "go.mod"), "module example.com/other // the other one\n\ngo 1.21.4\n");
  const repositories = [
    { name: "Library", repository: "https://github.com/example/library", relationship: "dependency", type: "gomod", sourceRoot: library },
    { name: "Other", repository: "https://github.com/example/other", relationship: "dependency", type: "gomod", sourceRoot: other }
  ];
  const state = { calls: [], modcache: path.join(root, "modcache") };
  const step = (action, repository = repositories[0].repository, runCommand = toolchain(state)) =>
    runConnectedAdapterStep({ action, repository, repositories, sessionSourceRoot: app, runCommand });
  const status = async () => (await inspectConnectedAdapters({ repositories, sessionSourceRoot: app }))[0];
  return { app, library, other, repositories, state, step, status };
}

function expectedWork(library, other) {
  return `${MARKER}\n\ngo 1.23\n\nuse (\n\t.\n\t"${library}" // example.com/library\n\t"${other}" // example.com/other\n)\n`;
}

test("gomod: apply writes one go.work using the app and every connected module, kept out of Git with go.work.sum", async (t) => {
  const { app, library, other, state, step, status, repositories } = await fixture(t);
  const applied = await step("apply");
  assert.equal(applied.ok, true, applied.error);
  assert.equal(applied.output, `[Connected] Library: example.com/library in effect from ${library} through go.work.`);
  assert.equal(await readFile(path.join(app, "go.work"), "utf8"), expectedWork(library, other));
  const exclude = await readFile(path.join(app, ".git", "info", "exclude"), "utf8");
  assert.match(exclude, /# BEGIN Vibe64 managed connected gomod packages files\n(?:.*\n)*\/go\.work\n(?:.*\n)*\/go\.work\.sum\n/u);
  await writeFile(path.join(app, "go.work.sum"), "example.com/x v1.0.0 h1:other=\n");
  assert.equal(await git(app, "status", "--porcelain", "--untracked-files=all"), "");

  // Each connection's apply writes the same file: applying the other one changes nothing.
  assert.equal((await step("apply", repositories[1].repository)).ok, true);
  assert.equal(await readFile(path.join(app, "go.work"), "utf8"), expectedWork(library, other));

  state.calls.length = 0;
  assert.deepEqual(await step("proof"), { ok: true, output: "[Connected] Library is in effect." });
  assert.deepEqual(state.calls.filter(call => call.command === "go").map(call => [call.args[0], call.cwd]), [["env", app], ["list", app]]);
  assert.equal((await status()).inEffect, true);
  assert.equal(await git(app, "diff", "HEAD", "--stat"), "");
});

test("gomod: apply refuses a go.work it did not write, a tracked go.work or go.work.sum, and a checkout that is no Go module", async (t) => {
  const { app, library, step } = await fixture(t);
  await writeFile(path.join(app, "go.work"), "go 1.22\n\nuse .\n");
  const foreign = await step("apply");
  assert.equal(foreign.code, "vibe64_connected_gomod_work_foreign");
  assert.equal(await readFile(path.join(app, "go.work"), "utf8"), "go 1.22\n\nuse .\n");

  await rm(path.join(app, "go.work"));
  await writeFile(path.join(app, "go.work.sum"), "");
  await git(app, "add", "go.work.sum");
  await git(app, "commit", "-qm", "sum");
  assert.equal((await step("apply")).code, "vibe64_connected_derived_tracked");
  assert.equal(await readFile(path.join(app, "go.work"), "utf8").catch(() => null), null);

  await git(app, "rm", "-q", "go.work.sum");
  await writeFile(path.join(app, "go.work"), `${MARKER}\n`);
  await git(app, "add", "go.work");
  await git(app, "commit", "-qm", "work");
  assert.equal((await step("apply")).code, "vibe64_connected_derived_tracked");
  assert.equal(await readFile(path.join(app, "go.work"), "utf8"), `${MARKER}\n`);

  await git(app, "rm", "-q", "go.work");
  await rm(path.join(library, "go.mod"));
  const notModule = await step("apply");
  assert.equal(notModule.code, "vibe64_connected_gomod_not_module");
  assert.equal(notModule.error, `Connected Library: ${library} has no go.mod with a module line, so it is not a Go module.`);
});

test("gomod: the proof says exactly why a connected module is not in effect", async (t) => {
  const { app, library, other, state, step, status } = await fixture(t);
  const workPath = path.join(app, "go.work");
  assert.equal((await step("apply")).ok, true);

  await rm(workPath);
  const missing = `${workPath} is missing; prepare the workspace to write it.`;
  assert.equal((await step("proof")).error, `Connected Library is not in effect: ${missing}`);
  assert.deepEqual([(await status()).inEffect, (await status()).reason], [false, missing]);

  await writeFile(workPath, expectedWork(library, other).replace(`\t"${library}" // example.com/library\n`, ""));
  const stale = `${workPath} no longer uses this session's connected Go modules; prepare the workspace again.`;
  assert.equal((await step("proof")).error, `Connected Library is not in effect: ${stale}`);
  assert.equal((await status()).reason, stale);

  await writeFile(workPath, expectedWork(library, other));
  state.gowork = "off";
  assert.equal((await step("proof")).error, `Connected Library is not in effect: Go uses the workspace "off", not ${workPath}; unset GOWORK.`);
  // The files alone still say it is: only the toolchain knows the environment bypasses it.
  assert.equal((await status()).inEffect, true);

  delete state.gowork;
  const cached = path.join(state.modcache, "example.com/library@v1.0.0");
  state.list = `example.com/library\t${cached}\texample.com/library\t${cached}\n`;
  assert.equal((await step("proof")).error,
    `Connected Library is not in effect: example.com/library package example.com/library is built from ${cached}, not the connected checkout ${library}.`);

  state.list = `example.com/app\t${app}\texample.com/app\t${app}\n`;
  assert.equal((await step("proof")).error,
    "Connected Library is not in effect: No package of example.com/library is in the build of ./..., so the session does not use it.");

  delete state.list;
  assert.equal((await step("proof")).ok, true);
});

test("gomod: restore removes Vibe64's go.work and go.work.sum once no Go module is connected, and keeps a person's own", async (t) => {
  const { app, repositories, step } = await fixture(t);
  assert.equal((await step("apply")).ok, true);
  await writeFile(path.join(app, "go.work.sum"), "");

  assert.deepEqual(await restoreDisconnected({ repositories, sessionSourceRoot: app }), []);
  assert.notEqual(await readFile(path.join(app, "go.work"), "utf8").catch(() => null), null);

  assert.deepEqual(await restoreDisconnected({ repositories: [], sessionSourceRoot: app }), [
    "[Connected] No Go module is connected any more: removed go.work."
  ]);
  for (const file of ["go.work", "go.work.sum"]) assert.equal(await readFile(path.join(app, file), "utf8").catch(() => null), null);
  assert.doesNotMatch(await readFile(path.join(app, ".git", "info", "exclude"), "utf8"), /\/go\.work/u);
  assert.equal(await git(app, "status", "--porcelain", "--untracked-files=all"), "");

  await writeFile(path.join(app, "go.work"), "go 1.22\n\nuse .\n");
  assert.deepEqual(await restoreDisconnected({ repositories: [], sessionSourceRoot: app }), []);
  assert.equal(await readFile(path.join(app, "go.work"), "utf8"), "go 1.22\n\nuse .\n");
});

test("gomod: locked reads what go.mod requires; bump moves go.mod and go.sum only to a newer version tag Go can fetch", async (t) => {
  const { app, library, other, repositories, state, step } = await fixture(t);
  const context = {
    connection: repositories[0],
    connections: repositories,
    sessionSourceRoot: app,
    trees: [app, library, other],
    runCommand: toolchain(state),
    writeGitExcludes: (tree, paths) => writeManagedGitExcludes(tree, paths, { section: "connected gomod packages" })
  };
  assert.deepEqual(await gomodAdapter.locked({ ...context, runCommand: null }), [{ package: "example.com/library", connected: null, locked: "v1.0.0" }]);
  assert.deepEqual(await gomodAdapter.locked({ ...context, connection: repositories[1], runCommand: null }),
    [{ package: "example.com/other", connected: null, locked: "v1.0.0" }]);
  assert.equal((await step("apply")).ok, true);
  const goMod = await readFile(path.join(app, "go.mod"), "utf8");
  const goSum = await readFile(path.join(app, "go.sum"), "utf8");
  const unchanged = async () => {
    assert.equal(await readFile(path.join(app, "go.mod"), "utf8"), goMod);
    assert.equal(await readFile(path.join(app, "go.sum"), "utf8"), goSum);
  };
  await git(library, "init", "-q", "--initial-branch=main");
  await git(library, "add", "--all");
  await git(library, "commit", "-qm", "library");

  assert.deepEqual(await gomodAdapter.bump(context), {
    bumped: [],
    lines: ["[Connected] Library: the connected copy has no version tag of example.com/library, so Staging and Production keep v1.0.0."]
  });
  await git(library, "tag", "v1.0.0");
  assert.deepEqual(await gomodAdapter.bump(context), { bumped: [], lines: [] });
  await git(library, "commit", "--allow-empty", "-qm", "older");
  await git(library, "tag", "v0.9.0");
  assert.deepEqual((await gomodAdapter.bump(context)).lines, [
    "[Connected] Library: the connected copy's example.com/library v0.9.0 is older than the v1.0.0 Staging and Production use; nothing changed."
  ]);
  assert.equal(state.calls.filter(call => call.args[0] === "get").length, 0);
  await unchanged();

  await git(library, "commit", "--allow-empty", "-qm", "newer");
  await git(library, "tag", "v1.1.0");
  state.goGet = "unreachable";
  assert.deepEqual(await gomodAdapter.bump(context), {
    bumped: [],
    lines: ["[Connected] Library: could not check whether example.com/library v1.1.0 is published: go: example.com/library@v1.1.0: "
      + "Get \"https://proxy.golang.org/example.com/library/@v/v1.1.0.info\": dial tcp: lookup proxy.golang.org: no such host."]
  });
  await unchanged();
  state.goGet = "unpublished";
  assert.deepEqual(await gomodAdapter.bump(context), {
    bumped: [],
    lines: ["[Connected] Library: example.com/library v1.1.0 is not published, so Staging and Production keep v1.0.0."]
  });
  await unchanged();

  state.goGet = "published";
  assert.deepEqual(await gomodAdapter.bump(context), {
    bumped: [{ package: "example.com/library", from: "v1.0.0", to: "v1.1.0" }],
    lines: ["[Connected] Library: Staging and Production now use the published example.com/library v1.1.0."]
  });
  assert.equal(await readFile(path.join(app, "go.mod"), "utf8"),
    goMod.replace("example.com/library v1.0.0", "example.com/library v1.1.0").replace("go 1.22", "go 1.24"));
  assert.equal(await readFile(path.join(app, "go.sum"), "utf8"), `${goSum}example.com/library v1.1.0 h1:published=\n`);
  // go.work follows the go line go get raised, and the connection stays in effect.
  assert.equal(await readFile(path.join(app, "go.work"), "utf8"), expectedWork(library, other).replace("go 1.23", "go 1.24"));
  assert.equal((await step("proof")).ok, true);
  assert.deepEqual(state.calls.filter(call => call.args[0] === "get").map(call => [call.args, call.env]),
    Array(3).fill([["get", "example.com/library@v1.1.0"], { GOWORK: "off" }]));
  assert.deepEqual(await gomodAdapter.locked({ ...context, runCommand: null }), [{ package: "example.com/library", connected: null, locked: "v1.1.0" }]);
  assert.deepEqual(await gomodAdapter.bump(context), { bumped: [], lines: [] });
});
