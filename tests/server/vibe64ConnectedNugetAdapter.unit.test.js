const exec = promisify(execFile);
const GENERATED = "Generated by Vibe64 for this session's connected NuGet packages.";

async function git(cwd, ...args) {
  return (await exec("git", ["-c", "user.name=t", "-c", "user.email=t@e", ...args], { cwd })).stdout;
}

/**
 * Answers like Git (really) and like the .NET SDK: `dotnet msbuild` evaluates PackageId,
 * IsPackable and PackageReference from the project file, and `dotnet restore` writes
 * obj/project.assets.json resolving a package as the project its Directory.Build.targets
 * references while that import is active, else as the package.
 */
function toolchain(state) {
  return async ({ command, args, cwd, env }) => {
    state.calls.push({ command, args, cwd, env });
    if (command === "git") {
      try {
        const { stdout, stderr } = await exec("git", args, { cwd });
        return { ok: true, stdout, stderr, exitCode: 0 };
      } catch (error) {
        return { ok: false, stdout: String(error.stdout || ""), stderr: String(error.stderr || ""), exitCode: error.code };
      }
    }
    assert.equal(command, "dotnet");
    const [verb, project] = args;
    const text = await readFile(project, "utf8");
    const dir = path.dirname(project);
    if (verb === "msbuild" && args.includes("-getProperty:PackageId")) {
      const properties = {
        PackageId: /<PackageId>([^<]*)</u.exec(text)?.[1] || "",
        IsPackable: /<IsPackable>([^<]*)</u.exec(text)?.[1] || ""
      };
      return { ok: true, stdout: JSON.stringify({ Properties: properties }), exitCode: 0 };
    }
    if (verb === "msbuild") {
      assert.ok(args.includes("-p:Vibe64ConnectedDisabled=true"));
      const references = [...text.matchAll(/<PackageReference Include="([^"]*)" Version="([^"]*)"/gu)]
        .map(([, Identity, Version]) => ({ Identity, Version }));
      const evaluation = { Items: { PackageReference: references }, Properties: { MSBuildProjectExtensionsPath: `${dir}/obj/` } };
      return { ok: true, stdout: JSON.stringify(evaluation), exitCode: 0 };
    }
    const assets = async (libraries) => {
      await mkdir(path.join(dir, "obj"), { recursive: true });
      await writeFile(path.join(dir, "obj", "project.assets.json"), JSON.stringify({ version: 3, libraries }));
    };
    if (verb === "add") {
      // dotnet add package restores the project as its tracked files say, then records the version.
      const [, , , id, , version] = args;
      state.targetsDuringAdd = await readFile(path.join(dir, "Directory.Build.targets"), "utf8").then(() => true, () => false);
      await assets({ [`${id}/1.0.0`]: { type: "package", path: `${id.toLowerCase()}/1.0.0` } });
      if (state.add !== "published") {
        await writeFile(project, "half-written\n");
        const stdout = state.add === "unreachable"
          ? "error: NU1301: Unable to load the service index for source https://api.nuget.org/v3/index.json.\n"
          : `error: NU1102: Unable to find package ${id} with version (>= ${version})\n`;
        return { ok: false, stdout, stderr: "", exitCode: 1 };
      }
      await writeFile(project, text.replace(`Include="${id}" Version="1.0.0"`, `Include="${id}" Version="${version}"`));
      const lock = path.join(dir, "packages.lock.json");
      await writeFile(lock, (await readFile(lock, "utf8")).replace("\"resolved\": \"1.0.0\"", `"resolved": "${version}"`));
      return { ok: true, stdout: "", exitCode: 0 };
    }
    assert.equal(verb, "restore");
    const targets = await readFile(path.join(dir, "Directory.Build.targets"), "utf8").catch(() => "");
    const active = targets.includes("<Vibe64ConnectedActive>true</Vibe64ConnectedActive>") && targets.includes(`== '${project}'`);
    const swapped = active && !state.resolveAsPackage ? /<ProjectReference Include="([^"]*)"/u.exec(targets)?.[1] : null;
    const libraries = {
      "Example.Library/1.0.0": swapped
        ? { type: "project", path: path.relative(dir, swapped), msbuildProject: path.relative(dir, swapped) }
        : { type: "package", path: "example.library/1.0.0" }
    };
    await mkdir(path.join(dir, "obj"), { recursive: true });
    await writeFile(path.join(dir, "obj", "project.assets.json"), JSON.stringify({ version: 3, libraries }));
    return { ok: true, stdout: "", exitCode: 0 };
  };
}

/** A committed app whose project references Example.Library 1.0.0, and a session copy of the library's repository. */
async function fixture(t, { libraryIgnoresBuildOutput = true } = {}) {
  const root = await realpath(await mkdtemp(path.join(tmpdir(), "vibe64-connected-nuget-")));
  t.after(() => rm(root, { recursive: true, force: true }));
  const app = path.join(root, "session", "source");
  const project = path.join(app, "src", "App", "App.csproj");
  await mkdir(path.dirname(project), { recursive: true });
  await writeFile(project, "<Project Sdk=\"Microsoft.NET.Sdk\">\n  <ItemGroup>\n    <PackageReference Include=\"Example.Library\" Version=\"1.0.0\" />\n"
    + "    <PackageReference Include=\"Other.Package\" Version=\"2.0.0\" />\n  </ItemGroup>\n</Project>\n");
  await writeFile(path.join(app, ".gitignore"), "bin/\nobj/\n");
  await git(app, "init", "-q", "--initial-branch=main");
  await git(app, "add", "--all");
  await git(app, "commit", "-qm", "app");
  const library = path.join(root, "session", "connected", "library");
  const csproj = path.join(library, "Example.Library.csproj");
  await mkdir(path.join(library, "tests"), { recursive: true });
  await writeFile(csproj, "<Project Sdk=\"Microsoft.NET.Sdk\">\n  <PropertyGroup>\n    <PackageId>Example.Library</PackageId>\n  </PropertyGroup>\n</Project>\n");
  await writeFile(path.join(library, "tests", "Tests.csproj"),
    "<Project Sdk=\"Microsoft.NET.Sdk\">\n  <PropertyGroup>\n    <PackageId>Example.Library.Tests</PackageId>\n    <IsPackable>false</IsPackable>\n  </PropertyGroup>\n</Project>\n");
  if (libraryIgnoresBuildOutput) await writeFile(path.join(library, ".gitignore"), "bin/\nobj/\n");
  await git(library, "init", "-q", "--initial-branch=main");
  await git(library, "add", "--all");
  await git(library, "commit", "-qm", "library");
  const repositories = [
    { name: "Library", repository: "https://github.com/example/library", relationship: "dependency", type: "nuget", sourceRoot: library }
  ];
  const state = { calls: [] };
  const step = (action) => runConnectedAdapterStep({
    action,
    repository: repositories[0].repository,
    repositories,
    sessionSourceRoot: app,
    runCommand: toolchain(state)
  });
  const status = async () => (await inspectConnectedAdapters({ repositories, sessionSourceRoot: app }))[0];
  return { app, csproj, library, project, repositories, state, step, status, targets: path.join(app, "src", "App", "Directory.Build.targets") };
}

function expectedTargets(project, csproj) {
  return [
    "<Project>",
    `  <!-- ${GENERATED} Untracked and Git-excluded; Vibe64 removes it when the connection goes. -->`,
    "  <PropertyGroup>",
    "    <Vibe64ParentBuildTargets>$([MSBuild]::GetPathOfFileAbove('Directory.Build.targets', '$(MSBuildThisFileDirectory)../'))</Vibe64ParentBuildTargets>",
    "  </PropertyGroup>",
    "  <Import Project=\"$(Vibe64ParentBuildTargets)\" Condition=\"'$(Vibe64ParentBuildTargets)' != ''\" />",
    `  <PropertyGroup Condition="'$(MSBuildProjectFullPath)' == '${project}' And '$(Vibe64ConnectedDisabled)' != 'true'">`,
    "    <Vibe64ConnectedActive>true</Vibe64ConnectedActive>",
    "    <!-- The graph differs from the tracked lock file; keep connected locks out of source. -->",
    `    <NuGetLockFilePath>${path.join(path.dirname(project), "obj", "vibe64-connected.packages.lock.json")}</NuGetLockFilePath>`,
    "    <RestoreLockedMode>false</RestoreLockedMode>",
    "  </PropertyGroup>",
    "  <ItemGroup Condition=\"'$(Vibe64ConnectedActive)' == 'true'\">",
    "    <PackageReference Remove=\"Example.Library\" />",
    `    <ProjectReference Include="${csproj}" />`,
    "  </ItemGroup>",
    "</Project>",
    ""
  ].join("\n");
}

test("nuget: apply swaps the package for its connected project beside the consuming project, restores, and keeps the import out of Git", async (t) => {
  const { app, csproj, project, state, step, status, targets } = await fixture(t);
  const applied = await step("apply");
  assert.equal(applied.ok, true, applied.error);
  assert.equal(applied.output, `[Connected] Library: src/App/App.csproj uses Example.Library from ${csproj}.`);
  assert.equal(await readFile(targets, "utf8"), expectedTargets(project, csproj));
  assert.match(await readFile(path.join(app, ".git", "info", "exclude"), "utf8"),
    /# BEGIN Vibe64 managed connected nuget packages files\n\/src\/App\/Directory\.Build\.targets\n/u);
  assert.equal(await git(app, "status", "--porcelain", "--untracked-files=all"), "");
  const restores = state.calls.filter(call => call.command === "dotnet" && call.args[0] === "restore");
  assert.deepEqual(restores.map(call => call.args), [["restore", project, "-nologo", "-v:q"]]);
  // No MSBuild or compiler server outlives the step.
  assert.equal(restores[0].env.MSBUILDDISABLENODEREUSE, "1");
  assert.equal(restores[0].env.UseSharedCompilation, "false");

  assert.equal((await step("apply")).ok, true);
  assert.equal(await readFile(targets, "utf8"), expectedTargets(project, csproj));
  assert.deepEqual(await step("proof"), { ok: true, output: "[Connected] Library is in effect." });
  assert.deepEqual([(await status()).inEffect, (await status()).reason], [true, ""]);
  assert.equal(await git(app, "diff", "HEAD", "--stat"), "");
});

test("nuget: apply refuses an import it did not write, a tracked one, an unused connection and a checkout that builds no package", async (t) => {
  const { app, csproj, library, project, step, targets } = await fixture(t);
  await writeFile(targets, "<Project />\n");
  const foreign = await step("apply");
  assert.equal(foreign.code, "vibe64_connected_nuget_targets_foreign");
  assert.equal(await readFile(targets, "utf8"), "<Project />\n");

  await writeFile(targets, expectedTargets(project, csproj));
  await git(app, "add", "--force", "src/App/Directory.Build.targets");
  await git(app, "commit", "-qm", "targets");
  assert.equal((await step("apply")).code, "vibe64_connected_derived_tracked");
  await git(app, "rm", "-q", "src/App/Directory.Build.targets");
  await git(app, "commit", "-qm", "untrack");

  const original = await readFile(project, "utf8");
  await writeFile(project, original.replace("Example.Library", "Unrelated.Package"));
  const unused = await step("apply");
  assert.equal(unused.code, "vibe64_connected_nuget_unused");
  assert.equal(unused.error, `Connected Library: no project in ${app} references a package ${library} builds.`);
  await writeFile(project, original);

  await writeFile(csproj, "<Project Sdk=\"Microsoft.NET.Sdk\">\n  <PropertyGroup>\n    <IsPackable>false</IsPackable>\n  </PropertyGroup>\n</Project>\n");
  assert.equal((await step("apply")).code, "vibe64_connected_nuget_no_package");
});

test("nuget: the proof says exactly why a connected package is not in effect", async (t) => {
  const { app, csproj, project, state, step, status, targets } = await fixture(t);
  assert.equal((await step("apply")).ok, true);
  const swapped = expectedTargets(project, csproj);

  await rm(targets);
  assert.equal((await status()).reason, `No project in ${app} uses a package built from ${path.dirname(csproj)}; prepare the workspace.`);
  assert.equal((await step("proof")).error,
    "Connected Library is not in effect: src/App/Directory.Build.targets no longer swaps this session's connected packages; prepare the workspace again.");

  // The import left in place but switched off: a build resolves the published package.
  await writeFile(targets, swapped.replace("<Vibe64ConnectedActive>true<", "<Vibe64ConnectedActive>false<"));
  assert.equal((await status()).reason, "src/App/Directory.Build.targets was changed since Vibe64 wrote it; prepare the workspace again.");
  assert.match((await step("proof")).error, /src\/App\/Directory\.Build\.targets no longer swaps/u);

  await writeFile(targets, swapped);
  state.resolveAsPackage = true;
  const asPackage = `src/App/App.csproj restores Example.Library as the package Example.Library/1.0.0, not the connected project ${csproj}.`;
  assert.equal((await step("proof")).error, `Connected Library is not in effect: ${asPackage}`);
  assert.equal((await status()).reason, asPackage);

  await rm(path.join(app, "src", "App", "obj", "project.assets.json"));
  assert.equal((await status()).reason, "src/App/App.csproj has not been restored since Vibe64 swapped Example.Library; prepare the workspace again.");

  delete state.resolveAsPackage;
  assert.equal((await step("proof")).ok, true);
  assert.equal((await status()).inEffect, true);
});

test("nuget: a connected checkout that does not ignore its build output gets it excluded from Git", async (t) => {
  const { library, step } = await fixture(t, { libraryIgnoresBuildOutput: false });
  assert.equal((await step("apply")).ok, true);
  assert.match(await readFile(path.join(library, ".git", "info", "exclude"), "utf8"),
    /# BEGIN Vibe64 managed connected nuget packages files\n\/bin\n(?:.*\n)*\/obj\n/u);
  await mkdir(path.join(library, "obj"), { recursive: true });
  await writeFile(path.join(library, "obj", "project.assets.json"), "{}");
  assert.equal(await git(library, "status", "--porcelain", "--untracked-files=all"), "");

  const ignoring = await fixture(t);
  assert.equal((await ignoring.step("apply")).ok, true);
  assert.doesNotMatch(await readFile(path.join(ignoring.library, ".git", "info", "exclude"), "utf8").catch(() => ""), /connected nuget/u);
});

test("nuget: restore removes Vibe64's imports once no NuGet package is connected, and keeps a person's own", async (t) => {
  const { app, repositories, step, targets } = await fixture(t);
  assert.equal((await step("apply")).ok, true);
  assert.deepEqual(await restoreDisconnected({ repositories, sessionSourceRoot: app }), []);
  assert.notEqual(await readFile(targets, "utf8").catch(() => null), null);

  assert.deepEqual(await restoreDisconnected({ repositories: [], sessionSourceRoot: app }), [
    "[Connected] No NuGet package is connected any more: removed src/App/Directory.Build.targets."
  ]);
  assert.equal(await readFile(targets, "utf8").catch(() => null), null);
  assert.doesNotMatch(await readFile(path.join(app, ".git", "info", "exclude"), "utf8"), /Directory\.Build\.targets/u);

  await writeFile(targets, "<Project />\n");
  assert.deepEqual(await restoreDisconnected({ repositories: [], sessionSourceRoot: app }), []);
  assert.equal(await readFile(targets, "utf8"), "<Project />\n");
});

test("nuget: locked reads what the tracked lock installs; bump moves project and lock only to a newer version the feeds publish", async (t) => {
  const { app, csproj, library, project, repositories, state, step, status, targets } = await fixture(t);
  const lockPath = path.join(app, "src", "App", "packages.lock.json");
  const lockEntry = { type: "Direct", requested: "[1.0.0, )", resolved: "1.0.0" };
  await writeFile(lockPath, `${JSON.stringify({ version: 1, dependencies: { "net10.0": { "Example.Library": lockEntry } } }, null, 2)}\n`);
  await git(app, "add", "--all");
  await git(app, "commit", "-qm", "lock");
  const declare = version => writeFile(csproj, "<Project Sdk=\"Microsoft.NET.Sdk\">\n  <PropertyGroup>\n    <PackageId>Example.Library</PackageId>\n"
    + `    <Version>${version}</Version>\n  </PropertyGroup>\n</Project>\n`);
  await declare("1.1.0");
  const context = {
    connection: repositories[0],
    connections: repositories,
    sessionSourceRoot: app,
    trees: [app, library],
    runCommand: toolchain(state),
    writeGitExcludes: (tree, paths) => writeManagedGitExcludes(tree, paths, { section: "connected nuget packages" })
  };
  assert.deepEqual(await nugetAdapter.locked({ ...context, runCommand: null }), [{ package: "Example.Library", connected: "1.1.0", locked: "1.0.0" }]);
  assert.equal((await step("apply")).ok, true);
  const projectText = await readFile(project, "utf8");
  const lockText = await readFile(lockPath, "utf8");
  const targetsText = await readFile(targets, "utf8");
  const unchanged = async () => {
    assert.equal(await readFile(project, "utf8"), projectText);
    assert.equal(await readFile(lockPath, "utf8"), lockText);
    assert.equal(await readFile(targets, "utf8"), targetsText);
    // The failed restore resolved the package; Vibe64 restored with the swap again.
    assert.equal((await status()).inEffect, true);
  };

  state.add = "unreachable";
  assert.deepEqual(await nugetAdapter.bump(context), {
    bumped: [],
    lines: ["[Connected] Library: could not check whether Example.Library 1.1.0 is published: "
      + "error: NU1301: Unable to load the service index for source https://api.nuget.org/v3/index.json."]
  });
  await unchanged();
  state.add = "unpublished";
  assert.deepEqual(await nugetAdapter.bump(context), {
    bumped: [],
    lines: ["[Connected] Library: Example.Library 1.1.0 is not published, so src/App/App.csproj keeps 1.0.0."]
  });
  await unchanged();

  state.add = "published";
  assert.deepEqual(await nugetAdapter.bump(context), {
    bumped: [{ package: "Example.Library", from: "1.0.0", to: "1.1.0" }],
    lines: ["[Connected] Library: Staging and Production now use the published Example.Library 1.1.0."]
  });
  // The restore inside dotnet add saw the published package, not Vibe64's swap.
  assert.equal(state.targetsDuringAdd, false);
  assert.equal(await readFile(project, "utf8"), projectText.replace("Include=\"Example.Library\" Version=\"1.0.0\"", "Include=\"Example.Library\" Version=\"1.1.0\""));
  assert.equal(await readFile(lockPath, "utf8"), lockText.replace("\"resolved\": \"1.0.0\"", "\"resolved\": \"1.1.0\""));
  assert.equal(await readFile(targets, "utf8"), targetsText);
  assert.equal(await readFile(`${targets}.vibe64-backup-bump`, "utf8").catch(() => null), null);
  assert.deepEqual(await step("proof"), { ok: true, output: "[Connected] Library is in effect." });
  assert.deepEqual(state.calls.filter(call => call.args[0] === "add").map(call => call.args),
    Array(3).fill(["add", project, "package", "Example.Library", "--version", "1.1.0"]));
  assert.deepEqual(await nugetAdapter.locked({ ...context, runCommand: null }), [{ package: "Example.Library", connected: "1.1.0", locked: "1.1.0" }]);

  assert.deepEqual(await nugetAdapter.bump(context), { bumped: [], lines: [] });
  await declare("0.9.0");
  assert.deepEqual((await nugetAdapter.bump(context)).lines, [
    "[Connected] Library: the connected copy's Example.Library 0.9.0 is older than the 1.1.0 src/App/App.csproj uses; nothing changed."
  ]);
  assert.equal(state.calls.filter(call => call.args[0] === "add").length, 3);
});
